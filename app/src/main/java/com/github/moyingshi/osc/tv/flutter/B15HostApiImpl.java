package com.github.moyingshi.osc.tv.flutter;

import android.app.Activity;
import android.content.Intent;
import android.net.Uri;
import android.os.Handler;
import android.os.Looper;
import android.text.TextUtils;

import androidx.fragment.app.FragmentActivity;

import com.github.catvod.utils.Path;
import com.github.moyingshi.osc.tv.App;
import com.github.moyingshi.osc.tv.R;
import com.github.moyingshi.osc.tv.setting.AppBranding;
import com.github.moyingshi.osc.tv.setting.Setting;
import com.github.moyingshi.osc.tv.ui.web.WebReaderActivity;
import com.github.moyingshi.osc.tv.utils.PermissionUtil;
import com.github.moyingshi.osc.tv.utils.Task;

import java.io.File;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * B8 B15: native side of the B15 Pigeon contract (mobile local-file
 * browser + app-branding page).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b15_local_messages.dart}. The generated
 * file {@code B15Messages.java} is not committed; see docs/b8-b15-local.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the file system, so Dart never hard-codes locale strings
 * or computes display values.
 *
 * <p>Every @async call completes exactly once on the main thread (B14
 * {@code Completion} precedent): the background work posts its result
 * back, and a watchdog completes with an error snapshot when the work
 * does not answer in time. A late background completion after the
 * watchdog is a no-op.
 *
 * <p>Result contract: this screen is a picker. Picking a file (or the
 * current directory in select-dir mode) sets RESULT_OK with a
 * {@code file://} Uri and finishes the C1 screen, so the caller's
 * ActivityResultLauncher receives the result exactly like the native
 * FileActivity (FileChooser funnel). Backing out of the root finishes
 * with no result (RESULT_CANCELED), like native.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. {@code Path} / {@code PermissionUtil} /
 * {@code AppBranding} / {@code WebReaderActivity} are all main-source-set,
 * so direct references are safe. All B15 strings
 * ({@code file_empty_*}, {@code lut_select_current_dir},
 * {@code setting_app_branding}, {@code app_branding_icon_*},
 * {@code dialog_negative} / {@code dialog_positive},
 * {@code error_play_timeout} / {@code error_retry}) are main-res
 * (verified per directory: mobile/leanback res contain none of them),
 * so direct R references are leanback-safe. The leanback FileActivity
 * is untouched; the host diversions guard on {@code !Util.isLeanback()}.
 */
public class B15HostApiImpl implements B15Messages.B15HostApi {

    /** Snapshot watchdog: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 35_000L;

    private final FragmentActivity activity;
    private final Handler handler = new Handler(Looper.getMainLooper());

    /** Storage permission is requested once per engine lifetime (native checkPermission runs once in initView). */
    private boolean permissionRequested;

    public B15HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public Boolean isB15Enabled() {
        return Setting.isFlutterB15Enabled();
    }

    @Override
    public void setB15Enabled(Boolean enabled) {
        Setting.putFlutterB15Enabled(enabled != null && enabled);
    }

    @Override
    public void getLocalFiles(String dirPath, Boolean selectDir, Boolean readMode,
            B15Messages.Result<B15Messages.B15LocalScreen> result) {
        boolean select = selectDir != null && selectDir;
        boolean read = readMode != null && readMode;
        Completion<B15Messages.B15LocalScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, errorScreen(select, read));
        ensureFilePermission(() -> Task.execute(() -> {
            B15Messages.B15LocalScreen screen = buildScreen(dirPath, select, read);
            App.post(() -> {
                if (completion.isDone()) return;
                completion.complete(screen);
            });
        }));
    }

    /**
     * Native FileActivity.checkPermission parity: request storage access
     * once, then list regardless of the grant (native ignores the
     * allGranted value and always calls update(Path.root())). The
     * watchdog above also bounds a user who never answers the system
     * dialog; a late grant is still honored on the next load because
     * PermissionUtil short-circuits when access already exists.
     */
    private void ensureFilePermission(Runnable after) {
        if (permissionRequested) {
            after.run();
            return;
        }
        permissionRequested = true;
        try {
            PermissionUtil.requestFile(activity, granted -> after.run());
        } catch (Throwable e) {
            e.printStackTrace();
            after.run();
        }
    }

    /** Native FileActivity.update + list, flattened into a snapshot. */
    private B15Messages.B15LocalScreen buildScreen(String dirPath, boolean selectDir, boolean readMode) {
        File dir = TextUtils.isEmpty(dirPath) ? Path.root() : new File(dirPath);
        List<B15Messages.B15LocalItem> items = new ArrayList<>();
        try {
            for (File file : list(dir, selectDir)) {
                items.add(new B15Messages.B15LocalItem.Builder()
                        .setName(file.getName())
                        .setPath(file.getAbsolutePath())
                        .setIsDirectory(file.isDirectory())
                        .build());
            }
        } catch (Throwable e) {
            e.printStackTrace();
        }
        File parent = dir.getParentFile();
        boolean isRoot = Path.root().equals(dir);
        return new B15Messages.B15LocalScreen.Builder()
                .setCurrentPath(dir.getAbsolutePath())
                .setParentPath(isRoot || parent == null ? "" : parent.getAbsolutePath())
                .setIsRoot(isRoot)
                .setSelectDir(selectDir)
                .setReadMode(readMode)
                .setSelectCurrentDirLabel(activity.getString(R.string.lut_select_current_dir))
                .setEmptyTitle(activity.getString(R.string.file_empty_title))
                .setEmptyDescription(activity.getString(R.string.file_empty_description))
                .setEmptyActionLabel(activity.getString(R.string.file_empty_action))
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setErrorText("")
                .setItems(items)
                .build();
    }

    /** Native FileActivity.list, verbatim. */
    private List<File> list(File dir, boolean selectDir) {
        if (!selectDir) return Path.list(dir);
        File[] files = dir.listFiles(File::isDirectory);
        if (files == null) return new ArrayList<>();
        Path.sort(files);
        return Arrays.asList(files);
    }

    private B15Messages.B15LocalScreen errorScreen(boolean selectDir, boolean readMode) {
        return new B15Messages.B15LocalScreen.Builder()
                .setCurrentPath("")
                .setParentPath("")
                .setIsRoot(true)
                .setSelectDir(selectDir)
                .setReadMode(readMode)
                .setSelectCurrentDirLabel(activity.getString(R.string.lut_select_current_dir))
                .setEmptyTitle(activity.getString(R.string.file_empty_title))
                .setEmptyDescription(activity.getString(R.string.file_empty_description))
                .setEmptyActionLabel(activity.getString(R.string.file_empty_action))
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setErrorText(activity.getString(R.string.error_play_timeout))
                .setItems(new ArrayList<>())
                .build();
    }

    @Override
    public void openLocalItem(String path, Boolean readMode) {
        if (TextUtils.isEmpty(path)) return;
        File file = new File(path);
        if (readMode != null && readMode && isReadable(file)) {
            startReader(file);
            return;
        }
        returnFile(file);
    }

    /** Native FileActivity.isReadable, verbatim. */
    private boolean isReadable(File file) {
        String n = file.getName().toLowerCase();
        return n.endsWith(".txt") || n.endsWith(".html") || n.endsWith(".htm")
                || n.endsWith(".epub") || n.endsWith(".zip") || n.endsWith(".pdf")
                || n.endsWith(".jpg") || n.endsWith(".jpeg") || n.endsWith(".png")
                || n.endsWith(".webp") || n.endsWith(".gif") || n.endsWith(".bmp");
    }

    /** Native FileActivity.startReader: the reader opens on top and this page stays (back returns to the list). */
    private void startReader(File file) {
        Intent intent = new Intent(activity, WebReaderActivity.class);
        intent.putExtra(WebReaderActivity.EXTRA_LOCAL_PATH, file.getAbsolutePath());
        activity.startActivity(intent);
    }

    /** Native FileActivity.onItemClick (non-read-mode file): return the file Uri and finish. */
    private void returnFile(File file) {
        activity.setResult(Activity.RESULT_OK, new Intent().setData(Uri.fromFile(file)));
        activity.finish();
    }

    @Override
    public void returnCurrentDir(String path) {
        if (TextUtils.isEmpty(path)) return;
        activity.setResult(Activity.RESULT_OK, new Intent().setData(Uri.fromFile(new File(path))));
        activity.finish();
    }

    @Override
    public void getBranding(B15Messages.Result<B15Messages.B15BrandingScreen> result) {
        Completion<B15Messages.B15BrandingScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, brandingErrorScreen());
        try {
            completion.complete(buildBrandingScreen());
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completion.isDone()) completion.complete(brandingErrorScreen());
        }
    }

    /** Native AppBrandingActivity.initView + updateSelection, flattened into a snapshot. */
    private B15Messages.B15BrandingScreen buildBrandingScreen() {
        int mode = AppBranding.getIconMode(activity);
        return new B15Messages.B15BrandingScreen.Builder()
                .setTitle(activity.getString(R.string.setting_app_branding))
                .setSelectLabel(activity.getString(R.string.app_branding_icon_select))
                .setCurrentLabel(activity.getString(R.string.app_branding_icon_current))
                .setHistoryLabel(activity.getString(R.string.app_branding_icon_history))
                .setSelectedMode((long) mode)
                .setCancelLabel(activity.getString(R.string.dialog_negative))
                .setSaveLabel(activity.getString(R.string.dialog_positive))
                .setErrorText("")
                .setRetryLabel(activity.getString(R.string.error_retry))
                .build();
    }

    private B15Messages.B15BrandingScreen brandingErrorScreen() {
        return new B15Messages.B15BrandingScreen.Builder()
                .setTitle(activity.getString(R.string.setting_app_branding))
                .setSelectLabel(activity.getString(R.string.app_branding_icon_select))
                .setCurrentLabel(activity.getString(R.string.app_branding_icon_current))
                .setHistoryLabel(activity.getString(R.string.app_branding_icon_history))
                .setSelectedMode((long) AppBranding.ICON_CURRENT)
                .setCancelLabel(activity.getString(R.string.dialog_negative))
                .setSaveLabel(activity.getString(R.string.dialog_positive))
                .setErrorText(activity.getString(R.string.error_play_timeout))
                .setRetryLabel(activity.getString(R.string.error_retry))
                .build();
    }

    @Override
    public void saveBrandingIcon(Long mode) {
        // Native AppBrandingActivity.save, verbatim: persist + apply the
        // launcher alias + restart via the launcher intent. The restart
        // tears this screen down with the app, so Dart awaits nothing.
        int selected = mode == null ? AppBranding.ICON_CURRENT : mode.intValue();
        AppBranding.putIconMode(selected);
        AppBranding.applyLauncherIcon(activity);
        activity.setResult(Activity.RESULT_OK);
        Intent intent = AppBranding.launcherIntent(activity)
                .addFlags(Intent.FLAG_ACTIVITY_CLEAR_TASK | Intent.FLAG_ACTIVITY_NEW_TASK);
        activity.startActivity(intent);
        activity.finish();
    }

    /**
     * Main-thread-only one-shot completion for an @async call, with a
     * watchdog. The timeout completes with the given value; a late
     * background completion is a no-op. All callers complete from the
     * main thread (App.post / Handler), so no synchronization is needed.
     * Copied from B14HostApiImpl (same shape, B15 result type).
     */
    private final class Completion<T> {
        private final B15Messages.Result<T> result;
        private boolean done;
        private final Runnable timeout;

        Completion(B15Messages.Result<T> result, long timeoutMs, T timeoutValue) {
            this.result = result;
            this.timeout = () -> complete(timeoutValue);
            handler.postDelayed(this.timeout, timeoutMs);
        }

        void complete(T value) {
            if (done) return;
            done = true;
            handler.removeCallbacks(timeout);
            result.success(value);
        }

        boolean isDone() {
            return done;
        }
    }
}
