/**
 * B8 B2: native side of the B2 Pigeon contract (mobile Keep screen).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b2_keep_messages.dart}. The generated file
 * {@code B2Messages.java} is not committed; see docs/b8-b2-keep.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the Keep bean, so Dart never hard-codes locale strings
 * or composes site names.
 *
 * <p>Complex sub-flows stay native on purpose: opening a card (config
 * load + detail/search), the delete-all confirm dialog and the sync
 * dialog all run here; Dart only renders and re-fetches.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Mobile-only classes are never referenced
 * directly (Product, MobileWindow, SyncDialog) — grid geometry is
 * re-implemented (D4) and the sync dialog is opened reflectively (D5),
 * both copied from C2. Two deliberate exceptions, both verified safe:
 * {@code VideoActivity.start(Activity, String, String, String, String)}
 * and {@code SearchActivity.start(Activity, String)} exist in BOTH the
 * mobile and leanback source sets with identical signatures, so a direct
 * reference compiles for both flavors — the same pattern
 * {@code HomeWebBridge} already uses for {@code KeepActivity.start}.
 * Mobile-only strings ({@code app_keep}, {@code menu_sync},
 * {@code menu_delete}, {@code dialog_delete_keep}) are resolved by name
 * at runtime (see {@link #mobileString}) instead of through R, because a
 * direct R reference would break the leanback build — C2's direct
 * references to {@code app_history}/{@code menu_sync}/{@code menu_delete}
 * carry that latent risk; see docs/b8-b2-keep.md.
 */
public class B2HostApiImpl implements B2Messages.B2HostApi {

    /** Config-load timeout: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 30_000L;

    private final FragmentActivity activity;

    public B2HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public Boolean isB2Enabled() {
        return Setting.isFlutterB2Enabled();
    }

    @Override
    public void setB2Enabled(Boolean enabled) {
        Setting.putFlutterB2Enabled(enabled);
    }

    @Override
    public B2Messages.B2KeepScreen getKeep() {
        List<Keep> keeps = Keep.getVod();
        List<B2Messages.B2KeepItem> items = new ArrayList<>(keeps.size());
        for (Keep keep : keeps) items.add(toItem(keep));
        int column = keepColumn();
        int[] spec = keepSpec(column);
        return new B2Messages.B2KeepScreen.Builder()
                .setTitle(mobileString("app_keep", ""))
                .setEmptyTitle(activity.getString(R.string.keep_empty_title))
                .setEmptyDescription(activity.getString(R.string.keep_empty_description))
                .setEmptyActionLabel(activity.getString(R.string.keep_empty_action))
                .setSyncTooltip(mobileString("menu_sync", ""))
                .setDeleteTooltip(mobileString("menu_delete", ""))
                .setColumnCount((long) column)
                .setCardImageWidthPx((long) spec[0])
                .setCardImageHeightPx((long) spec[1])
                .setItems(items)
                .build();
    }

    @Override
    public void openKeepItem(Long cid, String key, B2Messages.Result<B2Messages.B2LoadResult> result) {
        // Same chain as KeepActivity.onItemClick, with the outcome
        // reported back so Dart can show the host error state and retry.
        Keep keep = findKeep(cid, key);
        if (keep == null) {
            result.success(failedResult(""));
            return;
        }
        Config config = Config.find(keep.getCid());
        if (config == null) {
            FlutterNav.openSearch(activity, keep.getVodName());
            result.success(openedResult());
            return;
        }
        if (keep.getCid() != VodConfig.getCid()) {
            loadConfig(config, keep, result);
            return;
        }
        openDetail(keep);
        result.success(openedResult());
    }

    /** Same chain as KeepActivity.loadConfig, reporting the outcome to Dart. */
    private void loadConfig(Config config, Keep keep, B2Messages.Result<B2Messages.B2LoadResult> result) {
        boolean[] completed = new boolean[1];
        Handler handler = new Handler(Looper.getMainLooper());
        // Timeout guard: BaseConfig posts every callback to the main
        // thread, but a hung load must still complete the @async call.
        handler.postDelayed(() -> {
            if (!completed[0]) {
                completed[0] = true;
                result.success(failedResult(activity.getString(R.string.error_play_timeout)));
            }
        }, LOAD_TIMEOUT_MS);
        VodConfig.load(config, new Callback() {
            @Override
            public void success() {
                if (!completed[0]) {
                    completed[0] = true;
                    openDetail(keep);
                    result.success(openedResult());
                }
            }

            @Override
            public void error(String msg) {
                if (!completed[0]) {
                    completed[0] = true;
                    result.success(failedResult(msg));
                }
            }

            @Override
            public void noConfig() {
                // No config is not a load failure, but the default
                // Callback maps it to error("") — same as native, where
                // KeepActivity shows the error state with an empty
                // message. Dart hides the empty message line.
                if (!completed[0]) {
                    completed[0] = true;
                    result.success(failedResult(""));
                }
            }
        });
    }

    private void openDetail(Keep keep) {
        VideoActivity.start(activity, keep.getSiteKey(), keep.getVodId(), keep.getVodName(), keep.getVodPic());
    }

    private static B2Messages.B2LoadResult openedResult() {
        return new B2Messages.B2LoadResult.Builder()
                .setStatus("opened")
                .setErrorTitle("")
                .setErrorMessage("")
                .setRetryLabel("")
                .build();
    }

    private B2Messages.B2LoadResult failedResult(String message) {
        return new B2Messages.B2LoadResult.Builder()
                .setStatus("failed")
                .setErrorTitle(activity.getString(R.string.error_config_load))
                .setErrorMessage(message == null ? "" : message)
                .setRetryLabel(activity.getString(R.string.error_retry))
                .build();
    }

    @Override
    public void deleteKeepItem(Long cid, String key) {
        Keep keep = findKeep(cid, key);
        if (keep != null) keep.delete();
    }

    @Override
    public void deleteAllKeep(B2Messages.VoidResult result) {
        // Async (see the @async annotation in b2_keep_messages.dart): the
        // Dart Future completes when this dialog dismisses, whatever the
        // outcome, so Dart can reload against the post-dialog state. A
        // native dialog produces no Activity lifecycle event, so resume
        // alone would leave the list stale after a confirm.
        boolean[] completed = new boolean[1];
        try {
            // Same dialog as KeepActivity.onDelete().
            new WebHtvAlertDialogBuilder(activity)
                    .setTitle(R.string.dialog_delete_record)
                    .setMessage(mobileString("dialog_delete_keep", ""))
                    .setNegativeButton(R.string.dialog_negative, null)
                    .setPositiveButton(R.string.dialog_positive, (dialog, which) -> Keep.deleteAll())
                    .setOnDismissListener(dialog -> completeOnce(result, completed))
                    .show();
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

    private static void completeOnce(B2Messages.VoidResult result, boolean[] completed) {
        if (!completed[0]) {
            completed[0] = true;
            result.success();
        }
    }

    @Override
    public void openKeepSync() {
        // SyncDialog lives in the mobile source set (leanback builds have
        // no such class), so this main-source-set impl cannot reference it
        // directly. Invoke KeepActivity.onSync()'s exact chain
        // reflectively: SyncDialog.create().keep().show(activity). The
        // class always exists on mobile, and R8 keeps every app member
        // name (proguard-rules.pro keeps com.github.moyingshi.osc.tv.**),
        // so the reflective lookup survives release builds. On leanback
        // this screen has no entry point, so a failure here is unreachable
        // in practice and is swallowed like ImgUtil's own catches.
        try {
            Class<?> dialogClass = Class.forName("com.github.moyingshi.osc.tv.ui.dialog.SyncDialog");
            Object dialog = dialogClass.getMethod("create").invoke(null);
            dialog = dialogClass.getMethod("keep").invoke(dialog);
            dialogClass.getMethod("show", FragmentActivity.class).invoke(dialog, activity);
        } catch (Throwable e) {
            e.printStackTrace();
        }
    }

    @Override
    public void goHome() {
        // Same destination as KeepActivity.goHome(), via the router.
        FlutterNav.goHome(activity);
    }

    /** Finds a displayed item in a fresh snapshot by (cid, key); null when stale. */
    private static Keep findKeep(Long cid, String key) {
        if (cid == null || key == null) return null;
        for (Keep keep : Keep.getVod()) {
            if (keep.getCid() == cid && TextUtils.equals(keep.getKey(), key)) return keep;
        }
        return null;
    }

    /** Flattens one Keep bean the way KeepAdapter binds it. Null-safe: Pigeon fields are non-null. */
    private static B2Messages.B2KeepItem toItem(Keep keep) {
        String name = text(keep.getVodName());
        PicParts pic = resolvePic(name, keep.getVodPic());
        return new B2Messages.B2KeepItem.Builder()
                .setKey(text(keep.getKey()))
                .setCid((long) keep.getCid())
                .setVodName(name)
                .setSiteName(text(keep.getSiteName()))
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /**
     * Resolves a mobile-only string by name at runtime. These strings
     * live only in the mobile res/ tree, so a direct R reference here
     * would break the leanback build; on mobile this returns the exact
     * mobile string (locale-aware), on leanback it falls back. The
     * fallback is unreachable in practice: this screen has no leanback
     * entry point. See docs/b8-b2-keep.md.
     */
    private String mobileString(String name, String fallback) {
        int id = activity.getResources().getIdentifier(name, "string", activity.getPackageName());
        return id != 0 ? activity.getString(id) : fallback;
    }

    /** Resolved image parts for one card, mirroring ImgUtil.load() semantics. */
    private static final class PicParts {
        String url = "";
        String referer = "";
        String cookie = "";
        String userAgent = "";
        String extraHeadersJson = "";
        String fallbackUrl = "";
        String placeholderText = "！";
        int placeholderColor;
    }

    /**
     * Resolves one vodPic the way native loading does, without touching
     * ImgUtil: {@link ImgUtil#getUrl(String)} already parses the
     * {@code @Headers=} / {@code @Cookie=} / {@code @Referer=} /
     * {@code @User-Agent=} suffixes and the douban referer policy, and
     * its GlideUrl result exposes the clean URL plus the final header
     * map. Delegating to it keeps Dart pixel-for-pixel in sync with
     * native header handling and cannot drift. The fallback URL is the
     * same TmdbProxy auto-fallback the native failure listener tries.
     * Any failure degrades to the text placeholder, exactly like native
     * load()'s catch path; one bad picture never fails the whole screen.
     *
     * <p>Deliberately duplicated from C2HostApiImpl (same for the grid
     * geometry below): each batch must stay independently revertible, so
     * batches share no host helper. If either copy changes, the other
     * must change with it; see docs/b8-b2-keep.md.
     */
    private static PicParts resolvePic(String name, String rawPic) {
        PicParts parts = new PicParts();
        // TextDrawable parity: the first character (or "！"), colored by
        // ColorGenerator.get400() of that same character.
        parts.placeholderText = name.isEmpty() ? "！" : name.substring(0, 1);
        parts.placeholderColor = ColorGenerator.get400(parts.placeholderText);
        try {
            Object model = ImgUtil.getUrl(rawPic);
            if (model instanceof GlideUrl glideUrl) {
                parts.url = text(glideUrl.toStringUrl());
                splitHeaders(glideUrl.getHeaders(), parts);
            } else if (model instanceof String dataUrl) {
                // "data:" URLs pass through getUrl() unchanged. Dart shows
                // the placeholder for them (Image.network cannot load
                // data: URIs); see docs/b8-b2-keep.md.
                parts.url = dataUrl;
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.url = "";
        }
        try {
            String autoFallback = TmdbProxy.nextAutoImageUrl(text(rawPic));
            if (!TextUtils.isEmpty(autoFallback)) {
                Object fallbackModel = ImgUtil.getUrl(autoFallback);
                if (fallbackModel instanceof GlideUrl glideFallback) {
                    parts.fallbackUrl = text(glideFallback.toStringUrl());
                } else if (fallbackModel instanceof String fallbackString) {
                    parts.fallbackUrl = fallbackString;
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.fallbackUrl = "";
        }
        return parts;
    }

    /** Splits the final header map into the three named headers plus the rest as JSON. */
    private static void splitHeaders(Map<String, String> headers, PicParts parts) {
        if (headers == null || headers.isEmpty()) return;
        Map<String, String> extra = new LinkedHashMap<>();
        for (Map.Entry<String, String> entry : headers.entrySet()) {
            String key = entry.getKey();
            String value = text(entry.getValue());
            if ("Referer".equalsIgnoreCase(key)) parts.referer = value;
            else if ("Cookie".equalsIgnoreCase(key)) parts.cookie = value;
            else if ("User-Agent".equalsIgnoreCase(key)) parts.userAgent = value;
            else extra.put(text(key), value);
        }
        if (!extra.isEmpty()) parts.extraHeadersJson = App.gson().toJson(extra);
    }

    /**
     * Grid geometry. KeepActivity computes these through the mobile
     * Product/MobileWindow classes, which this main-source-set impl
     * cannot reference (leanback builds would fail: leanback Product has
     * different signatures and MobileWindow does not exist there). The
     * arithmetic below mirrors the mobile originals line by line (same
     * copy as C2HostApiImpl — KeepActivity uses the same
     * Product.getColumn/getSpec calls as HistoryActivity); if they
     * change, both copies must change with them. The clamps only guard
     * degenerate preferences (a zero column would crash both the native
     * grid and the Flutter grid); with shipped defaults they never fire.
     */

    /** Mirrors KeepActivity.setRecyclerView(): 3 columns unless wide. */
    private int keepColumn() {
        if (!isWide(activity)) return 3;
        // Mobile Product.getColumn(), wide branch only: 7 columns, +1 on pads.
        int count = 7 + (ResUtil.isPad() ? 1 : 0);
        return Math.max(1, Math.abs(PlayerSetting.getSize() - count));
    }

    /** Mirrors mobile Product.getSpec(Context, int) with Style.rect(). */
    private int[] keepSpec(int column) {
        int space = ResUtil.dp2px(32) + ResUtil.dp2px(16 * (column - 1)) + getCutout(activity);
        int width = Math.max(1, (windowWidth(activity) - space) / column);
        int height = Math.max(1, (int) (width / Style.rect().getRatio()));
        return new int[]{width, height};
    }

    /** Mirrors MobileWindow.isWide(): window width greater than height. */
    private static boolean isWide(Context context) {
        Rect bounds = windowBounds(context);
        return bounds.width() > bounds.height();
    }

    private static int windowWidth(Context context) {
        return windowBounds(context).width();
    }

    /** Mirrors MobileWindow.getBounds(). */
    private static Rect windowBounds(Context context) {
        WindowManager manager = (WindowManager) context.getSystemService(Context.WINDOW_SERVICE);
        if (manager != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            Rect bounds = manager.getCurrentWindowMetrics().getBounds();
            if (bounds.width() > 0 && bounds.height() > 0) return bounds;
        }
        DisplayMetrics metrics = new DisplayMetrics();
        if (manager != null) manager.getDefaultDisplay().getMetrics(metrics);
        if (metrics.widthPixels <= 0 || metrics.heightPixels <= 0) metrics = ResUtil.getDisplayMetrics(context);
        return new Rect(0, 0, metrics.widthPixels, metrics.heightPixels);
    }

    /** Mirrors mobile Product.getCutout(), including its bitwise-or quirk. */
    private static int getCutout(Context context) {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) return 0;
        DisplayCutout cutout = ResUtil.getDisplay(context).getCutout();
        if (cutout == null) return 0;
        int left = cutout.getSafeInsetLeft();
        int right = cutout.getSafeInsetRight();
        return left | right;
    }
}
