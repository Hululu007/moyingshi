package com.github.moyingshi.osc.tv.flutter;

import android.text.TextUtils;

import androidx.fragment.app.FragmentActivity;

import com.github.moyingshi.osc.tv.BuildConfig;
import com.github.moyingshi.osc.tv.R;
import com.github.moyingshi.osc.tv.Updater;
import com.github.moyingshi.osc.tv.setting.Setting;
import com.github.moyingshi.osc.tv.subtitle.provider.SubtitleProviderRegistry;
import com.github.moyingshi.osc.tv.ui.dialog.AboutDialog;
import com.github.moyingshi.osc.tv.ui.dialog.SubtitleSettingsDialog;
import com.github.moyingshi.osc.tv.ui.dialog.UpdateSettingsDialog;
import com.github.moyingshi.osc.tv.utils.AppVersion;
import com.github.moyingshi.osc.tv.utils.Notify;
import com.github.moyingshi.osc.tv.utils.ResUtil;

import java.util.Arrays;

/**
 * B8 C1: native side of the C1 Pigeon contract (About + subtitle settings).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/c1_messages.dart}. The generated file
 * {@code C1Messages.java} is not committed; see docs/b8-c1-about-subtitle.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity with initial route "/" (only the flag methods are ever
 * called on that engine); the C1 engine gets an instance bound to
 * C1ScreenActivity with the route from its intent. All display strings are
 * resolved here from resources so Dart never hard-codes locale strings.
 *
 * <p>Complex sub-flows stay native on purpose: the updater, the update
 * settings dialog, the GitHub-proxy dialog and both subtitle dialogs are
 * opened here; Dart only renders and re-fetches state on resume.
 */
public class C1HostApiImpl implements C1Messages.C1HostApi {

    private final FragmentActivity activity;
    private final String initialRoute;

    public C1HostApiImpl(FragmentActivity activity, String initialRoute) {
        this.activity = activity;
        this.initialRoute = initialRoute;
    }

    @Override
    public String getInitialRoute() {
        return initialRoute;
    }

    @Override
    public Boolean isC1Enabled() {
        return Setting.isFlutterC1Enabled();
    }

    @Override
    public void setC1Enabled(Boolean enabled) {
        Setting.putFlutterC1Enabled(enabled);
    }

    @Override
    public C1Messages.C1AboutInfo getAboutInfo() {
        return new C1Messages.C1AboutInfo.Builder()
                .setTitle(activity.getString(R.string.about_title))
                .setBadge(activity.getString(R.string.about_free_badge))
                .setVersionLine(activity.getString(R.string.about_version,
                        AppVersion.fullName(), BuildConfig.FLAVOR_mode, BuildConfig.FLAVOR_abi))
                .setDisclaimer(activity.getString(R.string.about_disclaimer))
                .setCheckUpdateLabel(activity.getString(R.string.about_check_update))
                .setGithubProxyLabel(activity.getString(R.string.setting_github_proxy_short))
                .setConfirmLabel(activity.getString(R.string.about_acknowledge))
                .setUpdateSettingsLabel(activity.getString(R.string.update_settings))
                .setHiddenSettingsEnabled(Setting.isHiddenSettingsEnabled())
                .build();
    }

    @Override
    public Boolean toggleHiddenSettings() {
        // The 5-tap counting lives in Dart (mirroring AboutDialog); this
        // only flips the switch, mirroring AboutDialog.onVersionClick().
        boolean enabled = !Setting.isHiddenSettingsEnabled();
        Setting.putHiddenSettingsEnabled(enabled);
        Notify.show(enabled ? R.string.hidden_settings_enabled : R.string.hidden_settings_disabled);
        return enabled;
    }

    @Override
    public void checkUpdate() {
        // Deliberately does not finish the screen first: the native dialog
        // dismisses itself before starting the updater, but this Flutter
        // screen IS the Activity, and starting the updater flow from a
        // finishing Activity risks a bad window token. The updater UI
        // overlays this screen instead; see docs/b8-c1-about-subtitle.md.
        Updater.create().force().start(activity);
    }

    @Override
    public void openUpdateSettings() {
        UpdateSettingsDialog.show(activity);
    }

    @Override
    public void openGithubProxy() {
        AboutDialog.showGithubProxy(activity);
    }

    @Override
    public C1Messages.C1SubtitleInfo getSubtitleInfo() {
        String[] labels = ResUtil.getStringArray(R.array.select_subtitle_language);
        String[] values = ResUtil.getStringArray(R.array.select_subtitle_language_value);
        String current = Setting.getSubtitlePreferredLanguage();
        return new C1Messages.C1SubtitleInfo.Builder()
                .setScreenTitle(activity.getString(R.string.setting_subtitle))
                .setAutoMatchTitle(activity.getString(R.string.player_subtitle_auto_match))
                .setAutoMatchEnabled(Setting.isSubtitleAutoMatchEnabled())
                .setOnText(activity.getString(R.string.setting_on))
                .setOffText(activity.getString(R.string.setting_off))
                .setLanguageTitle(activity.getString(R.string.player_subtitle_language))
                .setLanguageText(getSubtitleLanguageText(labels, values, current))
                .setLanguageLabels(Arrays.asList(labels))
                .setLanguageValues(Arrays.asList(values))
                .setCurrentLanguage(current)
                .setSourceTitle(activity.getString(R.string.player_subtitle_source))
                .setSourceText(activity.getString(R.string.player_subtitle_source_count,
                        SubtitleProviderRegistry.get().providerNames().size()))
                .build();
    }

    @Override
    public void setSubtitleAutoMatch(Boolean enabled) {
        Setting.putSubtitleAutoMatchEnabled(enabled);
    }

    @Override
    public void openSubtitleLanguage() {
        String[] labels = ResUtil.getStringArray(R.array.select_subtitle_language);
        String[] values = ResUtil.getStringArray(R.array.select_subtitle_language_value);
        SubtitleSettingsDialog.showPreferredLanguage(activity, labels, values,
                Setting.getSubtitlePreferredLanguage(),
                value -> Setting.putSubtitlePreferredLanguage(value));
    }

    @Override
    public void openSubtitleSource() {
        // onSaved is null: Dart re-fetches getSubtitleInfo() on resume.
        SubtitleSettingsDialog.showSourceSummary(activity,
                SubtitleProviderRegistry.get().providers(), null);
    }

    @Override
    public void closeScreen() {
        activity.finish();
    }

    /** Mirrors SettingSubtitleFragment.getSubtitleLanguageText(). */
    private static String getSubtitleLanguageText(String[] labels, String[] values, String current) {
        if (values != null) {
            for (int i = 0; i < values.length; i++) {
                if (TextUtils.equals(values[i], current) && labels != null && i < labels.length) {
                    return labels[i];
                }
            }
        }
        return current;
    }
}
