/**
 * B8 B16: native side of the B16 Pigeon contract (mobile viewing-report
 * page).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b16_report_messages.dart}. The generated
 * file {@code B16Messages.java} is not committed; see docs/b8-b16-report.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the report model, so Dart never hard-codes locale strings
 * or computes display values.
 *
 * <p>The load pipeline is the native
 * {@code ViewingReportActivity.loadReport}, verbatim order: cache read
 * (unless forced), local generation, AI analysis when an AI service is
 * configured, cache write. The AI call is a synchronous network call and
 * runs on a background thread here, exactly like the native single-thread
 * executor; AI not configured or the call failing degrades silently to a
 * report without the AI card, like native.
 *
 * <p>Every @async call completes exactly once on the main thread (B14
 * {@code Completion} precedent): the background work posts its result
 * back, and a watchdog completes with an error snapshot when the work
 * does not answer in time. A late background completion after the
 * watchdog is a no-op (the cache write still happens on that thread).
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. {@code ViewingReport*} / {@code Task} /
 * {@code App} are all main-source-set, so direct references are safe.
 * All B16 strings ({@code viewing_report_*}, {@code menu_viewing_report},
 * {@code error_play_timeout} / {@code error_retry},
 * {@code dialog_negative} / {@code dialog_positive}) are main-res
 * (verified per directory: mobile/leanback res contain none of them),
 * so direct R references are leanback-safe. The leanback history entry
 * is untouched; the host diversions are mobile-only (mobile
 * HistoryActivity + the C2 history screen, which has no leanback entry).
 */
public class B16HostApiImpl implements B16Messages.B16HostApi {

    /** Snapshot watchdog: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 35_000L;

    private final FragmentActivity activity;
    private final Handler handler = new Handler(Looper.getMainLooper());

    public B16HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public B16Messages.B16ReportShell getReportShell() {
        List<B16Messages.B16RangeItem> ranges = new ArrayList<>();
        for (ViewingReportRange range : ViewingReportRange.values()) {
            ranges.add(new B16Messages.B16RangeItem.Builder()
                    .setName(range.name())
                    .setDisplayLabel(range.getDisplayLabel())
                    .build());
        }
        return new B16Messages.B16ReportShell.Builder()
                .setTitle(activity.getString(R.string.viewing_report_title))
                .setRefreshLabel(activity.getString(R.string.viewing_report_refresh))
                .setLoadingLabel(activity.getString(R.string.viewing_report_loading_local))
                .setEmptyText(activity.getString(R.string.viewing_report_empty))
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setSelectRangeTitle(activity.getString(R.string.viewing_report_select_range))
                .setGenerateLabel(activity.getString(R.string.viewing_report_generate))
                .setCancelLabel(activity.getString(R.string.dialog_negative))
                .setRanges(ranges)
                .build();
    }

    @Override
    public void getReport(String rangeName, Boolean forceRefresh,
            B16Messages.Result<B16Messages.B16ReportScreen> result) {
        ViewingReportRange range = parseRange(rangeName);
        boolean force = forceRefresh != null && forceRefresh;
        Completion<B16Messages.B16ReportScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, errorScreen(range));
        Task.execute(() -> {
            B16Messages.B16ReportScreen screen = buildScreen(range, force);
            App.post(() -> {
                if (completion.isDone()) return;
                completion.complete(screen);
            });
        });
    }

    /** Unknown or missing range names fall back to ALL (Dart validates the same way). */
    private static ViewingReportRange parseRange(String name) {
        if (TextUtils.isEmpty(name)) return ViewingReportRange.ALL;
        try {
            return ViewingReportRange.valueOf(name);
        } catch (IllegalArgumentException e) {
            return ViewingReportRange.ALL;
        }
    }

    /**
     * Native ViewingReportActivity.loadReport, flattened into a snapshot.
     * Cache read (unless forced) -> local generation -> AI analysis when
     * ready -> cache write. Runs on a background thread; the AI call is
     * synchronous network I/O, like the native executor.
     */
    private B16Messages.B16ReportScreen buildScreen(ViewingReportRange range, boolean forceRefresh) {
        if (forceRefresh) {
            ViewingReportCache.clear(range);
        } else {
            ViewingReport cached = ViewingReportCache.read(range);
            if (cached != null && !cached.isEmpty()) return toScreen(cached);
        }
        ViewingReport report = new ViewingReportGenerator().generate(range);
        if (report.isEmpty()) return emptyScreen(range);
        ViewingReportAiAnalyzer analyzer = new ViewingReportAiAnalyzer();
        if (analyzer.isReady()) analyzer.analyze(report);
        ViewingReportCache.write(report);
        return toScreen(report);
    }

    /** Native ViewingReportActivity.display + fill* methods, flattened. */
    private B16Messages.B16ReportScreen toScreen(ViewingReport report) {
        return new B16Messages.B16ReportScreen.Builder()
                .setRangeName(report.getRange() == null
                        ? ViewingReportRange.ALL.name() : report.getRange().name())
                .setRangeLabel(report.getRange() == null
                        ? ViewingReportRange.ALL.getDisplayLabel() : report.getRange().getDisplayLabel())
                .setIsEmpty(report.isEmpty())
                .setErrorText("")
                .setOverviewLabel(activity.getString(R.string.viewing_report_overview_watch))
                .setOverviewHours(overviewHours(report))
                .setOverviewSub(overviewSub(report))
                .setTimeTitle(activity.getString(R.string.viewing_report_time_pattern))
                .setTimeContent(timeContent(report))
                .setGenreVisible(genreVisible(report))
                .setGenreTitle(activity.getString(R.string.viewing_report_content_preference))
                .setGenreContent(genreContent(report))
                .setPeopleVisible(peopleVisible(report))
                .setPeopleTitle(activity.getString(R.string.viewing_report_people_preference))
                .setPeopleContent(peopleContent(report))
                .setAiVisible(aiVisible(report))
                .setAiTitle(activity.getString(R.string.viewing_report_ai_persona))
                .setAiSummary(text(report.getAiSummary()))
                .setAiTags(new ArrayList<>(report.getStyleTags()))
                .setAiInsights(aiInsights(report))
                .setBadgesVisible(!report.getBadges().isEmpty())
                .setBadgesTitle(activity.getString(R.string.viewing_report_badges))
                .setBadgeContent(badgeContent(report))
                .build();
    }

    private B16Messages.B16ReportScreen emptyScreen(ViewingReportRange range) {
        return new B16Messages.B16ReportScreen.Builder()
                .setRangeName(range.name())
                .setRangeLabel(range.getDisplayLabel())
                .setIsEmpty(true)
                .setErrorText("")
                .setOverviewLabel(activity.getString(R.string.viewing_report_overview_watch))
                .setOverviewHours("")
                .setOverviewSub("")
                .setTimeTitle(activity.getString(R.string.viewing_report_time_pattern))
                .setTimeContent("")
                .setGenreVisible(false)
                .setGenreTitle(activity.getString(R.string.viewing_report_content_preference))
                .setGenreContent("")
                .setPeopleVisible(false)
                .setPeopleTitle(activity.getString(R.string.viewing_report_people_preference))
                .setPeopleContent("")
                .setAiVisible(false)
                .setAiTitle(activity.getString(R.string.viewing_report_ai_persona))
                .setAiSummary("")
                .setAiTags(new ArrayList<>())
                .setAiInsights("")
                .setBadgesVisible(false)
                .setBadgesTitle(activity.getString(R.string.viewing_report_badges))
                .setBadgeContent("")
                .build();
    }

    private B16Messages.B16ReportScreen errorScreen(ViewingReportRange range) {
        // Same shape as emptyScreen, but with the timeout error text;
        // built directly (no getters on the generated class are used).
        return new B16Messages.B16ReportScreen.Builder()
                .setRangeName(range.name())
                .setRangeLabel(range.getDisplayLabel())
                .setIsEmpty(false)
                .setErrorText(activity.getString(R.string.error_play_timeout))
                .setOverviewLabel(activity.getString(R.string.viewing_report_overview_watch))
                .setOverviewHours("")
                .setOverviewSub("")
                .setTimeTitle(activity.getString(R.string.viewing_report_time_pattern))
                .setTimeContent("")
                .setGenreVisible(false)
                .setGenreTitle(activity.getString(R.string.viewing_report_content_preference))
                .setGenreContent("")
                .setPeopleVisible(false)
                .setPeopleTitle(activity.getString(R.string.viewing_report_people_preference))
                .setPeopleContent("")
                .setAiVisible(false)
                .setAiTitle(activity.getString(R.string.viewing_report_ai_persona))
                .setAiSummary("")
                .setAiTags(new ArrayList<>())
                .setAiInsights("")
                .setBadgesVisible(false)
                .setBadgesTitle(activity.getString(R.string.viewing_report_badges))
                .setBadgeContent("")
                .build();
    }

    /** Native fillOverview: hours line. */
    private String overviewHours(ViewingReport report) {
        double hours = report.getTotalWatchMinutes() / 60.0;
        return String.format(Locale.getDefault(), "%.1f %s",
                hours, activity.getString(R.string.viewing_report_unit_hours));
    }

    /** Native fillOverview: two-line sub. */
    private String overviewSub(ViewingReport report) {
        return String.format(Locale.getDefault(),
                "📺 %s %d %s · %d %s\n🏆 %s %.0f%%",
                activity.getString(R.string.viewing_report_watched),
                report.getTotalVodCount(),
                activity.getString(R.string.viewing_report_unit_vods),
                report.getTotalEpisodeCount(),
                activity.getString(R.string.viewing_report_unit_episodes),
                activity.getString(R.string.viewing_report_completion_rate),
                report.getCompletionRate() * 100);
    }

    /** Native fillTimePattern. */
    private String timeContent(ViewingReport report) {
        StringBuilder sb = new StringBuilder();
        if (report.getTopTimeSlot() != null) {
            sb.append(activity.getString(R.string.viewing_report_top_time_slot)).append(": ")
                    .append(report.getTopTimeSlot().getLabel()).append("\n");
        }
        sb.append(activity.getString(R.string.viewing_report_weekend_ratio)).append(": ")
                .append(Math.round(report.getWeekendRatio() * 100)).append("%\n");
        sb.append(activity.getString(R.string.viewing_report_avg_watch)).append(": ")
                .append(String.format(Locale.getDefault(), "%.1f", report.getAverageWatchMinutes()))
                .append(" ").append(activity.getString(R.string.viewing_report_unit_minutes)).append("\n");
        sb.append(activity.getString(R.string.viewing_report_late_night)).append(": ")
                .append(report.getLateNightCount()).append(" ")
                .append(activity.getString(R.string.viewing_report_unit_times));
        return sb.toString();
    }

    /** Native fillPreference visibility rule. */
    private boolean genreVisible(ViewingReport report) {
        return !(report.getTopGenres().isEmpty()
                && report.getTvRatio() == 0 && report.getMovieRatio() == 0);
    }

    /** Native fillPreference. */
    private String genreContent(ViewingReport report) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < Math.min(5, report.getTopGenres().size()); i++) {
            ViewingReport.CountStat stat = report.getTopGenres().get(i);
            if (i > 0) sb.append("\n");
            double percent = (double) stat.getCount() / report.getTotalVodCount() * 100;
            sb.append(emojiFor(stat.getName())).append(" ").append(stat.getName())
                    .append(" ").append(Math.round(percent)).append("%");
        }
        if (report.getTvRatio() > 0 || report.getMovieRatio() > 0) {
            sb.append("\n\n").append(activity.getString(R.string.viewing_report_tv_movie_ratio)).append(": ")
                    .append(Math.round(report.getTvRatio() * 100)).append("% / ")
                    .append(Math.round(report.getMovieRatio() * 100)).append("%");
        }
        if (report.getCompletionRate() > 0) {
            sb.append("\n").append(activity.getString(R.string.viewing_report_completion_rate)).append(": ")
                    .append(Math.round(report.getCompletionRate() * 100)).append("%");
        }
        return sb.toString();
    }

    /** Native fillPeople visibility rule. */
    private boolean peopleVisible(ViewingReport report) {
        return !(report.getTopActors().isEmpty() && report.getTopDirectors().isEmpty());
    }

    /** Native fillPeople. */
    private String peopleContent(ViewingReport report) {
        StringBuilder sb = new StringBuilder();
        if (!report.getTopActors().isEmpty()) {
            sb.append("👤 ").append(activity.getString(R.string.viewing_report_top_actors)).append(":\n");
            for (int i = 0; i < Math.min(5, report.getTopActors().size()); i++) {
                ViewingReport.CountStat stat = report.getTopActors().get(i);
                if (i > 0) sb.append("\n");
                sb.append("  ").append(stat.getName()).append(" ×").append(stat.getCount());
            }
        }
        if (!report.getTopDirectors().isEmpty()) {
            if (sb.length() > 0) sb.append("\n\n");
            sb.append("🎬 ").append(activity.getString(R.string.viewing_report_top_directors)).append(":\n");
            for (int i = 0; i < Math.min(3, report.getTopDirectors().size()); i++) {
                ViewingReport.CountStat stat = report.getTopDirectors().get(i);
                if (i > 0) sb.append("\n");
                sb.append("  ").append(stat.getName()).append(" ×").append(stat.getCount());
            }
        }
        return sb.toString();
    }

    /** Native fillAi visibility rule (the AI persona field itself is never displayed, like native). */
    private boolean aiVisible(ViewingReport report) {
        return report.isAiAnalyzed() && !TextUtils.isEmpty(report.getAiSummary());
    }

    /** Native fillAi: one "• ..." line per insight; empty when there are none. */
    private String aiInsights(ViewingReport report) {
        if (report.getInsights().isEmpty()) return "";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < report.getInsights().size(); i++) {
            if (i > 0) sb.append("\n");
            sb.append("• ").append(report.getInsights().get(i));
        }
        return sb.toString();
    }

    /** Native fillBadges. */
    private String badgeContent(ViewingReport report) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < report.getBadges().size(); i++) {
            ViewingReport.Badge badge = report.getBadges().get(i);
            if (i > 0) sb.append("\n\n");
            sb.append(badge.getIcon()).append(" ").append(badge.getName());
            if (!TextUtils.isEmpty(badge.getDescription())) {
                sb.append("\n  ").append(badge.getDescription());
            }
        }
        return sb.toString();
    }

    /** Native ViewingReportActivity.emojiFor, verbatim. */
    private String emojiFor(String genre) {
        if (genre.contains("悬疑") || genre.contains("推理") || genre.contains("犯罪")) return "🔍";
        if (genre.contains("爱情") || genre.contains("浪漫")) return "💕";
        if (genre.contains("动作") || genre.contains("冒险")) return "🎬";
        if (genre.contains("喜剧")) return "😄";
        if (genre.contains("科幻")) return "🚀";
        if (genre.contains("恐怖") || genre.contains("惊悚")) return "😱";
        if (genre.contains("剧情")) return "🎭";
        if (genre.contains("动画")) return "🎨";
        if (genre.contains("纪录")) return "📽️";
        return "🎬";
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /**
     * Main-thread-only one-shot completion for an @async call, with a
     * watchdog. The timeout completes with the given value; a late
     * background completion is a no-op. All callers complete from the
     * main thread (App.post / Handler), so no synchronization is needed.
     * Copied from B15HostApiImpl (same shape, B16 result type).
     */
    private final class Completion<T> {
        private final B16Messages.Result<T> result;
        private boolean done;
        private final Runnable timeout;

        Completion(B16Messages.Result<T> result, long timeoutMs, T timeoutValue) {
            this.result = result;
            this.timeout = () -> complete(timeoutValue);
            handler.postDelayed(this.timeout, timeoutMs);
        }

        void complete(T value) {
            if (done) return;
            done = true;
            handler.removeCallbacks(timeout);
            result.success(value);
        }

        boolean isDone() {
            return done;
        }
    }
}
