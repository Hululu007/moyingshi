/**
* Native TmdbPersonActivity.openWork, verbatim: the current-site
* search runs on a background thread, the result navigation runs
* back on the main thread. Called from Dart when a work card is
* tapped; all toasts are host-side.
*/
@Override
public void openPersonWork(Long tmdbId, String mediaType, String title) {
String keyword = title == null? "": title;
TmdbItem item = null;
if (tmdbId!= null) {
item = workByKey.get(text(mediaType) + ":" + tmdbId);
}
if (item == null) {
// Unknown work (stale snapshot): fall back to a direct
// search, like the native no-match path.
SearchActivity.direct(activity, keyword);
return;
}
final TmdbItem work = item;
Site site = VodConfig.get().getSite(sessionSiteKey);
if (site == null || site.isEmpty() ||!site.isSearchable()) {
SearchActivity.direct(activity, keyword);
return;
}
Notify.show(activity.getString(R.string.detail_work_searching, keyword));
Task.execute(() -> {
Vod match = searchCurrentSite(keyword, site);
App.post(() -> {
if (activity.isFinishing() || activity.isDestroyed()) return;
if (match == null) {
Notify.show(activity.getString(
R.string.detail_work_global_searching, keyword));
SearchActivity.direct(activity, keyword);
return;
}
TmdbDetailActivity.start(activity, site.getKey(), match.getId(),
match.getName(), match.getPic(), "", work, sessionDetailMode);
});
});
}

/** Native TmdbPersonActivity.searchCurrentSite. */
private Vod searchCurrentSite(String keyword, Site site) {
try {
Result result = SiteApi.searchContent(site, keyword, false, "1");
return bestVod(result!= null? result.getList(): List.of(), keyword);
} catch (Throwable e) {
return null;
}
}

/** Native TmdbPersonActivity.bestVod / scoreVod / normalizeTitle. */
private Vod bestVod(List<Vod> items, String keyword) {
if (items == null || items.isEmpty()) return null;
Vod best = null;
int score = Integer.MIN_VALUE;
for (Vod item: items) {
int current = scoreVod(item, keyword);
if (current > score) {
score = current;
best = item;
}
}
return score > 0? best: null;
}

private int scoreVod(Vod item, String keyword) {
if (item == null) return Integer.MIN_VALUE;
String normalizedKeyword = normalizeTitle(keyword);
String name = normalizeTitle(item.getName());
if (name.isEmpty()) return Integer.MIN_VALUE;
if (name.equals(normalizedKeyword)) return 300;
if (name.contains(normalizedKeyword) || normalizedKeyword.contains(name)) return 220;
String remarks = normalizeTitle(item.getRemarks());
if (!remarks.isEmpty() && (remarks.contains(normalizedKeyword) || normalizedKeyword.contains(remarks))) return 120;
return 0;
}

private String normalizeTitle(String text) {
return TextUtils.isEmpty(text)? "": text.replaceAll("[\\s·•・._\\-_/\\\\|()（）\\[\\]《》<>]+", "").trim().toLowerCase(Locale.ROOT);
}

