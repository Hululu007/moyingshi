/** Native TmdbPersonActivity.highResTmdbImage. */
private String highResTmdbImage(String url) {
int marker = url.indexOf("/t/p/");
if (marker < 0) return url;
int sizeStart = marker + "/t/p/".length();
int sizeEnd = url.indexOf('/', sizeStart);
if (sizeEnd < 0) return url;
return url.substring(0, sizeStart) + "original" + url.substring(sizeEnd);
}

/**
* Native TmdbPersonActivity.loadPerson, flattened into a snapshot.
* Runs on a background thread. Any failure degrades to an error
* screen (the native catch path only hides the progress bar and
* toasts; Dart shows the error state with retry instead).
*/
private B17Messages.B17PersonScreen buildScreen(int personId, String siteKey, int detailMode) {
TmdbConfig config = TmdbConfig.effectiveCurrent();
if (!config.isReady()) return needKeyScreen(personId);
try {
JsonObject detail = tmdbService.person(personId, config);
if (detail == null || detail.size() == 0) return emptyScreen(personId);
TmdbPerson profile = tmdbService.personProfile(detail, config);
List<String> photos = tmdbService.personPhotos(detail, config);
List<TmdbItem> cast = tmdbService.personCastWorks(detail, config);
List<TmdbItem> crew = tmdbService.personCrewWorks(detail, config);
List<TmdbItem> all = tmdbService.personWorks(detail, config);
PersonScore score = personScore(detail);
// Publish the session for openPersonWork before completing.
Map<String, TmdbItem> byKey = new HashMap<>();
putWorks(byKey, all);
putWorks(byKey, cast);
putWorks(byKey, crew);
workByKey = byKey;
sessionSiteKey = siteKey;
sessionDetailMode = detailMode;
return toScreen(personId, profile, photos, all, cast, crew, score);
} catch (Throwable e) {
e.printStackTrace();
return errorScreen(personId);
}
}

private static void putWorks(Map<String, TmdbItem> byKey, List<TmdbItem> works) {
if (works == null) return;
for (TmdbItem item: works) {
if (item!= null) byKey.put(text(item.getMediaType()) + ":" + item.getTmdbId(), item);
}
}

