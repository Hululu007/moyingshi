/**
* Native TmdbPersonActivity.refreshFilterButtons, flattened into the
* chip list: "all" first when it has works, then cast/crew/director/
* movie/tv by count desc (stable sort keeps the native insertion
* order on ties), only count > 0. Dart filters locally from the
* three work lists using the same filteredWorks rules.
*/
private List<B17Messages.B17FilterItem> buildFilters(
List<TmdbItem> all, List<TmdbItem> cast, List<TmdbItem> crew) {
List<B17Messages.B17FilterItem> filters = new ArrayList<>();
int allCount = filterCount("all", all, cast, crew);
if (allCount > 0) {
filters.add(new B17Messages.B17FilterItem.Builder()
.setKey("all")
.setLabel(activity.getString(R.string.detail_filter_all))
.setCount((long) allCount)
.build());
}
List<String> keys = new ArrayList<>(List.of("cast", "crew", "director", "movie", "tv"));
List<long[]> counted = new ArrayList<>();
for (String key: keys) {
int count = filterCount(key, all, cast, crew);
if (count > 0) counted.add(new long[]{keys.indexOf(key), count});
}
counted.sort((a, b) -> Long.compare(b[1], a[1]));
for (long[] entry: counted) {
String key = keys.get((int) entry[0]);
filters.add(new B17Messages.B17FilterItem.Builder()
.setKey(key)
.setLabel(filterLabel(key))
.setCount(entry[1])
.build());
}
return filters;
}

private String filterLabel(String key) {
return switch (key) {
case "cast" -> activity.getString(R.string.detail_filter_cast);
case "crew" -> activity.getString(R.string.detail_filter_crew);
case "director" -> activity.getString(R.string.detail_filter_director);
case "movie" -> activity.getString(R.string.detail_filter_movie);
case "tv" -> activity.getString(R.string.detail_filter_tv);
default -> activity.getString(R.string.detail_filter_all);
};
}

/** Native TmdbPersonActivity.filteredWorks / filterCount. */
private int filterCount(String value, List<TmdbItem> all, List<TmdbItem> cast, List<TmdbItem> crew) {
return filteredWorks(value, all, cast, crew).size();
}

private List<TmdbItem> filteredWorks(String value, List<TmdbItem> all, List<TmdbItem> cast, List<TmdbItem> crew) {
List<TmdbItem> source = switch (value) {
case "cast" -> cast;
case "crew", "director" -> crew;
default -> all;
};
List<TmdbItem> filtered = new ArrayList<>();
if (source == null) return filtered;
for (TmdbItem item: source) {
if ("movie".equals(value) &&!"movie".equals(item.getMediaType())) continue;
if ("tv".equals(value) &&!"tv".equals(item.getMediaType())) continue;
if ("director".equals(value) &&!isDirector(item)) continue;
filtered.add(item);
}
return filtered;
}

private boolean isDirector(TmdbItem item) {
String credit = text(item.getCredit()).toLowerCase(Locale.ROOT);
return credit.contains("director") || credit.contains("directing") || credit.contains("导演");
}

