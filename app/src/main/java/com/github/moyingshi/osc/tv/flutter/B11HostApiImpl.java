/**
 * B8 B11: native side of the B11 Pigeon contract (mobile home shell,
 * HomeActivity + VodFragment top bar / tabs / bottom bar).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b11_home_messages.dart}. The generated file
 * {@code B11Messages.java} is not committed; see docs/b8-b11-home.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the site beans, so Dart never hard-codes locale strings.
 *
 * <p>Scope of this batch is the SHELL plus the tab grid: the top bar
 * (logo / title / search pill / overflow menu), the category tabs, the
 * glass bottom bar, and the inline video grid for the selected tab
 * (b8-home-grid, same list the B8 category screen shows, via the same
 * {@code SiteViewModel.categoryContent} path). Folder cards in the grid
 * drill down into the B8 {@code /category} screen; every other card tap
 * goes through the B8 host chain from Dart.
 *
 * <p>Home-screen data comes from one-shot {@link SiteViewModel}
 * subscriptions (B8 pattern: {@code init()} clears stale values,
 * {@code observeForever} on {@code getResult()}, 35s watchdog, observer
 * removed on every path). The shell load and the grid load share one
 * activity-scoped ViewModel, so a single serial guard covers both: a
 * second load while either is in flight completes with an error
 * immediately. The native home underneath stays alive while the
 * Flutter home is on top (see HomeActivity.change(0) / handleNavItem
 * diversion): HomeActivity.onDestroy() stops the server and clears
 * VodConfig, so it must NOT be finished, and back from the Flutter home
 * lands on the native home (one extra back press to exit, recorded as
 * deviation V1 in docs/b8-b11-home.md).
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Mobile-only classes are never referenced
 * directly: SiteDialog / HistoryDialog / LocalSourceDialog are opened
 * reflectively through a headless host fragment (B7/B9 pattern);
 * ShortDramaActivity / HkSearchActivity / ShortcutReceiver are opened
 * reflectively; HkStore.isMiniapp / titleOf and DramaSites.isDramaSite
 * are replicated below (plan §4.8招3, drift warnings inline);
 * HomeActivity / LiveActivity / HistoryActivity / KeepActivity exist in
 * BOTH flavors with identical signatures, so direct references are safe
 * (B2 precedent). All mobile-only strings are resolved at runtime via
 * {@link #mobileString(String, int)} with main-res fallbacks (the
 * fallbacks are unreachable in practice: the screen has no leanback
 * entry, C1ScreenActivity is mobile-manifest only).
 */
