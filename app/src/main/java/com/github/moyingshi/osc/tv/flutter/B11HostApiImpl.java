    @Override
    public void getHomeShell(B11Messages.Result<B11Messages.B11HomeScreen> result) {
        if (loading || loadingTab) {
            result.error(new IllegalStateException("home load already in progress"));
            return;
        }
        loading = true;
        SiteViewModel viewModel = new ViewModelProvider(activity).get(SiteViewModel.class);
        viewModel.init();
        boolean[] completed = new boolean[1];
        AtomicReference<Observer<Result>> observerRef = new AtomicReference<>();
        Runnable timeout = () -> {
            if (completed[0]) return;
            completed[0] = true;
            loading = false;
            Observer<Result> observer = observerRef.get();
            if (observer != null) viewModel.getResult().removeObserver(observer);
            result.success(buildScreen(null, activity.getString(R.string.error_play_timeout)));
        };
        handler.postDelayed(timeout, LOAD_TIMEOUT_MS);
        // B8 crash fix (docs/b8-crash-singletop-fix.md, root cause B):
        // when the process config load is still in flight and VodConfig
        // holds no sites yet, homeContent() would read an empty home
        // Site and answer an empty screen — and no signal ever tells
        // Dart to re-fetch. Wait for that one load instead; the
        // watchdog above still bounds the total wait, and a late
        // runnable no-ops via completed[0]. When the config is already
        // loaded, no load is running, or the load ended with no config
        // (a legal empty state), start immediately.
        Runnable startLoad = () -> {
            if (completed[0]) return;
            Observer<Result> observer = loaded -> {
                if (loaded == null || completed[0]) return;
                completed[0] = true;
                loading = false;
                handler.removeCallbacks(timeout);
                viewModel.getResult().removeObserver(observerRef.get());
                result.success(buildScreen(loaded, ""));
            };
            observerRef.set(observer);
            viewModel.getResult().observeForever(observer);
            viewModel.homeContent();
        };
        if (VodConfig.get().getSites().isEmpty() && C1ScreenActivity.isConfigLoadPending()) {
            // The config callback may fire off the main thread; hop
            // back so the observer registration and homeContent() run
            // on it, like the immediate path below.
            C1ScreenActivity.runAfterConfigLoad(() -> handler.post(startLoad));
        } else {
            startLoad.run();
        }
    }

    /** Builds the shell snapshot. {@code loaded == null} means the watchdog fired. */
    private B11Messages.B11HomeScreen buildScreen(Result loaded, String errorToast) {
        Site home = VodConfig.get().getHome();
        String title = AppBranding.getDisplayName(activity, home.getDisplayName(),
                VodConfig.get().getConfig().getName());
        List<B11Messages.B11HomeTab> tabs = new ArrayList<>();
        String toast = errorToast == null ? "" : errorToast;
        boolean empty = false;
        if (loaded != null) {
            if (!TextUtils.isEmpty(loaded.getMsg())) toast = loaded.getMsg();
            if (loaded.getTypes() != null) {
                // Fresh Result: the TypeFilterDialog's items + filter
                // source, and filter overrides reset (native page
                // recreation resets filter state).
                homeTypes = new ArrayList<>(loaded.getTypes());
                filterOverrides.clear();
                for (Class clazz : loaded.getTypes()) {
                    tabs.add(new B11Messages.B11HomeTab.Builder()
                            .setTypeId(clazz.getTypeId())
                            .setTypeName(clazz.getTypeName())
                            .setTypeJson(App.gson().toJson(clazz))
                            .build());
                }
            }
            // Native VodFragment shows the empty view when the load
            // succeeded but produced no tabs and no list.
            empty = TextUtils.isEmpty(loaded.getMsg()) && tabs.isEmpty()
                    && (loaded.getList() == null || loaded.getList().isEmpty());
        }
        Wallpaper wallpaper = resolveWallpaper();
        return new B11Messages.B11HomeScreen.Builder()
                .setTitle(title)
                .setSearchHint(mobileString("menu_search", R.string.danmaku_search_title))
                .setHistoryTooltip(mobileString("app_history", R.string.setting_home_history))
                .setMoreTooltip(mobileString("control_other", R.string.home_filter_title))
                .setTabs(tabs)
                .setErrorToast(toast)
                .setEmptyTitle(empty ? activity.getString(R.string.home_empty_title) : "")
                .setEmptyDescription(empty ? activity.getString(R.string.home_empty_description) : "")
                .setEmptyActionLabel(empty ? activity.getString(R.string.home_empty_action) : "")
                .setIsHkHome(isMiniapp(home))
                .setIsWebHome(WebHomeTarget.canLoad(home))
                .setNavItems(navItems())
                .setSelectedNavToken("vod")
                .setGlassEnabled(Setting.isLiquidGlass())
                .setGlassBlurDp((long) Setting.getGlassBlur())
                .setGlassDistortionDp((long) Setting.getGlassDistortion())
                .setGlassTranslucency((long) Setting.getGlassTranslucency())
                .setGlassDispersion(Setting.isGlassDispersion())
                .setDarkMode(isNightMode())
                .setAccentColor((long) accentColor())
                .setMenuItems(menuItems())
                .setTabPlaceholderEmptyText(activity.getString(R.string.widget_empty))
                .setWallpaperPath(wallpaper.path)
                .setWallpaperColor((long) wallpaper.color)
                .build();
    }

    /** Resolved home wallpaper: an image file Dart can load, plus its fallback color. */
    private static final class Wallpaper {
        final String path;
        final int color;

        Wallpaper(String path, int color) {
            this.path = path;
            this.color = color;
        }
    }

    /**
     * Wallpaper resolution mirroring CustomWallView.load(), static image
     * only: Dart cannot play video/gif walls, so every custom wall
     * resolves to the frame-0 JPEG snapshot WallConfig already wrote
     * (FileUtil.getWallCache()). Built-in design walls are Android
     * drawables with no file form, so the drawable is rendered once to
     * a files-dir JPEG Dart can load; the render is cached by wall
     * index. Any failure degrades to the fallback color, never to a
     * missing snapshot — the wallpaper must never fail the shell.
     * The built-in color branch is dead upstream
     * (Setting.isBuiltInColorWall always returns false) and the green
     * branch is unreachable (Setting.getWall remaps WALL_GREEN), but
     * both keep their native order here so a future Setting change
     * cannot silently reorder the resolution.
     */
    private Wallpaper resolveWallpaper() {
        int wall = Setting.getWall();
        int type = Setting.getWallType();
        if (type == 0 && Setting.isBuiltInColorWall(wall)) {
            return new Wallpaper("", Setting.getBuiltInWallColor(wall));
        }
        if (type == 0 && Setting.isBuiltInDesignWall(wall)) {
            String path = snapshotDrawable(CustomWallView.getDesignResId(wall), wall);
            return new Wallpaper(path == null ? "" : path, Setting.getBuiltInWallColor(wall));
        }
        if (type == 0 && wall == Setting.WALL_GREEN) {
            String path = snapshotDrawable(R.drawable.wallpaper_1, wall);
            return new Wallpaper(path == null ? "" : path, GREEN_WALL_COLOR);
        }
        File cache = FileUtil.getWallCache();
        if (cache.exists()) return new Wallpaper(cache.getAbsolutePath(), DEFAULT_WALL_COLOR);
        return new Wallpaper("", DEFAULT_WALL_COLOR);
    }

    /**
     * Renders one drawable resource to a files-dir JPEG for Dart,
     * downsampled like CustomWallView.decodeWallBitmap (max side 1920,
     * ARGB_8888: blurred gradient walls band visibly in RGB_565).
     * Returns null on any failure; the caller falls back to the color.
     */
    private String snapshotDrawable(int resId, int wall) {
        if (resId == 0) return null;
        File out = new File(activity.getFilesDir(), FLUTTER_WALLPAPER_FILE);
        if (wall == lastWallpaperWall && out.exists()) return out.getAbsolutePath();
        try {
            BitmapFactory.Options bounds = new BitmapFactory.Options();
            bounds.inJustDecodeBounds = true;
            BitmapFactory.decodeResource(activity.getResources(), resId, bounds);
            if (bounds.outWidth <= 0 || bounds.outHeight <= 0) return null;
            DisplayMetrics metrics = activity.getResources().getDisplayMetrics();
            int reqWidth = Math.max(1, Math.min(metrics.widthPixels, MAX_WALL_BITMAP_SIDE));
            int reqHeight = Math.max(1, Math.min(metrics.heightPixels, MAX_WALL_BITMAP_SIDE));
            BitmapFactory.Options options = new BitmapFactory.Options();
            options.inSampleSize = wallSampleSize(bounds, reqWidth, reqHeight);
            options.inPreferredConfig = Bitmap.Config.ARGB_8888;
            Bitmap bitmap = BitmapFactory.decodeResource(activity.getResources(), resId, options);
            if (bitmap == null) return null;
            try (FileOutputStream fos = new FileOutputStream(out)) {
                bitmap.compress(Bitmap.CompressFormat.JPEG, 90, fos);
            } finally {
                bitmap.recycle();
            }
            lastWallpaperWall = wall;
            return out.getAbsolutePath();
        } catch (Throwable e) {
            e.printStackTrace();
            return null;
        }
    }

    /** Power-of-two downsample so the decoded bitmap fits the request, mirroring CustomWallView. */
    private static int wallSampleSize(BitmapFactory.Options bounds, int reqWidth, int reqHeight) {
        int sampleSize = 1;
        while (bounds.outWidth / sampleSize > reqWidth || bounds.outHeight / sampleSize > reqHeight) sampleSize *= 2;
        return sampleSize;
    }

