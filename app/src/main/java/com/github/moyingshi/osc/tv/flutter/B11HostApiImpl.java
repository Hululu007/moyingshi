    /**
     * HkStore.isMiniapp, replicated: api or key starts with "hk://".
     * DRIFT WARNING: if HkStore.isMiniapp changes, update this too.
     */
    private boolean isMiniapp(Site site) {
        if (site == null) return false;
        String api = site.getApi();
        if (!TextUtils.isEmpty(api) && api.startsWith(HK_SCHEME)) return true;
        String key = site.getKey();
        return !TextUtils.isEmpty(key) && key.startsWith(HK_SCHEME);
    }

    /**
     * HkStore.titleOf, replicated: the hk:// rule title (api minus the
     * scheme prefix); "" when not a miniapp site.
     * DRIFT WARNING: if HkStore.titleOf changes, update this too.
     */
    private String hkTitleOf(Site site) {
        if (site == null) return "";
        String api = site.getApi();
        if (!TextUtils.isEmpty(api) && api.startsWith(HK_SCHEME)) return api.substring(HK_SCHEME.length());
        String key = site.getKey();
        if (!TextUtils.isEmpty(key) && key.startsWith(HK_SCHEME)) return key.substring(HK_SCHEME.length());
        return "";
    }

    /**
     * DramaSites.isDramaSite, replicated: name/key contains a drama
     * keyword, or the site is enabled in the short-drama config.
     * DRIFT WARNING: if DramaSites.KEYWORDS / isDramaSite changes,
     * update this too.
     */
    private boolean isDramaSite(Site site) {
        if (site == null || site.isEmpty()) return false;
        String name = site.getName();
        String key = site.getKey();
        for (String keyword : DRAMA_KEYWORDS) {
            if (!TextUtils.isEmpty(name) && name.contains(keyword)) return true;
            if (!TextUtils.isEmpty(key) && key.contains(keyword)) return true;
        }
        return Setting.isShortDramaSiteEnabled(key, name == null ? "" : name);
    }

    private boolean hasDramaSites() {
        for (Site site : VodConfig.get().getSites()) if (isDramaSite(site)) return true;
        return false;
    }

