    /** Builds a page snapshot from the given items (main thread). */
    private B18Messages.B18BrowseScreen buildScreen(List<WidgetItem> items, int pageNumber,
            boolean fromCache, String errorText) {
        List<B18Messages.B18ModuleItem> modules = new ArrayList<>();
        List<B18Messages.B18ParamItem> paramItems = new ArrayList<>();
        if (module != null && metadata != null) {
            for (WidgetModule candidate : metadata.getModules()) {
                if (candidate.isCategory()) continue;
                modules.add(new B18Messages.B18ModuleItem.Builder()
                        .setFunctionName(text(candidate.getFunctionName()))
                        .setTitle(text(candidate.getTitle()))
                        .setSelected(candidate.getFunctionName() != null
                                && candidate.getFunctionName().equals(module.getFunctionName()))
                        .build());
            }
            for (JsonObject param : WidgetManager.visibleParams(module, params)) {
                paramItems.add(toParamItem(param));
            }
        }
        List<B18Messages.B18BrowseItem> out = new ArrayList<>();
        if (items != null) {
            for (WidgetItem item : items) out.add(toBrowseItem(item));
        }
        String emptyText = "";
        if (out.isEmpty() && TextUtils.isEmpty(errorText)) {
            emptyText = module == null
                    ? activity.getString(R.string.widget_no_module)
                    : activity.getString(R.string.widget_empty);
        }
        return new B18Messages.B18BrowseScreen.Builder()
                .setWidgetId(text(widgetId))
                .setTitle(title())
                .setLoaded(TextUtils.isEmpty(errorText))
                .setErrorText(text(errorText))
                .setEmptyText(emptyText)
                .setModules(modules)
                .setParams(paramItems)
                .setItems(out)
                .setHasMore(!out.isEmpty() && hasPageParam(module))
                .setPage((long) pageNumber)
                .setFromCache(fromCache)
                .setColumnCount((long) browseColumn())
                .build();
    }

    /** Error snapshot: empty items, no more pages, chrome kept. */
    private B18Messages.B18BrowseScreen errorScreen(String errorText) {
        return new B18Messages.B18BrowseScreen.Builder()
                .setWidgetId(text(widgetId))
                .setTitle(title())
                .setLoaded(false)
                .setErrorText(text(errorText))
                .setEmptyText("")
                .setModules(new ArrayList<>())
                .setParams(new ArrayList<>())
                .setItems(new ArrayList<>())
                .setHasMore(false)
                .setPage(1L)
                .setFromCache(false)
                .setColumnCount((long) browseColumn())
                .build();
    }

    private String title() {
        return metadata == null ? "" : text(metadata.getTitle());
    }

    private String loadFailed(String message) {
        return activity.getString(R.string.widget_load_failed, text(message));
    }

    /** Flattens one visible param (native setParamChips + paramDisplayValue). */
    private B18Messages.B18ParamItem toParamItem(JsonObject param) {
        String name = Json.safeString(param, "name");
        String type = Json.safeString(param, "type");
        String title = Json.safeString(param, "title");
        if (TextUtils.isEmpty(title)) title = name;
        List<B18Messages.B18ParamOption> options = new ArrayList<>();
        if ("enumeration".equals(type) && param.has("enumOptions")) {
            JsonArray raw = param.getAsJsonArray("enumOptions");
            for (int i = 0; i < raw.size(); i++) {
                JsonObject option = raw.get(i).getAsJsonObject();
                options.add(new B18Messages.B18ParamOption.Builder()
                        .setTitle(Json.safeString(option, "title"))
                        .setValue(Json.safeString(option, "value"))
                        .build());
            }
        }
        return new B18Messages.B18ParamItem.Builder()
                .setName(name)
                .setType(type)
                .setTitle(title)
                .setValue(params.get(name) == null ? "" : params.get(name))
                .setDisplayValue(paramDisplayValue(param))
                .setHint(Json.safeString(param, "description"))
                .setOptions(options)
                .build();
    }

    /**
     * Native WidgetBrowseActivity.paramDisplayValue, verbatim:
     * enumeration shows the selected option title, string shows the
     * raw value truncated to 8 chars + "…", empty shows "全部".
     */
    private String paramDisplayValue(JsonObject param) {
        String value = params.get(Json.safeString(param, "name"));
        if (value == null) value = "";
        if ("enumeration".equals(Json.safeString(param, "type")) && param.has("enumOptions")) {
            JsonArray options = param.getAsJsonArray("enumOptions");
            for (int i = 0; i < options.size(); i++) {
                JsonObject option = options.get(i).getAsJsonObject();
                if (value.equals(Json.safeString(option, "value"))) {
                    return Json.safeString(option, "title");
                }
            }
        }
        if (value.length() > 8) value = value.substring(0, 8) + "…";
        return value.isEmpty() ? ALL_LABEL : value;
    }

    /** Flattens one WidgetItem the way WidgetGridAdapter binds it. */
    private B18Messages.B18BrowseItem toBrowseItem(WidgetItem item) {
        String title = text(item.getTitle());
        String remarks = text(item.getDisplayRemark());
        PicParts pic = resolvePic(title, WidgetManager.posterUrlWithHeaders(item));
        return new B18Messages.B18BrowseItem.Builder()
                .setTitle(title)
                .setRemarks(remarks)
                .setRemarksVisible(!remarks.isEmpty())
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    private static List<WidgetItem> parseItems(String json) {
        if (TextUtils.isEmpty(json)) return null;
        try {
            return App.gson().fromJson(json, new TypeToken<List<WidgetItem>>() {
            }.getType());
        } catch (Throwable e) {
            return null;
        }
    }

    private static boolean hasPageParam(WidgetModule module) {
        if (module == null) return false;
        for (JsonObject param : module.getParams()) {
            if ("page".equals(Json.safeString(param, "type"))) return true;
        }
        return false;
    }

