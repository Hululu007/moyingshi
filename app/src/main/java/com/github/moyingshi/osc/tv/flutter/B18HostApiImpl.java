    /**
     * Mirrors native WidgetBrowseActivity.initView: wide screens use
     * mobile Product.getColumn, otherwise 3. Product.getColumn is
     * copied verbatim below (mobile-only class); if mobile changes
     * it, this copy must change with it — see docs/b8-b2-keep.md §2.6
     * for the same warning on the C2/B2 copies.
     */
    private int browseColumn() {
        if (!isWide(activity)) return 3;
        int count = 7 + (ResUtil.isPad() ? 1 : 0);
        return Math.abs(PlayerSetting.getSize() - count);
    }

    /** Mirrors MobileWindow.isWide(): window width greater than height (B8 copy). */
    private static boolean isWide(Context context) {
        Rect bounds = windowBounds(context);
        return bounds.width() > bounds.height();
    }

    /** Mirrors MobileWindow.getBounds() (B8 copy). */
    private static Rect windowBounds(Context context) {
        WindowManager manager = (WindowManager) context.getSystemService(Context.WINDOW_SERVICE);
        if (manager != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            Rect bounds = manager.getCurrentWindowMetrics().getBounds();
            if (bounds.width() > 0 && bounds.height() > 0) return bounds;
        }
        DisplayMetrics metrics = new DisplayMetrics();
        if (manager != null) manager.getDefaultDisplay().getMetrics(metrics);
        if (metrics.widthPixels <= 0 || metrics.heightPixels <= 0) {
            metrics = ResUtil.getDisplayMetrics(context);
        }
        return new Rect(0, 0, metrics.widthPixels, metrics.heightPixels);
    }

    // ------------------------------------------------------------------
    // Images (C2/B2/B13 copy: ImgUtil.getUrl delegation)
    // ------------------------------------------------------------------

    private static final class PicParts {
        String url = "";
        String referer = "";
        String cookie = "";
        String userAgent = "";
        String extraHeadersJson = "";
        String fallbackUrl = "";
        String placeholderText = "！";
        int placeholderColor;
    }

    /**
     * Resolves one poster URL the way native loading does, without touching
     * ImgUtil (C2 copy, see docs/b8-c2-history.md §2.5): {@link
     * ImgUtil#getUrl(String)} already parses the {@code @Headers=} /
     * {@code @Cookie=} / {@code @Referer=} / {@code @User-Agent=}
     * suffixes and the douban referer policy, and its GlideUrl result
     * exposes the clean URL plus the final header map. Delegating to it
     * keeps Dart pixel-for-pixel in sync with native header handling and
     * cannot drift. The fallback URL is the same TmdbProxy auto-fallback
     * the native failure listener tries. Any failure degrades to the text
     * placeholder, exactly like native load()'s catch path; one bad
     * picture never fails the whole screen. Deliberately duplicated from
     * C2HostApiImpl/B2HostApiImpl/B8HostApiImpl/B12HostApiImpl/B13HostApiImpl
     * (same for the header split below): each batch must stay
     * independently revertible, so batches share no host helper. If any
     * copy changes, the others must change with it.
     */
    private static PicParts resolvePic(String name, String rawPic) {
        PicParts parts = new PicParts();
        // TextDrawable parity: the first character (or "！"), colored by
        // ColorGenerator.get400() of that same character.
        parts.placeholderText = name.isEmpty() ? "！" : name.substring(0, 1);
        parts.placeholderColor = ColorGenerator.get400(parts.placeholderText);
        try {
            Object model = ImgUtil.getUrl(rawPic);
            if (model instanceof GlideUrl glideUrl) {
                parts.url = text(glideUrl.toStringUrl());
                splitHeaders(glideUrl.getHeaders(), parts);
            } else if (model instanceof String dataUrl) {
                // "data:" URLs pass through getUrl() unchanged. Dart shows
                // the placeholder for them (Image.network cannot load
                // data: URIs); see docs/b8-c2-history.md.
                parts.url = dataUrl;
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.url = "";
        }
        try {
            String autoFallback = TmdbProxy.nextAutoImageUrl(text(rawPic));
            if (!TextUtils.isEmpty(autoFallback)) {
                Object fallbackModel = ImgUtil.getUrl(autoFallback);
                if (fallbackModel instanceof GlideUrl glideFallback) {
                    parts.fallbackUrl = text(glideFallback.toStringUrl());
                } else if (fallbackModel instanceof String fallbackString) {
                    parts.fallbackUrl = fallbackString;
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.fallbackUrl = "";
        }
        return parts;
    }

    /** Splits the final header map into the three named headers plus the rest as JSON (C2 copy). */
    private static void splitHeaders(Map<String, String> headers, PicParts parts) {
        if (headers == null || headers.isEmpty()) return;
        Map<String, String> extra = new LinkedHashMap<>();
        for (Map.Entry<String, String> entry : headers.entrySet()) {
            String key = entry.getKey();
            String value = text(entry.getValue());
            if ("Referer".equalsIgnoreCase(key)) parts.referer = value;
            else if ("Cookie".equalsIgnoreCase(key)) parts.cookie = value;
            else if ("User-Agent".equalsIgnoreCase(key)) parts.userAgent = value;
            else extra.put(text(key), value);
        }
        if (!extra.isEmpty()) parts.extraHeadersJson = App.gson().toJson(extra);
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /**
     * Main-thread-only one-shot completion for an @async call, with a
     * watchdog. The timeout completes with the given value; a late
     * background completion is a no-op. All callers complete from the
     * main thread (Handler), so no synchronization is needed. Copied
     * from B17HostApiImpl (same shape, B18 result type). Completing
     * also clears the serial loading guard.
     */
    private final class Completion<T> {
        private final B18Messages.Result<T> result;
        private boolean done;
        private final Runnable timeout;

        Completion(B18Messages.Result<T> result, long timeoutMs, T timeoutValue) {
            this.result = result;
            this.timeout = () -> complete(timeoutValue);
            handler.postDelayed(this.timeout, timeoutMs);
        }

        void complete(T value) {
            if (done) return;
            done = true;
            handler.removeCallbacks(timeout);
            loading = false;
            if (pendingCompletion == this) pendingCompletion = null;
            result.success(value);
        }

        boolean isDone() {
            return done;
        }
    }
