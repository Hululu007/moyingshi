/**
 * B8 B10: native side of the B10 Pigeon contract (mobile aggregate
 * search page, CollectFragment).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b10_collect_messages.dart}. The generated file
 * {@code B10Messages.java} is not committed; see docs/b8-b10-collect.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the site beans, so Dart never hard-codes locale strings
 * or composes filter/image values.
 *
 * <p>This impl holds the whole search session that CollectFragment held
 * as fragment fields (master lists, visible lists, paging, filter
 * group, similarity, progress), because the multi-site search arrives
 * through three LiveData streams that outlive any single @async call:
 * {@code getSearch()} per site, {@code getSearchProgress()} for the
 * totals, and {@code getResult()} for per-site page loads. Dart polls
 * the lightweight progress snapshot while the search (or a page load)
 * is pending and re-reads the full snapshot when the revision changes
 * (plan §4.6, no EventChannel). The observers are registered once per
 * session and removed by {@link #cancelSearch}; a second startSearch
 * supersedes the first (the ViewModel's epoch cancels the old futures).
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Mobile-only classes are never referenced
 * directly: grid geometry is re-implemented below (copied from
 * CollectFragment's Product calls, like B8); FolderActivity is opened
 * reflectively (B9 SiteDialog pattern) so its own B8 diversion still
 * applies; {@code VideoActivity.collect} and {@code SearchActivity}
 * exist in BOTH flavors with identical signatures. All strings used
 * here live in main res, so no runtime {@code mobileString} lookup is
 * needed. The similarity slider dialog is built inline from the same
 * LightDialog primitive SliderNumberDialog uses, because that helper
 * exposes no dismiss hook (see docs/b8-b10-collect.md V9).
 */
