    private B10Messages.B10CollectScreen buildSnapshot() {
        updateSelection();
        List<Collect> rows = getFilteredCollectItems();
        Collect active = getSelectedCollect(rows);
        String activeKey = active.getSite().getKey();
        List<B10Messages.B10CollectItem> items = new ArrayList<>();
        for (Vod item : active.getList()) items.add(toItem(item));
        boolean horizontal = Setting.getSearchUi() == 0;
        int columnCount = getCount();
        boolean isGrid = columnCount == 2;
        int span = 1;
        int imageWidthPx = 0;
        int imageHeightPx = 0;
        if (isGrid) {
            int column = searchColumn();
            int targetWidth = searchSpec(column)[0];
            int resultWidth = getResultWidth(horizontal);
            int resultPadding = ResUtil.dp2px(8);
            int available = resultWidth - resultPadding;
            span = SearchGridLayout.resolveSpanCount(column, targetWidth, available, ResUtil.dp2px(96),
                    ResUtil.dp2px(4));
            int width = SearchGridLayout.resolveItemWidth(resultWidth, resultPadding, span, ResUtil.dp2px(4));
            imageWidthPx = width;
            imageHeightPx = (int) (width / 0.75f);
        }
        // Empty state (CollectFragment.updateEmptyState, plus a general
        // empty text: native leaves a blank area when nothing matched
        // at all, this page shows the host empty title instead).
        boolean loading = "all".equals(activeKey) ? mPaging.hasPending() : mPaging.isPending(activeKey);
        boolean emptyVisible = false;
        String emptyText = "";
        if (mSimilarity > 0 && mSearchCompleted && !loading && active.getList().isEmpty()
                && hasRawResults(activeKey)) {
            emptyVisible = true;
            emptyText = mSimilarity == 100
                    ? activity.getString(R.string.search_filter_empty_exact)
                    : activity.getString(R.string.search_filter_empty, mSimilarity);
        } else if (mSearchCompleted && totalVisibleItems(rows) == 0) {
            emptyVisible = true;
            emptyText = activity.getString(R.string.widget_empty);
        }
        List<B10Messages.B10SourceItem> sources = new ArrayList<>();
        for (Collect row : rows) {
            String key = row.getSite().getKey();
            String progressText = "";
            if ("all".equals(key) && progressTotal > 0) progressText = progressCurrent + "/" + progressTotal;
            sources.add(new B10Messages.B10SourceItem.Builder()
                    .setSiteKey(key)
                    .setDisplayName(row.getSite().getDisplayName())
                    .setSelected(row.isSelected())
                    .setProgressText(progressText)
                    .build());
        }
        return new B10Messages.B10CollectScreen.Builder()
                .setTitle(getTitleText())
                .setGroups(new ArrayList<>(mGroups))
                .setCurrentGroup(mFilterGroup)
                .setCanFilterGroup(canFilterGroup())
                .setAllScopeLabel(activity.getString(R.string.search_scope_all))
                .setSources(sources)
                .setItems(items)
                .setActiveSiteKey(activeKey)
                .setColumnCount((long) columnCount)
                .setIsGrid(isGrid)
                .setGridSpanCount((long) span)
                .setCardImageWidthPx((long) imageWidthPx)
                .setCardImageHeightPx((long) imageHeightPx)
                .setSourceColumnWidthPx((long) collectWidthPx)
                .setHorizontalSources(horizontal)
                .setSimilarity((long) mSimilarity)
                .setSimilarityTitle(getSimilarityFilterTitle())
                .setEmptyVisible(emptyVisible)
                .setEmptyText(emptyText)
                .setErrorTitle(activity.getString(R.string.error_config_load))
                .setErrorMessage(lastErrorMessage)
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setProgressCurrent((long) progressCurrent)
                .setProgressTotal((long) progressTotal)
                .setSearchFinished(mSearchCompleted)
                .setHasPendingPage(mPaging.hasPending())
                .setCanLoadMore(canLoadMore(activeKey))
                .setRevision((long) revision)
                .build();
    }

    private int totalVisibleItems(List<Collect> rows) {
        int total = 0;
        // rows[0] is "all" (the concatenation of the rest); count the
        // site rows only.
        for (int i = 1; i < rows.size(); i++) total += rows.get(i).getList().size();
        return total;
    }

