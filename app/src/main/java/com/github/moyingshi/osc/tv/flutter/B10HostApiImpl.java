    @Override
    public void startSearch(String keyword, Boolean currentSite, String siteKey, String group, String pic,
            String wallPic, Long historyResumeCid, String historyResumeKey, Long historyResumeTargetCid,
            B10Messages.Result<B10Messages.B10CollectScreen> result) {
        // A second call supersedes the first: complete the stale calls
        // with the then-current snapshot (the ViewModel epoch cancels
        // the old search futures when the new search starts).
        completeSearch();
        completeLoadMore();
        this.keyword = text(keyword);
        this.entrySiteKey = text(siteKey);
        this.entryGroup = text(group);
        this.pic = text(pic);
        this.wallPic = text(wallPic);
        this.hrCid = historyResumeCid == null ? -1 : historyResumeCid.intValue();
        this.hrKey = text(historyResumeKey);
        this.hrTargetCid = historyResumeTargetCid == null ? -1 : historyResumeTargetCid.intValue();
        // Site-key rule (B9HostApiImpl.submitSearch, factored): under
        // current-site scope the entry key counts, or the home key when
        // it is empty; otherwise the key is the explicit filter (empty
        // = all sites). Callers pre-apply the native scope rule.
        if (Boolean.TRUE.equals(currentSite) && TextUtils.isEmpty(this.entrySiteKey)) {
            try {
                Site home = VodConfig.get().getHome();
                this.resolvedSiteKey = home == null ? "" : text(home.getKey());
            } catch (Throwable e) {
                e.printStackTrace();
                this.resolvedSiteKey = "";
            }
        } else {
            this.resolvedSiteKey = this.entrySiteKey;
        }
        mSimilarity = Setting.getSearchSimilarity();
        mFilterGroup = this.entryGroup;
        activeSiteKey = "all";
        mSearchCompleted = false;
        mPaging.clear();
        mAllCollectItems.clear();
        mVisibleItems.clear();
        mSiteOrder.clear();
        progressCurrent = 0;
        progressTotal = 0;
        lastErrorMessage = "";
        revision++;
        setSites();
        setWidth();
        mAllCollectItems.add(Collect.all());
        if (Setting.getSearchResultSort() == 1) {
            for (Site site : mSites) mAllCollectItems.add(new Collect(site, new ArrayList<>()));
        }
        if (mSites.isEmpty()) {
            // No searchable site in scope: nothing to wait for.
            mSearchCompleted = true;
            revision++;
            result.success(buildSnapshot());
            return;
        }
        viewModel = new ViewModelProvider(activity).get(SiteViewModel.class);
        viewModel.init();
        registerObservers();
        pendingSearchResult = result;
        searchWatchdog = () -> {
            if (pendingSearchResult == null) return;
            lastErrorMessage = activity.getString(R.string.error_play_timeout);
            revision++;
            completeSearch();
        };
        handler.postDelayed(searchWatchdog, SEARCH_TIMEOUT_MS);
        try {
            viewModel.searchContent(mSites, this.keyword, false);
        } catch (Throwable e) {
            e.printStackTrace();
            lastErrorMessage = activity.getString(R.string.error_play_timeout);
            revision++;
            completeSearch();
        }
    }

    private void registerObservers() {
        if (observersRegistered || viewModel == null) return;
        observersRegistered = true;
        searchObserver = this::onSearchResult;
        progressObserver = this::onSearchProgress;
        resultObserver = this::onPageResult;
        viewModel.getSearch().observeForever(searchObserver);
        viewModel.getSearchProgress().observeForever(progressObserver);
        viewModel.getResult().observeForever(resultObserver);
    }

    private void removeObservers() {
        if (!observersRegistered || viewModel == null) return;
        observersRegistered = false;
        if (searchObserver != null) viewModel.getSearch().removeObserver(searchObserver);
        if (progressObserver != null) viewModel.getSearchProgress().removeObserver(progressObserver);
        if (resultObserver != null) viewModel.getResult().removeObserver(resultObserver);
    }

    /** Completes the pending startSearch with the current snapshot, exactly once. */
    private void completeSearch() {
        if (pendingSearchResult == null) return;
        B10Messages.Result<B10Messages.B10CollectScreen> pending = pendingSearchResult;
        pendingSearchResult = null;
        if (searchWatchdog != null) handler.removeCallbacks(searchWatchdog);
        searchWatchdog = null;
        pending.success(buildSnapshot());
    }

    /** Completes the pending loadMore with the current snapshot, exactly once. */
    private void completeLoadMore() {
        if (pendingLoadMoreResult == null) return;
        B10Messages.Result<B10Messages.B10CollectScreen> pending = pendingLoadMoreResult;
        pendingLoadMoreResult = null;
        pendingLoadMoreSiteKey = "";
        if (loadMoreWatchdog != null) handler.removeCallbacks(loadMoreWatchdog);
        loadMoreWatchdog = null;
        pending.success(buildSnapshot());
    }

    /** Completes the pending loadMore once its site has no page in flight anymore. */
    private void maybeCompleteLoadMore() {
        if (pendingLoadMoreResult == null) return;
        if (mPaging.isPending(pendingLoadMoreSiteKey)) return;
        completeLoadMore();
    }

    @Override
    public B10Messages.B10Progress getProgress() {
        return new B10Messages.B10Progress.Builder()
                .setCurrent((long) progressCurrent)
                .setTotal((long) progressTotal)
                .setFinished(mSearchCompleted)
                .setRevision((long) revision)
                .setHasPendingPage(mPaging.hasPending())
                .build();
    }

    @Override
    public B10Messages.B10CollectScreen getSnapshot() {
        return buildSnapshot();
    }

    @Override
    public void cancelSearch() {
        completeSearch();
        completeLoadMore();
        if (viewModel != null) {
            try {
                viewModel.stopSearch();
            } catch (Throwable e) {
                e.printStackTrace();
            }
        }
        removeObservers();
        mPaging.clear();
        mAllCollectItems.clear();
        mVisibleItems.clear();
        mSites.clear();
        mGroups.clear();
        SiteHealthStore.flush();
    }

    // ---- Session observers: CollectFragment.setCollect / setSearch /
    // setSearchProgress, with the adapter calls replaced by state
    // updates (the snapshot builder renders from the same state). All
    // three run on the main thread (LiveData delivery).

    /** Mirrors CollectFragment.setCollect: one site's first page arrived. */
    private void onSearchResult(Result result) {
        if (result == null || result.getList().isEmpty()) return;
        List<Vod> items = new ArrayList<>(result.getList());
        Collect raw = addMasterCollect(items);
        raw.setPage(mPaging.getPage(raw.getSite().getKey()));
        mPaging.recordInitial(raw.getSite().getKey(), result.getPageCount(), SearchPageState.pageToken(items));
        boolean visiblePageHasItems = appendVisibleItems(raw.getSite().getKey(), items);
        if (matchFilter(raw.getSite())) {
            String pageSiteKey = raw.getSite().getKey();
            updateSelection();
            maybeLoadNextPage(pageSiteKey, true, visiblePageHasItems);
            if (!pageSiteKey.equals(activeSiteKey)) maybeLoadSelectedPage();
        }
        revision++;
    }

    /** Mirrors CollectFragment.setSearchProgress. */
    private void onSearchProgress(SearchProgress progress) {
        if (progress == null) return;
        progressCurrent = progress.current();
        progressTotal = progress.total();
        mSearchCompleted = progress.total() > 0 && progress.current() >= progress.total();
        revision++;
        if (mSearchCompleted) completeSearch();
    }

    /** Mirrors CollectFragment.setSearch: one per-site page load landed. */
    private void onPageResult(Result result) {
        if (result == null) return;
        boolean hasItems = !result.getList().isEmpty();
        String resultSiteKey = hasItems ? result.getVod().getSiteKey() : "";
        SearchPageState.Completion completion = mPaging.complete(resultSiteKey, hasItems, result.getPageCount(),
                SearchPageState.pageToken(result.getList()));
        if (!completion.handled()) return;
        Collect raw = findCollect(mAllCollectItems, completion.siteKey());
        if (completion.accepted() && raw != null) raw.setPage(completion.page());
        if (!completion.accepted()) {
            updateSelection();
            if (!completion.siteKey().equals(activeSiteKey)) maybeLoadSelectedPage();
            maybeCompleteLoadMore();
            revision++;
            return;
        }
        List<Vod> items = new ArrayList<>(result.getList());
        raw = addMasterCollect(items);
        String pageSiteKey = raw.getSite().getKey();
        raw.setPage(mPaging.getPage(pageSiteKey));
        boolean visiblePageHasItems = appendVisibleItems(pageSiteKey, items);
        if (matchFilter(raw.getSite())) {
            updateSelection();
            maybeLoadNextPage(pageSiteKey, true, visiblePageHasItems);
            if (!pageSiteKey.equals(activeSiteKey)) maybeLoadSelectedPage();
        } else {
            maybeLoadSelectedPage();
        }
        maybeCompleteLoadMore();
        revision++;
    }

    // ---- Session state: CollectFragment.setSites / setWidth and the
    // master/visible/filter helpers, copied line by line.

    private void setSites() {
        mSites.clear();
        for (Site site : VodConfig.get().getSites()) {
            if (!site.isSearchable()) continue;
            if (!TextUtils.isEmpty(resolvedSiteKey) && !site.getKey().equals(resolvedSiteKey)) continue;
            if (!TextUtils.isEmpty(entryGroup) && !site.inGroup(entryGroup)) continue;
            mSites.add(site);
        }
        // 固定模式严格按配置顺序,跳过健康度排序
        if (Setting.getSearchResultSort() != 1) SiteHealthStore.sortSites(mSites);
        mSiteOrder.clear();
        for (int i = 0; i < mSites.size(); i++) mSiteOrder.put(mSites.get(i).getKey(), i);
        mGroups.clear();
        if (!isSiteSearch() && !isGroupSearch()) mGroups.addAll(SiteGroupOrderStore.sort(Site.getGroups(mSites)));
    }

    private void setWidth() {
        int width = 0;
        int space = ResUtil.dp2px(48);
        int maxWidth = ResUtil.getScreenWidth(activity) / 2 - ResUtil.dp2px(40);
        for (Site site : mSites) width = Math.max(width, ResUtil.getTextWidth(site.getDisplayName(), 14));
        int contentWidth = width + space;
        int minWidth = ResUtil.dp2px(120);
        collectWidthPx = Math.max(minWidth, Math.min(contentWidth, maxWidth));
    }

    private boolean isSiteSearch() {
        return !TextUtils.isEmpty(resolvedSiteKey);
    }

    private boolean isGroupSearch() {
        return !TextUtils.isEmpty(entryGroup);
    }

    private boolean isHistoryResume() {
        return hrCid >= 0 && hrTargetCid >= 0 && !TextUtils.isEmpty(hrKey);
    }

    private Collect addMasterCollect(List<Vod> items) {
        Site site = items.get(0).getSite();
        Collect collect = findCollect(mAllCollectItems, site.getKey());
        if (collect == null) {
            collect = new Collect(site, new ArrayList<>());
            mAllCollectItems.add(collect);
        }
        collect.getList().addAll(items);
        return collect;
    }

    private boolean appendVisibleItems(String siteKey, List<Vod> items) {
        List<Vod> visible = SearchResultFilter.filter(items, keyword, mSimilarity);
        mVisibleItems.computeIfAbsent(siteKey, key -> new ArrayList<>()).addAll(visible);
        return !visible.isEmpty();
    }

    private void rebuildVisibleItems() {
        mVisibleItems.clear();
        for (int i = 1; i < mAllCollectItems.size(); i++) {
            Collect raw = mAllCollectItems.get(i);
            mVisibleItems.put(raw.getSite().getKey(), SearchResultFilter.filter(raw.getList(), keyword, mSimilarity));
        }
    }

    private List<Vod> getVisibleItems(String siteKey) {
        List<Vod> visible = mVisibleItems.get(siteKey);
        return visible == null ? new ArrayList<>() : new ArrayList<>(visible);
    }

    private Collect findCollect(List<Collect> items, String siteKey) {
        for (Collect item : items) if (item.getSite().getKey().equals(siteKey)) return item;
        return null;
    }

    private boolean matchFilter(Site site) {
        return TextUtils.isEmpty(mFilterGroup) || site.inGroup(mFilterGroup);
    }

    private boolean hasRawResults(String siteKey) {
        if (!"all".equals(siteKey)) {
            Collect raw = findCollect(mAllCollectItems, siteKey);
            return raw != null && !raw.getList().isEmpty();
        }
        for (int i = 1; i < mAllCollectItems.size(); i++) {
            Collect raw = mAllCollectItems.get(i);
            if (matchFilter(raw.getSite()) && !raw.getList().isEmpty()) return true;
        }
        return false;
    }

    private List<Collect> getFilteredCollectItems() {
        List<Collect> items = new ArrayList<>();
        Collect all = Collect.all();
        all.setSelected("all".equals(activeSiteKey));
        items.add(all);
        for (int i = 1; i < mAllCollectItems.size(); i++) {
            Collect raw = mAllCollectItems.get(i);
            if (!matchFilter(raw.getSite())) continue;
            String siteKey = raw.getSite().getKey();
            List<Vod> visible = getVisibleItems(siteKey);
            if (!SearchSourceVisibility.shouldShow(!visible.isEmpty())) continue;
            Collect item = new Collect(raw.getSite(), visible);
            item.setPage(mPaging.getPage(raw.getSite().getKey()));
            item.setSelected(raw.getSite().getKey().equals(activeSiteKey));
            all.getList().addAll(visible);
            items.add(item);
        }
        if (getSelectedCollect(items) == all) all.setSelected(true);
        return items;
    }

    private Collect getSelectedCollect(List<Collect> items) {
        for (Collect item : items) if (item.isSelected()) return item;
        return items.get(0);
    }

    /**
     * Mirrors CollectFragment.applyFilters' selection update (without
     * adapters): the active row is the filtered row matching the
     * previous active key, else "all".
     */
    private void updateSelection() {
        List<Collect> rows = getFilteredCollectItems();
        activeSiteKey = getSelectedCollect(rows).getSite().getKey();
    }

    private void maybeLoadNextPage(String siteKey, boolean rawPageHasItems, boolean visiblePageHasItems) {
        if (!siteKey.equals(activeSiteKey)) return;
        if (!mPaging.shouldContinue(siteKey, mSimilarity > 0, rawPageHasItems, visiblePageHasItems)) return;
        triggerPageLoad(siteKey);
    }

    private void maybeLoadSelectedPage() {
        if (mAllCollectItems.isEmpty()) return;
        String siteKey = activeSiteKey;
        Collect raw = findCollect(mAllCollectItems, siteKey);
        maybeLoadNextPage(siteKey, raw != null && !raw.getList().isEmpty(), !getVisibleItems(siteKey).isEmpty());
    }

    /** Mirrors CollectFragment.onLoadMore minus the CustomScroller. */
    private void triggerPageLoad(String siteKey) {
        if (viewModel == null || "all".equals(siteKey)) return;
        Collect raw = findCollect(mAllCollectItems, siteKey);
        if (raw == null || raw.getList().isEmpty()) return;
        int requestedPage = mPaging.getPage(siteKey) + 1;
        if (!mPaging.begin(siteKey, requestedPage)) return;
        try {
            viewModel.searchContent(raw.getSite(), keyword, false, String.valueOf(requestedPage));
        } catch (RuntimeException e) {
            e.printStackTrace();
            mPaging.cancelPending();
        }
    }

    // ---- Dart-driven actions.

    @Override
    public void loadMore(B10Messages.Result<B10Messages.B10CollectScreen> result) {
        completeLoadMore();
        String siteKey = activeSiteKey;
        if ("all".equals(siteKey) || viewModel == null) {
            result.success(buildSnapshot());
            return;
        }
        Collect raw = findCollect(mAllCollectItems, siteKey);
        if (raw == null || raw.getList().isEmpty()) {
            result.success(buildSnapshot());
            return;
        }
        int requestedPage = mPaging.getPage(siteKey) + 1;
        if (!mPaging.begin(siteKey, requestedPage)) {
            result.success(buildSnapshot());
            return;
        }
        pendingLoadMoreResult = result;
        pendingLoadMoreSiteKey = siteKey;
        loadMoreWatchdog = () -> {
            if (pendingLoadMoreResult == null) return;
            mPaging.cancelPending();
            completeLoadMore();
        };
        handler.postDelayed(loadMoreWatchdog, PAGE_TIMEOUT_MS);
        try {
            viewModel.searchContent(raw.getSite(), keyword, false, String.valueOf(requestedPage));
        } catch (RuntimeException e) {
            e.printStackTrace();
            mPaging.cancelPending();
            completeLoadMore();
        }
    }

    @Override
    public B10Messages.B10CollectScreen setActiveSource(String siteKey) {
        String key = text(siteKey);
        // Only rows on screen can be picked (native: taps come from the
        // adapter); ignore unknown keys.
        boolean known = "all".equals(key);
        if (!known) {
            for (Collect row : getFilteredCollectItems()) {
                if (row.getSite().getKey().equals(key)) {
                    known = true;
                    break;
                }
            }
        }
        if (known) {
            activeSiteKey = key;
            updateSelection();
            maybeLoadNextPage(activeSiteKey, hasRawResults(activeSiteKey),
                    !getVisibleItems(activeSiteKey).isEmpty());
        }
        revision++;
        return buildSnapshot();
    }

    @Override
    public B10Messages.B10CollectScreen setGroupFilter(String group) {
        mFilterGroup = text(group);
        updateSelection();
        maybeLoadSelectedPage();
        revision++;
        return buildSnapshot();
    }

    @Override
    public B10Messages.B10CollectScreen setColumn(Long column) {
        int value = column == null ? 1 : column.intValue();
        Setting.putSearchColumn(value == 2 ? 2 : 1);
        revision++;
        return buildSnapshot();
    }

    @Override
    public void openSimilarityDialog(B10Messages.Result<B10Messages.B10CollectScreen> result) {
        // SliderNumberDialog.show() exposes no dismiss hook, so the
        // dialog is built here from the same LightDialog primitive with
        // the same content (B3 openDetailOpenMode pattern); dismiss
        // (confirm, cancel, back, outside tap) completes the call on
        // every path. If this content drifts from SliderNumberDialog,
        // both must change together.
        boolean[] completed = new boolean[1];
        try {
            int current = Math.max(0, Math.min(mSimilarity, 100));
            MaterialTextView valueView = new MaterialTextView(activity);
            valueView.setText(formatSimilarityValue(current));
            valueView.setTextColor(Color.parseColor("#202124"));
            valueView.setTextSize(28);
            valueView.setGravity(Gravity.CENTER);
            Slider slider = new Slider(activity);
            slider.setLayoutDirection(View.LAYOUT_DIRECTION_LTR);
            slider.setValueFrom(0);
            slider.setValueTo(100);
            slider.setStepSize(1);
            slider.setTickVisible(false);
            slider.setValue(current);
            slider.setFocusable(true);
            slider.setFocusableInTouchMode(true);
            ColorStateList active = ColorStateList.valueOf(Color.parseColor("#3D5AFE"));
            ColorStateList inactive = ColorStateList.valueOf(Color.parseColor("#D0D5DD"));
            slider.setTrackActiveTintList(active);
            slider.setTrackInactiveTintList(inactive);
            slider.setThumbTintList(active);
            slider.setHaloTintList(active);
            LinearLayout container = new LinearLayout(activity);
            container.setLayoutDirection(View.LAYOUT_DIRECTION_LTR);
            container.setOrientation(LinearLayout.VERTICAL);
            int horizontal = ResUtil.dp2px(12);
            container.setPadding(horizontal, 0, horizontal, 0);
            container.addView(valueView, new LinearLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT,
                    ViewGroup.LayoutParams.WRAP_CONTENT));
            MaterialTextView hintView = new MaterialTextView(activity);
            hintView.setText(R.string.search_filter_similarity_hint);
            hintView.setTextColor(Color.parseColor("#5F6368"));
            hintView.setTextSize(14);
            hintView.setGravity(Gravity.CENTER);
            LinearLayout.LayoutParams hintParams = new LinearLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT,
                    ViewGroup.LayoutParams.WRAP_CONTENT);
            hintParams.topMargin = ResUtil.dp2px(8);
            container.addView(hintView, hintParams);
            LinearLayout.LayoutParams sliderParams = new LinearLayout.LayoutParams(
                    ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT);
            sliderParams.topMargin = ResUtil.dp2px(8);
            container.addView(slider, sliderParams);
            int[] selected = {current};
            slider.addOnChangeListener((source, value, fromUser) -> {
                selected[0] = Math.round(value);
                valueView.setText(formatSimilarityValue(selected[0]));
            });
            Dialog[] holder = new Dialog[1];
            View.OnClickListener onPositive = v -> {
                applySimilarity(selected[0]);
                if (holder[0] != null) holder[0].dismiss();
            };
            Dialog dialog = LightDialog.create(activity, activity.getString(R.string.search_filter_similarity),
                    container, activity.getString(R.string.dialog_positive), onPositive,
                    activity.getString(R.string.dialog_negative), null);
            holder[0] = dialog;
            slider.setOnKeyListener((view, keyCode, event) -> {
                if (KeyUtil.isEnterKey(event)) {
                    onPositive.onClick(view);
                    return true;
                }
                return false;
            });
            dialog.setOnShowListener(d -> slider.requestFocus());
            dialog.setOnDismissListener(d -> {
                if (completed[0]) return;
                completed[0] = true;
                result.success(buildSnapshot());
            });
            dialog.show();
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

    /** Mirrors CollectFragment.onSimilarityFilter's dialog callback. */
    private void applySimilarity(int value) {
        mSimilarity = Math.max(0, Math.min(value, 100));
        Setting.putSearchSimilarity(mSimilarity);
        rebuildVisibleItems();
        updateSelection();
        maybeLoadSelectedPage();
        revision++;
    }

    private static String formatSimilarityValue(int value) {
        return value + "%";
    }

    @Override
    public void openCollectItem(String itemId, String itemName, String itemPic, Boolean itemIsFolder,
            String itemSiteKey) {
        String id = text(itemId);
        String name = text(itemName);
        String rawPic = text(itemPic);
        String key = text(itemSiteKey);
        Vod item = new Vod();
        item.setId(id);
        item.setName(name);
        item.setPic(rawPic);
        Site site = VodConfig.get().getSite(key);
        if (site != null) item.setSite(site);
        if (Boolean.TRUE.equals(itemIsFolder)) {
            // FolderActivity is mobile-only: reflection (B9 SiteDialog
            // pattern). Its own start() diversion still applies, so a
            // B8-enabled device opens the Flutter category page.
            try {
                Class<?> folderClass = Class.forName(FOLDER_ACTIVITY_CLASS);
                if (isHistoryResume()) {
                    folderClass.getMethod("start", Activity.class, String.class, Result.class, int.class,
                            String.class, int.class).invoke(null, activity, key, Result.folder(item), hrCid,
                            hrKey, hrTargetCid);
                } else {
                    folderClass.getMethod("start", Activity.class, String.class, Result.class).invoke(null,
                            activity, key, Result.folder(item));
                }
            } catch (Throwable e) {
                e.printStackTrace();
                // Defensive fallback (B8 folder pattern): never leave a
                // tap silent.
                VideoActivity.collect(activity, key, id, name, rawPic.isEmpty() ? pic : rawPic, wallPic, keyword);
            }
            return;
        }
        if (isHistoryResume()) {
            HistoryResumeCoordinator.openSelected(activity, hrCid, hrKey, hrTargetCid, item);
            return;
        }
        String pic = rawPic.isEmpty() ? this.pic : rawPic;
        VideoActivity.collect(activity, key, id, name, pic, wallPic, keyword);
    }

    @Override
    public void recordSearch(String keyword) {
        String query = keyword == null ? "" : keyword.trim();
        if (query.isEmpty()) return;
        // Native SearchFragment.search() adds the keyword to the records
        // 250ms later (App.post delay); same here.
        App.post(() -> addRecord(query), 250);
    }

    /** Mirrors RecordAdapter.checkToAdd: dedupe, most recent first, max 10. */
    private void addRecord(String keyword) {
        List<String> records = getRecords();
        records.remove(keyword);
        records.add(0, keyword);
        while (records.size() > RECORD_LIMIT) records.remove(records.size() - 1);
        Setting.putKeyword(App.gson().toJson(records));
    }

    private static List<String> getRecords() {
        String json = Setting.getKeyword();
        if (TextUtils.isEmpty(json)) return new ArrayList<>();
        try {
            // Same parse as RecordAdapter.getItems().
            List<String> records = App.gson().fromJson(json,
                    TypeToken.getParameterized(List.class, String.class).getType());
            return records == null ? new ArrayList<>() : new ArrayList<>(records);
        } catch (Throwable e) {
            e.printStackTrace();
            return new ArrayList<>();
        }
    }

