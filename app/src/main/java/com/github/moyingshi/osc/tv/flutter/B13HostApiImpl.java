/**
 * B8 B13: native side of the B13 Pigeon contract (mobile home blocks B:
 * the JS widget sections, widgets inside the /home family).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b13_home_b_messages.dart}. The generated
 * file {@code B13Messages.java} is not committed; see docs/b8-b13-home-b.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the beans, so Dart never hard-codes locale strings or
 * computes display remarks.
 *
 * <p>All JavaScript runs here, host-side: {@link WidgetManager} loads
 * the four builtin scripts (Bangumi / Douban / Mikan / TMDB) through
 * {@code WidgetHost} (QuickJS) and posts one {@code Section} per widget
 * on the main thread, cache first and then fresh (a fresh load is
 * skipped while the 15-minute session throttle holds). This class only
 * accumulates those sections into one @async snapshot. Dart never
 * executes scripts and takes no JS dependency.
 *
 * <p>Completion rule ({@link #getWidgets}): the snapshot completes when
 * every builtin has delivered a first outcome (a section, or a
 * failure). A section that delivered only its cached items is held
 * briefly for its fresh result: once all four have a first outcome, a
 * 2s grace timer runs and the snapshot completes at its end — or
 * immediately if every section turns fresh/failed first. The 35s
 * watchdog completes with whatever has arrived, so the callback
 * completes exactly once on every path. An empty sections list hides
 * the whole area (native updateWidgetVisibility rule: visible iff
 * &gt;= 1 section).
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. {@code WidgetManager} / {@code WidgetHost} /
 * {@code WidgetItem} / {@code WidgetMetadata} / {@code WidgetModule}
 * are main-source-set, so direct references are safe.
 * {@code SearchActivity} exists in BOTH flavors with identical
 * {@code start(Activity, String)} signatures, so the direct reference
 * is safe (B2 precedent). {@code WidgetBrowseActivity} is mobile-only
 * and is opened via reflection (plan §4.8招4); the ProGuard keep
 * {@code -keep com.github.moyingshi.osc.tv.**} covers it. The only
 * string used here, {@code widget_more}, is main-res (verified per
 * directory). The widget geometry (104x140dp cards) is fixed numbers
 * in the Dart widget; {@code WidgetSectionAdapter} (mobile-only) is
 * not referenced at all.
 */
public class B13HostApiImpl implements B13Messages.B13HostApi {

    /** Widget load watchdog: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 35_000L;

    /** Grace after all four builtins delivered a first outcome, to let
     * cache-only sections catch their fresh result before the snapshot
     * is sent (see the class doc). */
    private static final long FRESH_GRACE_MS = 2_000L;

    private final FragmentActivity activity;
    private final Handler handler = new Handler(Looper.getMainLooper());

    /** True while a getWidgets one-shot load is in flight (B11: single load). */
    private boolean widgetsLoading;

    /** Host-side widget loader, created lazily on the first getWidgets call. */
    private WidgetManager widgetManager;

    /** Sections delivered so far in the current load, keyed by widget id (latest wins). */
    private final Map<String, WidgetManager.Section> pendingSections = new LinkedHashMap<>();

    /** Per-builtin outcome of the current load: true once fresh or failed (final). */
    private final Map<String, Boolean> pendingFinal = new LinkedHashMap<>();

    /** Pending @async result, completed by the load or by disposeWidgets(). */
    private B13Messages.Result<B13Messages.B13WidgetScreen> pendingResult;

    /** True once a completion has been sent for the current load. */
    private boolean[] pendingCompleted;

    private Runnable pendingTimeout;
    private Runnable pendingGrace;

    public B13HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public Boolean isB13Enabled() {
        return Setting.isFlutterB13Enabled();
    }

    @Override
    public void setB13Enabled(Boolean enabled) {
        Setting.putFlutterB13Enabled(Boolean.TRUE.equals(enabled));
    }

    // ------------------------------------------------------------------
    // Widget sections snapshot (host-side JS, one-shot, cache then fresh)
    // ------------------------------------------------------------------

    @Override
    public void getWidgets(B13Messages.Result<B13Messages.B13WidgetScreen> result) {
        if (!(activity instanceof C1ScreenActivity)) {
            // C0 engine: only the flag methods are ever called here, and
            // this engine never loads widget sections, so a wait would
            // always hit the watchdog. Complete empty at once.
            result.success(emptyScreen());
            return;
        }
        if (!Setting.isHomeWidget()) {
            // Native refreshWidgets() early-returns when the switch is
            // off: the whole area is hidden, so there is nothing to load.
            result.success(emptyScreen());
            return;
        }
        if (widgetsLoading) {
            result.error(new IllegalStateException("widgets load already in progress"));
            return;
        }
        widgetsLoading = true;
        pendingSections.clear();
        pendingFinal.clear();
        pendingResult = result;
        pendingCompleted = new boolean[1];
        if (widgetManager == null) widgetManager = new WidgetManager();
        pendingTimeout = () -> completeWithBest();
        handler.postDelayed(pendingTimeout, LOAD_TIMEOUT_MS);
        widgetManager.loadHome(new WidgetManager.Listener() {
            @Override
            public void onSection(WidgetManager.Section section) {
                if (pendingCompleted == null || pendingCompleted[0]) return;
                String widgetId = text(section.metadata.getId());
                pendingSections.put(widgetId, section);
                pendingFinal.put(widgetId, !section.fromCache);
                checkCompletion();
            }

            @Override
            public void onSectionFailed(String widgetId) {
                if (pendingCompleted == null || pendingCompleted[0]) return;
                pendingFinal.put(text(widgetId), true);
                checkCompletion();
            }
        });
    }

    /** Decides whether the current load can complete, and when. */
    private void checkCompletion() {
        if (pendingCompleted == null || pendingCompleted[0]) return;
        if (pendingFinal.size() < WidgetManager.BUILTINS.size()) return;
        boolean allFinal = true;
        for (Boolean fin : pendingFinal.values()) {
            if (!Boolean.TRUE.equals(fin)) {
                allFinal = false;
                break;
            }
        }
        if (allFinal) {
            completeWithBest();
            return;
        }
        if (pendingGrace != null) return;
        pendingGrace = () -> completeWithBest();
        handler.postDelayed(pendingGrace, FRESH_GRACE_MS);
    }

    /** Completes the pending load once, with the best available sections. */
    private void completeWithBest() {
        if (pendingCompleted == null || pendingCompleted[0]) return;
        pendingCompleted[0] = true;
        widgetsLoading = false;
        if (pendingTimeout != null) handler.removeCallbacks(pendingTimeout);
        if (pendingGrace != null) handler.removeCallbacks(pendingGrace);
        pendingTimeout = null;
        pendingGrace = null;
        B13Messages.Result<B13Messages.B13WidgetScreen> result = pendingResult;
        pendingResult = null;
        List<WidgetManager.Section> sections = new ArrayList<>(pendingSections.values());
        sections.sort((a, b) -> Integer.compare(
                WidgetManager.builtinOrder(text(a.metadata.getId())),
                WidgetManager.builtinOrder(text(b.metadata.getId()))));
        if (result != null) result.success(buildScreen(sections));
    }

    private static B13Messages.B13WidgetScreen emptyScreen() {
        return new B13Messages.B13WidgetScreen.Builder()
                .setSections(new ArrayList<>())
                .build();
    }

    /** Builds the snapshot from the delivered sections, in native display order. */
    private B13Messages.B13WidgetScreen buildScreen(List<WidgetManager.Section> sections) {
        List<B13Messages.B13WidgetSection> out = new ArrayList<>();
        for (WidgetManager.Section section : sections) {
            List<B13Messages.B13WidgetItem> items = new ArrayList<>();
            if (section.items != null) {
                for (WidgetItem item : section.items) items.add(toWidgetItem(item));
            }
            out.add(new B13Messages.B13WidgetSection.Builder()
                    .setWidgetId(text(section.metadata.getId()))
                    .setTitle(text(section.title()))
                    .setMoreLabel(activity.getString(R.string.widget_more))
                    .setItems(items)
                    .build());
        }
        return new B13Messages.B13WidgetScreen.Builder().setSections(out).build();
    }

    /** Flattens one WidgetItem the way WidgetSectionAdapter binds it. Null-safe: Pigeon fields are non-null. */
    private static B13Messages.B13WidgetItem toWidgetItem(WidgetItem item) {
        String title = text(item.getTitle());
        String remarks = text(item.getDisplayRemark());
        PicParts pic = resolvePic(title, WidgetManager.posterUrlWithHeaders(item));
        return new B13Messages.B13WidgetItem.Builder()
                .setTitle(title)
                .setRemarks(remarks)
                .setRemarksVisible(!remarks.isEmpty())
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    @Override
    public void openWidgetItem(String title) {
        // Same as VodFragment.onWidgetItemClick: search the tapped title
        // in the current site (B9-diverted when its flag is on, same as
        // native). A blank title would open an empty search; ignore it.
        if (TextUtils.isEmpty(title)) return;
        SearchActivity.start(activity, title);
    }

    @Override
    public void openWidgetMore(String widgetId) {
        // B8 B18 takes over the "more" opening (B13 V5): when the B18
        // flag is on, open the Flutter /widgets route on the shared C1
        // engine and finish this (Flutter) home screen — start-then-
        // finish, the B11 V10 G2 race risk (see docs/b8-b18-widget.md
        // §6). It must NOT go through WidgetBrowseActivity.start()
        // here, or the old Flutter home Activity would stay alive and
        // violate the single-C1-engine invariant. Flag off = the
        // original reflection path to the native browse page.
        if (TextUtils.isEmpty(widgetId)) return;
        if (Setting.isFlutterB18Enabled() && Util.isMobile()) {
            C1ScreenActivity.start(activity, C1ScreenActivity.ROUTE_WIDGETS + "?widgetId=" + encode(widgetId));
            activity.finish();
            return;
        }
        try {
            Class<?> clazz = Class.forName(
                    "com.github.moyingshi.osc.tv.ui.activity.WidgetBrowseActivity");
            Method start = clazz.getMethod("start", Activity.class, String.class);
            start.invoke(null, activity, widgetId);
        } catch (Throwable e) {
            e.printStackTrace();
        }
    }

    @Override
    public void disposeWidgets() {
        // The Dart widget is gone (home screen popped): destroy the
        // manager's executor threads, and complete any in-flight load
        // with the best available sections so its Result never dangles.
        if (widgetManager != null) {
            widgetManager.destroy();
            widgetManager = null;
        }
        completeWithBest();
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /** URL-encodes a route query value (B11 pattern). */
    private String encode(String value) {
        try {
            return URLEncoder.encode(value == null ? "" : value, "UTF-8");
        } catch (UnsupportedEncodingException e) {
            return value == null ? "" : value;
        }
    }

    /** Resolved image parts for one card, mirroring ImgUtil.load() semantics (C2/B2 copy). */
    private static final class PicParts {
        String url = "";
        String referer = "";
        String cookie = "";
        String userAgent = "";
        String extraHeadersJson = "";
        String fallbackUrl = "";
        String placeholderText = "！";
        int placeholderColor;
    }

    /**
     * Resolves one poster URL the way native loading does, without touching
     * ImgUtil (C2 copy, see docs/b8-c2-history.md §2.5): {@link
     * ImgUtil#getUrl(String)} already parses the {@code @Headers=} /
     * {@code @Cookie=} / {@code @Referer=} / {@code @User-Agent=}
     * suffixes and the douban referer policy, and its GlideUrl result
     * exposes the clean URL plus the final header map. Delegating to it
     * keeps Dart pixel-for-pixel in sync with native header handling and
     * cannot drift. The fallback URL is the same TmdbProxy auto-fallback
     * the native failure listener tries. Any failure degrades to the text
     * placeholder, exactly like native load()'s catch path; one bad
     * picture never fails the whole screen. Deliberately duplicated from
     * C2HostApiImpl/B2HostApiImpl/B8HostApiImpl/B12HostApiImpl (same for
     * the header split below): each batch must stay independently
     * revertible, so batches share no host helper. If any copy changes,
     * the others must change with it.
     */
    private static PicParts resolvePic(String name, String rawPic) {
        PicParts parts = new PicParts();
        // TextDrawable parity: the first character (or "！"), colored by
        // ColorGenerator.get400() of that same character.
        parts.placeholderText = name.isEmpty() ? "！" : name.substring(0, 1);
        parts.placeholderColor = ColorGenerator.get400(parts.placeholderText);
        try {
            Object model = ImgUtil.getUrl(rawPic);
            if (model instanceof GlideUrl glideUrl) {
                parts.url = text(glideUrl.toStringUrl());
                splitHeaders(glideUrl.getHeaders(), parts);
            } else if (model instanceof String dataUrl) {
                // "data:" URLs pass through getUrl() unchanged. Dart shows
                // the placeholder for them (Image.network cannot load
                // data: URIs); see docs/b8-c2-history.md.
                parts.url = dataUrl;
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.url = "";
        }
        try {
            String autoFallback = TmdbProxy.nextAutoImageUrl(text(rawPic));
            if (!TextUtils.isEmpty(autoFallback)) {
                Object fallbackModel = ImgUtil.getUrl(autoFallback);
                if (fallbackModel instanceof GlideUrl glideFallback) {
                    parts.fallbackUrl = text(glideFallback.toStringUrl());
                } else if (fallbackModel instanceof String fallbackString) {
                    parts.fallbackUrl = fallbackString;
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.fallbackUrl = "";
        }
        return parts;
    }

    /** Splits the final header map into the three named headers plus the rest as JSON (C2 copy). */
    private static void splitHeaders(Map<String, String> headers, PicParts parts) {
        if (headers == null || headers.isEmpty()) return;
        Map<String, String> extra = new LinkedHashMap<>();
        for (Map.Entry<String, String> entry : headers.entrySet()) {
            String key = entry.getKey();
            String value = text(entry.getValue());
            if ("Referer".equalsIgnoreCase(key)) parts.referer = value;
            else if ("Cookie".equalsIgnoreCase(key)) parts.cookie = value;
            else if ("User-Agent".equalsIgnoreCase(key)) parts.userAgent = value;
            else extra.put(text(key), value);
        }
        if (!extra.isEmpty()) parts.extraHeadersJson = App.gson().toJson(extra);
    }
}
