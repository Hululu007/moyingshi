    private B4Messages.B4EnhanceRow row(String key, int titleRes, String text, boolean error) {
        return new B4Messages.B4EnhanceRow.Builder()
                .setKey(key)
                .setTitle(activity.getString(titleRes))
                .setText(text == null ? "" : text)
                .setHasError(error)
                .build();
    }

    /** One row's summary text, mirroring SettingEnhanceFragment.safeRun(): a failure degrades to the host error text. */
    private B4Messages.B4EnhanceRow safeRow(String key, int titleRes, java.util.function.Supplier<String> supplier) {
        String text;
        boolean error = false;
        try {
            text = supplier.get();
            if (text == null) text = "";
        } catch (Throwable e) {
            e.printStackTrace();
            text = activity.getString(R.string.error_config_get);
            error = true;
        }
        return row(key, titleRes, text, error);
    }

    private B4Messages.B4EnhanceRow customCspRow() {
        String text;
        boolean error = false;
        try {
            CustomCspSetting.Status status = CustomCspSetting.status();
            if (!status.available()) {
                text = activity.getString(R.string.error_config_get);
                error = true;
            } else {
                CustomCspSetting.Count count = status.count();
                text = getSwitch(status.enabled()) + " · "
                        + activity.getString(R.string.setting_custom_csp_count, count.active(), count.enabled());
            }
        } catch (Throwable e) {
            e.printStackTrace();
            text = activity.getString(R.string.error_config_get);
            error = true;
        }
        return row("customCsp", R.string.setting_custom_csp, text, error);
    }

    private B4Messages.B4EnhanceRow shellProxyRow() {
        String text;
        boolean error = false;
        try {
            int count = ProxySetting.count();
            text = getSwitch(Setting.isShellProxy()) + " · "
                    + activity.getString(R.string.setting_proxy_rule_count, count);
        } catch (Throwable e) {
            e.printStackTrace();
            text = activity.getString(R.string.error_config_get);
            error = true;
        }
        return row("shellProxy", R.string.setting_shell_proxy, text, error);
    }

    private String getCspWarmupText() {
        int mode = Setting.getCspWarmupMode();
        if (mode == Setting.CSP_WARMUP_CUSTOM) {
            return activity.getString(R.string.setting_csp_warmup_custom_count, Setting.getCspWarmupSites().size());
        }
        return activity.getString(mode == Setting.CSP_WARMUP_DEFAULT
                ? R.string.setting_csp_warmup_default : R.string.setting_disable);
    }

    private String getSiteHealthText() {
        SiteHealthStore.Summary summary = SiteHealthStore.summary();
        String state = getSwitch(Setting.isSiteHealthSort());
        if (summary.siteCount <= 0) return state;
        return state + " · " + activity.getString(R.string.site_health_report_setting_summary,
                summary.siteCount, summary.sampleCount);
    }

