/**
 * B8 B4: native side of the B4 Pigeon contract (mobile enhance settings
 * page, the "/settings" family member "enhance").
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b4_enhance_messages.dart}. The
 * generated file {@code B4Messages.java} is not committed; see
 * docs/b8-b4-enhance.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the Setting/bean stores, so Dart never hard-codes locale
 * strings or recomputes a value. The row order is the native display
 * order (SettingEnhanceFragment.reorderItems()); the always-GONE
 * shellProxyConfig row is not in the snapshot.
 *
 * <p>Complex sub-flows stay native on purpose: every dialog runs here;
 * Dart only renders the snapshot and re-fetches after a dialog reports
 * a change. Dialog methods are {@code @async} on the Dart side and
 * complete exactly when the underlying state may have changed (see the
 * dialog contract in docs/b8-b3-settings-a.md §2.5); Dart never awaits
 * them, it attaches a refetch continuation.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. All dialogs, stores and configs referenced
 * here live in the main source set. {@code FileActivity} is referenced
 * directly because both flavors define it with the same package (the B2
 * V5 precedent: VideoActivity/SearchActivity); this screen has no
 * leanback entry, so the call is unreachable there. Every string
 * referenced here was verified to live in the main res/ tree (checked
 * per directory, not with a truncated grep — the B2
 * dialog_delete_record lesson), so no runtime {@code mobileString()}
 * resolution is needed in this batch.
 */
