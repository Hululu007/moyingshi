    @Override
    public void openSiteName(B4Messages.VoidResult result) {
        boolean[] completed = new boolean[1];
        try {
            // Async: completes when the dialog reports a change; closing
            // it without a change completes nothing (Dart does not await).
            SiteNameDialog.create(activity).onChanged(() -> completeOnce(result, completed)).show();
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

