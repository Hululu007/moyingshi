        rows.add(safeRow("playbackArtworkWall", R.string.setting_playback_artwork_wall,
                () -> getSwitch(Setting.isPlaybackArtworkWall())));
        rows.add(safeRow("driveCheck", R.string.setting_drive_check, () -> getSwitch(Setting.isDriveCheck())));
