/**
 * B8 B12: native side of the B12 Pigeon contract (mobile home blocks A:
 * banner carousel + continue watching, widgets inside the /home family).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b12_home_a_messages.dart}. The generated
 * file {@code B12Messages.java} is not committed; see docs/b8-b12-home-a.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the beans, so Dart never hard-codes locale strings,
 * cleans display names, or computes progress.
 *
 * <p>Banner data comes from the B11 shell's homeContent load: this class
 * NEVER calls {@code SiteViewModel.init()} or {@code homeContent()}
 * itself. {@code SiteViewModel.execute()} cancels the previous in-flight
 * {@code TaskType.RESULT} future, so a second homeContent() call would
 * cancel the B11 shell load (or be cancelled by it). {@link #getBanner}
 * only observes the shared activity-scoped {@code getResult()} LiveData
 * (value already present, or the next non-null value while a B11 refetch
 * is in flight). Continue watching is purely local
 * ({@code History.getForDisplay()}), so it is a synchronous call that
 * never waits on the network — the row shows immediately, like native
 * {@code VodFragment.initView()} does.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Mobile-only classes are never referenced
 * directly: {@code BannerAdapter} / {@code ContinueAdapter} /
 * {@code Product} are not used at all — the banner geometry (188dp,
 * 16dp side margins) and the continue geometry (104x140dp cards) are
 * fixed numbers in the Dart widgets, and the continue display-name
 * cleanup is replicated below (plan §4.8招3, drift warning inline).
 * {@code VideoActivity} / {@code SearchActivity} exist in BOTH flavors
 * with identical signatures, so direct references are safe (B2
 * precedent). {@code HistoryResumeCoordinator} and
 * {@code ActionCardHelper} are main-source-set classes. The only string
 * used here, {@code home_continue_watching}, is main-res (verified per
 * directory), as are {@code push_image} and the
 * {@code continue_placeholder} drawable.
 */
public class B12HostApiImpl implements B12Messages.B12HostApi {

    /** Banner load watchdog: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 35_000L;

    /** Native continue row cap (VodFragment.refreshContinue). */
    private static final int CONTINUE_MAX_ITEMS = 10;

    private final FragmentActivity activity;
    private final Handler handler = new Handler(Looper.getMainLooper());

    /** True while a getBanner one-shot observation is in flight (B11: single subscription). */
    private boolean bannerLoading;

    public B12HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public Boolean isB12Enabled() {
        return Setting.isFlutterB12Enabled();
    }

    @Override
    public void setB12Enabled(Boolean enabled) {
        Setting.putFlutterB12Enabled(Boolean.TRUE.equals(enabled));
    }

    // ------------------------------------------------------------------
    // Banner snapshot (piggyback on the B11 shell load, never a fresh fetch)
    // ------------------------------------------------------------------

    @Override
    public void getBanner(B12Messages.Result<B12Messages.B12BannerScreen> result) {
        if (!(activity instanceof C1ScreenActivity)) {
            // C0 engine: only the flag methods are ever called here, and
            // this engine's SiteViewModel never loads home content, so a
            // wait would always hit the watchdog. Complete empty at once.
            result.success(emptyBanner());
            return;
        }
        if (bannerLoading) {
            result.error(new IllegalStateException("banner load already in progress"));
            return;
        }
        bannerLoading = true;
        SiteViewModel viewModel = new ViewModelProvider(activity).get(SiteViewModel.class);
        // The B11 shell already loaded (or is loading) this value: take
        // it now when present instead of waiting for the next post.
        Result current = viewModel.getResult().getValue();
        if (current != null) {
            bannerLoading = false;
            result.success(buildBanner(current));
            return;
        }
        boolean[] completed = new boolean[1];
        AtomicReference<Observer<Result>> observerRef = new AtomicReference<>();
        Runnable timeout = () -> {
            if (completed[0]) return;
            completed[0] = true;
            bannerLoading = false;
            Observer<Result> observer = observerRef.get();
            if (observer != null) viewModel.getResult().removeObserver(observer);
            result.success(emptyBanner());
        };
        handler.postDelayed(timeout, LOAD_TIMEOUT_MS);
        Observer<Result> observer = loaded -> {
            if (loaded == null || completed[0]) return;
            completed[0] = true;
            bannerLoading = false;
            handler.removeCallbacks(timeout);
            viewModel.getResult().removeObserver(observerRef.get());
            result.success(buildBanner(loaded));
        };
        observerRef.set(observer);
        viewModel.getResult().observeForever(observer);
    }

    private static B12Messages.B12BannerScreen emptyBanner() {
        return new B12Messages.B12BannerScreen.Builder()
                .setItems(new ArrayList<>())
                .build();
    }

    /** Builds the banner snapshot from one home Result (error results carry an empty list). */
    private static B12Messages.B12BannerScreen buildBanner(Result loaded) {
        List<B12Messages.B12BannerItem> items = new ArrayList<>();
        if (loaded != null && loaded.getList() != null) {
            int index = 0;
            for (Vod vod : loaded.getList()) {
                items.add(toBannerItem(vod, index++));
            }
        }
        return new B12Messages.B12BannerScreen.Builder().setItems(items).build();
    }

    /** Flattens one banner Vod the way BannerAdapter binds it. Null-safe: Pigeon fields are non-null. */
    private static B12Messages.B12BannerItem toBannerItem(Vod vod, int index) {
        String name = text(vod.getName());
        String remarks = text(vod.getRemarks());
        String rawPic = text(vod.getPic());
        PicParts pic = resolvePic(name, rawPic);
        return new B12Messages.B12BannerItem.Builder()
                .setIndex((long) index)
                .setId(text(vod.getId()))
                .setName(name)
                .setRemarks(remarks)
                .setRemarksVisible(!remarks.isEmpty())
                .setIsAction(vod.isAction())
                .setAction(text(vod.getAction()))
                .setRawPic(rawPic)
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    @Override
    public void openBannerItem(Long index) {
        if (index == null) return;
        SiteViewModel viewModel = new ViewModelProvider(activity).get(SiteViewModel.class);
        Result current = viewModel.getResult().getValue();
        if (current == null || current.getList() == null) return;
        int position = index.intValue();
        if (position < 0 || position >= current.getList().size()) return;
        Vod item = current.getList().get(position);
        // Same as VodFragment.onBannerClick: action / index-site search /
        // detail with the raw vodPic (the detail page parses @Headers=
        // suffixes itself; a cleaned URL would drop auth headers).
        Site home = VodConfig.get().getHome();
        String key = home == null ? "" : text(home.getKey());
        if (item.isAction()) {
            ActionCardHelper.handleAction(activity, key, text(item.getAction()));
        } else if (home != null && home.isIndex()) {
            FlutterNav.openSearch(activity, text(item.getName()));
        } else {
            VideoActivity.start(activity, key, text(item.getId()), text(item.getName()),
                    text(item.getPic()), null);
        }
    }

    // ------------------------------------------------------------------
    // Continue watching snapshot (purely local, synchronous)
    // ------------------------------------------------------------------

    @Override
    public B12Messages.B12ContinueScreen getContinueWatching() {
        List<B12Messages.B12ContinueItem> items = new ArrayList<>();
        for (History history : History.getForDisplay()) {
            if (history.getDuration() > 0 && history.getPosition() < history.getDuration()) {
                items.add(toContinueItem(history));
            }
            if (items.size() >= CONTINUE_MAX_ITEMS) break;
        }
        return new B12Messages.B12ContinueScreen.Builder()
                .setTitle(activity.getString(R.string.home_continue_watching))
                .setItems(items)
                .build();
    }

    /** Flattens one History bean the way ContinueAdapter binds it. Null-safe: Pigeon fields are non-null. */
    private B12Messages.B12ContinueItem toContinueItem(History history) {
        String name = displayName(text(history.getVodName()));
        String remarks = text(history.getVodRemarks());
        String rawPic = text(history.getVodPic());
        long duration = history.getDuration();
        int progress = duration > 0 ? (int) (history.getPosition() * 100 / duration) : 0;
        progress = Math.max(0, Math.min(100, progress));
        PicParts pic = resolvePic(name, rawPic);
        return new B12Messages.B12ContinueItem.Builder()
                .setKey(text(history.getKey()))
                .setCid((long) history.getCid())
                .setDisplayName(name)
                .setRemarks(remarks)
                .setRemarksVisible(!remarks.isEmpty())
                .setProgressPercent((long) progress)
                .setHasRealPic(hasRealPic(rawPic))
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    /** Native ContinueAdapter rule: no picture, or the legacy push data-URI placeholder, shows the gradient. */
    private boolean hasRealPic(String rawPic) {
        return !TextUtils.isEmpty(rawPic)
                && !TextUtils.equals(rawPic, activity.getString(R.string.push_image));
    }

    @Override
    public void openContinueItem(Long cid, String key) {
        History history = findHistory(cid, key);
        if (history != null) HistoryResumeCoordinator.open(activity, history);
    }

    /** Finds a displayed item in a fresh snapshot by (cid, key); null when stale (C2 copy). */
    private static History findHistory(Long cid, String key) {
        if (cid == null || key == null) return null;
        for (History history : History.getForDisplay()) {
            if (history.getCid() == cid && TextUtils.equals(history.getKey(), key)) return history;
        }
        return null;
    }

    /**
     * ContinueAdapter.displayName, replicated (mobile-only class, plan
     * §4.8招3): file:// and similar technical strings are not shown as
     * titles — take the last segment; playlist files (.m3u8) take the
     * parent folder name; strip the extension and decode %XX. Plain
     * names pass through unchanged. If the mobile original changes,
     * this copy must change with it.
     */
    private static String displayName(String name) {
        if (name == null) return "";
        int scheme = name.indexOf("://");
        if (scheme < 0) return name;
        String clean = name.substring(scheme + 3);
        while (clean.startsWith("/")) clean = clean.substring(1);
        int lastSlash = clean.lastIndexOf('/');
        String last = lastSlash >= 0 ? clean.substring(lastSlash + 1) : clean;
        if (last.endsWith(".m3u8") || last.endsWith(".M3U8")) {
            clean = lastSlash > 0 ? clean.substring(0, lastSlash) : clean;
            lastSlash = clean.lastIndexOf('/');
            last = lastSlash >= 0 ? clean.substring(lastSlash + 1) : clean;
        }
        int dot = last.lastIndexOf('.');
        if (dot > 0) last = last.substring(0, dot);
        try {
            return Uri.decode(last);
        } catch (IllegalArgumentException e) {
            return last;
        }
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /** Resolved image parts for one card, mirroring ImgUtil.load() semantics (C2/B2 copy). */
    private static final class PicParts {
        String url = "";
        String referer = "";
        String cookie = "";
        String userAgent = "";
        String extraHeadersJson = "";
        String fallbackUrl = "";
        String placeholderText = "！";
        int placeholderColor;
    }

    /**
     * Resolves one vodPic the way native loading does, without touching
     * ImgUtil (C2 copy, see docs/b8-c2-history.md §2.5): {@link
     * ImgUtil#getUrl(String)} already parses the {@code @Headers=} /
     * {@code @Cookie=} / {@code @Referer=} / {@code @User-Agent=}
     * suffixes and the douban referer policy, and its GlideUrl result
     * exposes the clean URL plus the final header map. Delegating to it
     * keeps Dart pixel-for-pixel in sync with native header handling and
     * cannot drift. The fallback URL is the same TmdbProxy auto-fallback
     * the native failure listener tries. Any failure degrades to the text
     * placeholder, exactly like native load()'s catch path; one bad
     * picture never fails the whole screen. Deliberately duplicated from
     * C2HostApiImpl/B2HostApiImpl/B8HostApiImpl (same for the header
     * split below): each batch must stay independently revertible, so
     * batches share no host helper. If any copy changes, the others must
     * change with it.
     */
    private static PicParts resolvePic(String name, String rawPic) {
        PicParts parts = new PicParts();
        // TextDrawable parity: the first character (or "！"), colored by
        // ColorGenerator.get400() of that same character.
        parts.placeholderText = name.isEmpty() ? "！" : name.substring(0, 1);
        parts.placeholderColor = ColorGenerator.get400(parts.placeholderText);
        try {
            Object model = ImgUtil.getUrl(rawPic);
            if (model instanceof GlideUrl glideUrl) {
                parts.url = text(glideUrl.toStringUrl());
                splitHeaders(glideUrl.getHeaders(), parts);
            } else if (model instanceof String dataUrl) {
                // "data:" URLs pass through getUrl() unchanged. Dart shows
                // the placeholder for them (Image.network cannot load
                // data: URIs); see docs/b8-c2-history.md.
                parts.url = dataUrl;
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.url = "";
        }
        try {
            String autoFallback = TmdbProxy.nextAutoImageUrl(text(rawPic));
            if (!TextUtils.isEmpty(autoFallback)) {
                Object fallbackModel = ImgUtil.getUrl(autoFallback);
                if (fallbackModel instanceof GlideUrl glideFallback) {
                    parts.fallbackUrl = text(glideFallback.toStringUrl());
                } else if (fallbackModel instanceof String fallbackString) {
                    parts.fallbackUrl = fallbackString;
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.fallbackUrl = "";
        }
        return parts;
    }

    /** Splits the final header map into the three named headers plus the rest as JSON (C2 copy). */
    private static void splitHeaders(Map<String, String> headers, PicParts parts) {
        if (headers == null || headers.isEmpty()) return;
        Map<String, String> extra = new LinkedHashMap<>();
        for (Map.Entry<String, String> entry : headers.entrySet()) {
            String key = entry.getKey();
            String value = text(entry.getValue());
            if ("Referer".equalsIgnoreCase(key)) parts.referer = value;
            else if ("Cookie".equalsIgnoreCase(key)) parts.cookie = value;
            else if ("User-Agent".equalsIgnoreCase(key)) parts.userAgent = value;
            else extra.put(text(key), value);
        }
        if (!extra.isEmpty()) parts.extraHeadersJson = App.gson().toJson(extra);
    }
}
