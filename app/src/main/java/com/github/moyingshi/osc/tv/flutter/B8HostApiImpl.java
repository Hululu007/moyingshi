/**
 * B8 B8: native side of the B8 Pigeon contract (mobile category list,
 * the first network screen).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b8_category_messages.dart}. The generated file
 * {@code B8Messages.java} is not committed; see docs/b8-b8-category.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the site beans, so Dart never hard-codes locale strings
 * or composes filter/image values.
 *
 * <p>Data comes from a one-shot {@link SiteViewModel} subscription, the
 * same call TypeFragment makes ({@code categoryContent}): the stale
 * retained value is cleared first ({@code init()}), the observer is
 * registered with {@code observeForever} and removed on every path, and
 * a timeout guard completes the @async call even when the ViewModel was
 * cleared or the load hangs. Pagination state (hasMore / nextPage) is
 * computed here from {@code Result.pageCount}, mirroring
 * {@code CustomScroller}; Dart only passes the page number and the
 * current filter map.
 *
 * <p>Complex sub-flows stay native on purpose: opening a card (action /
 * index-site search / history-resume open / detail) and the long-press
 * search run here; Dart only renders, paginates and drills down inside
 * the family Navigator.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Mobile-only classes are never referenced
 * directly (grid geometry is re-implemented below, copied from C2/B2);
 * {@code VideoActivity.start} and {@code SearchActivity.start} exist in
 * BOTH the mobile and leanback source sets with identical signatures,
 * so a direct reference compiles for both flavors — the same pattern
 * {@code HomeWebBridge} already uses. All strings used here live in
 * main res, so no runtime {@code mobileString} lookup is needed.
 */
public class B8HostApiImpl implements B8Messages.B8HostApi {

    /** One-shot load timeout: every @async method must complete on all paths. */
    private static final long LOAD_TIMEOUT_MS = 35_000L;

    private final FragmentActivity activity;

    public B8HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public Boolean isB8Enabled() {
        return Setting.isFlutterB8Enabled();
    }

    @Override
    public void setB8Enabled(Boolean enabled) {
        Setting.putFlutterB8Enabled(enabled);
    }

    @Override
    public void getCategoryPage(String key, String typeJson, String typeId, String extendJson, Long page,
            B8Messages.Result<B8Messages.B8CategoryScreen> result) {
        int pageInt = page == null || page < 1 ? 1 : page.intValue();
        Class parsed;
        try {
            // objectFrom() is a bare Gson parse (no try/catch inside).
            parsed = Class.objectFrom(typeJson);
        } catch (Throwable e) {
            e.printStackTrace();
            parsed = null;
        }
        if (parsed == null) {
            result.success(errorScreen("", new ArrayList<>(), text(extendJson), pageInt, "", ""));
            return;
        }
        // Single assignment so the lambdas below can capture it.
        final Class clazz = parsed;
        // The effective filter map: the caller's map when one was sent
        // (an explicitly empty "{}" means "nothing selected", it must
        // NOT re-apply the init values); otherwise the Class filters'
        // init values, exactly like FolderFragment.getExtend().
        // categoryContent() takes a HashMap, not a Map.
        LinkedHashMap<String, String> extend = parseExtend(extendJson);
        boolean hasExtend = extendJson != null && !extendJson.isEmpty();
        if (!hasExtend) {
            for (Filter filter : clazz.getFilters()) {
                if (filter.getInit() != null) extend.put(filter.getKey(), filter.setSelected(filter.getInit()));
            }
        }
        List<B8Messages.B8FilterGroup> groups = toFilterGroups(clazz, extend);
        Site site = VodConfig.get().getSite(key);
        Style baseStyle = clazz.isFolder() ? Style.list()
                : site == null ? (clazz.getStyle() != null ? clazz.getStyle() : Style.rect())
                : site.getStyle(clazz.getStyle());
        // One-shot SiteViewModel subscription (see class javadoc). The
        // ViewModel is activity-scoped; onCleared() cancels the pending
        // load, and the timeout below still completes this call.
        SiteViewModel viewModel = new ViewModelProvider(activity).get(SiteViewModel.class);
        viewModel.init();
        boolean[] completed = new boolean[1];
        AtomicReference<Observer<Result>> observerRef = new AtomicReference<>();
        Runnable timeout = () -> {
            if (completed[0]) return;
            completed[0] = true;
            Observer<Result> observer = observerRef.get();
            if (observer != null) viewModel.getResult().removeObserver(observer);
            result.success(errorScreen(clazz.getTypeName(), groups, App.gson().toJson(extend), pageInt,
                    activity.getString(R.string.error_play_timeout),
                    groups.isEmpty() ? "" : activity.getString(R.string.home_filter_title)));
        };
        Handler handler = new Handler(Looper.getMainLooper());
        handler.postDelayed(timeout, LOAD_TIMEOUT_MS);
        Observer<Result> observer = loaded -> {
            if (loaded == null || completed[0]) return;
            completed[0] = true;
            handler.removeCallbacks(timeout);
            viewModel.getResult().removeObserver(observerRef.get());
            result.success(buildScreen(loaded, clazz, baseStyle, groups, extend, pageInt));
        };
        observerRef.set(observer);
        viewModel.getResult().observeForever(observer);
        viewModel.categoryContent(key, typeId, String.valueOf(pageInt), true, extend);
    }

    /** Builds the success snapshot for one loaded page. */
    private B8Messages.B8CategoryScreen buildScreen(Result loaded, Class clazz, Style baseStyle,
            List<B8Messages.B8FilterGroup> groups, Map<String, String> extend, int pageInt) {
        String title = clazz.getTypeName();
        String extendJson = App.gson().toJson(extend);
        String filterTitle = groups.isEmpty() ? "" : activity.getString(R.string.home_filter_title);
        String msg = loaded.getMsg();
        if (!TextUtils.isEmpty(msg)) {
            // Result.error(): the site reported a failure; same as the
            // native empty list, but with the host message for Dart.
            return errorScreen(title, groups, extendJson, pageInt, msg, filterTitle);
        }
        List<B8Messages.B8CategoryItem> items = new ArrayList<>();
        for (Vod item : loaded.getList()) items.add(toItem(item));
        // Per-page style override, exactly like TypeFragment.addVideo():
        // the first item's style wins when it has one, else the base.
        Style effective = loaded.getVod().getStyle(baseStyle);
        int columnCount;
        int imageWidthPx;
        int imageHeightPx;
        if (effective.isList()) {
            // List rows use a fixed 40dp thumb; no grid geometry.
            columnCount = 1;
            imageWidthPx = 0;
            imageHeightPx = 0;
        } else {
            columnCount = categoryColumn(effective);
            int[] spec = categorySpec(columnCount, effective);
            imageWidthPx = spec[0];
            imageHeightPx = spec[1];
        }
        int pageCount = loaded.getPageCount();
        boolean hasMore = pageInt < pageCount || pageCount == 0;
        int nextPage = items.isEmpty() ? pageInt : pageInt + 1;
        return new B8Messages.B8CategoryScreen.Builder()
                .setTitle(title)
                .setStyleType(effective.getType())
                .setStyleRatio((double) effective.getRatio())
                .setColumnCount((long) columnCount)
                .setCardImageWidthPx((long) imageWidthPx)
                .setCardImageHeightPx((long) imageHeightPx)
                .setFilters(groups)
                .setItems(items)
                .setHasMore(hasMore)
                .setPageCount((long) pageCount)
                .setNextPage((long) nextPage)
                .setExtendJson(extendJson)
                .setEmptyTitle(activity.getString(R.string.widget_empty))
                .setEmptyDescription("")
                .setErrorTitle(activity.getString(R.string.error_config_load))
                .setErrorMessage("")
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setFilterTitle(filterTitle)
                .build();
    }

    /** Error snapshot: empty items, no more pages, filters kept for Dart. */
    private B8Messages.B8CategoryScreen errorScreen(String title, List<B8Messages.B8FilterGroup> groups,
            String extendJson, int pageInt, String errorMessage, String filterTitle) {
        return new B8Messages.B8CategoryScreen.Builder()
                .setTitle(title)
                .setStyleType("rect")
                .setStyleRatio((double) Style.rect().getRatio())
                .setColumnCount(1L)
                .setCardImageWidthPx(0L)
                .setCardImageHeightPx(0L)
                .setFilters(groups)
                .setItems(new ArrayList<>())
                .setHasMore(false)
                .setPageCount(0L)
                .setNextPage((long) pageInt)
                .setExtendJson(extendJson)
                .setEmptyTitle(activity.getString(R.string.widget_empty))
                .setEmptyDescription("")
                .setErrorTitle(activity.getString(R.string.error_config_load))
                .setErrorMessage(errorMessage == null ? "" : errorMessage)
                .setRetryLabel(activity.getString(R.string.error_retry))
                .setFilterTitle(filterTitle)
                .build();
    }

    @Override
    public void openCategoryItem(String key, String itemId, String itemName, String itemPic, Boolean itemIsFolder,
            Boolean itemIsAction, String itemAction, Long historyResumeCid, String historyResumeKey,
            Long historyResumeTargetCid) {
        if (Boolean.TRUE.equals(itemIsFolder)) {
            // Defensive only: Dart intercepts folder taps for the
            // in-family drill-down, so this should never arrive. A tap
            // must never silently do nothing, so fall back to the
            // detail page with the folder name as the mark.
            VideoActivity.start(activity, key, text(itemId), text(itemName), text(itemPic), text(itemName));
            return;
        }
        if (Boolean.TRUE.equals(itemIsAction)) {
            ActionCardHelper.handleAction(activity, key, text(itemAction));
            return;
        }
        Site site = VodConfig.get().getSite(key);
        boolean historyResume = isHistoryResume(historyResumeCid, historyResumeKey, historyResumeTargetCid);
        if (site != null && site.isIndex()) {
            if (historyResume) {
                HistoryResumeCoordinator.openSearch(activity, historyResumeCid.intValue(), historyResumeKey,
                        historyResumeTargetCid.intValue(), text(itemName));
            } else {
                FlutterNav.openSearch(activity, text(itemName));
            }
            return;
        }
        if (historyResume) {
            // Same as TypeFragment.onItemClick: the selected item carries
            // the page site into the resume flow.
            Vod selected = new Vod();
            selected.setId(text(itemId));
            selected.setName(text(itemName));
            selected.setPic(text(itemPic));
            if (site != null) selected.setSite(site);
            HistoryResumeCoordinator.openSelected(activity, historyResumeCid.intValue(), historyResumeKey,
                    historyResumeTargetCid.intValue(), selected);
            return;
        }
        VideoActivity.start(activity, key, text(itemId), text(itemName), text(itemPic), null);
    }

    @Override
    public void searchCategoryItem(String keyword, Long historyResumeCid, String historyResumeKey,
            Long historyResumeTargetCid) {
        if (isHistoryResume(historyResumeCid, historyResumeKey, historyResumeTargetCid)) {
            HistoryResumeCoordinator.openSearch(activity, historyResumeCid.intValue(), historyResumeKey,
                    historyResumeTargetCid.intValue(), text(keyword));
        } else {
            FlutterNav.openSearch(activity, text(keyword));
        }
    }

    /** Mirrors TypeFragment.isHistoryResume(). */
    private static boolean isHistoryResume(Long cid, String key, Long targetCid) {
        return cid != null && cid >= 0 && targetCid != null && targetCid >= 0 && key != null && !key.isEmpty();
    }

    /** Filter groups with the selected value of each group marked from the extend map. */
    private static List<B8Messages.B8FilterGroup> toFilterGroups(Class clazz, Map<String, String> extend) {
        List<B8Messages.B8FilterGroup> groups = new ArrayList<>();
        for (Filter filter : clazz.getFilters()) {
            List<B8Messages.B8FilterValue> values = new ArrayList<>();
            for (Value value : filter.getValue()) {
                values.add(new B8Messages.B8FilterValue.Builder()
                        .setLabel(text(value.getN()))
                        .setValue(text(value.getV()))
                        .setSelected(text(value.getV()).equals(extend.get(filter.getKey())))
                        .build());
            }
            groups.add(new B8Messages.B8FilterGroup.Builder()
                    .setKey(text(filter.getKey()))
                    .setName(text(filter.getName()))
                    .setValues(values)
                    .build());
        }
        return groups;
    }

    /** Parses the Dart-sent extend map (a JSON object string); empty when absent or malformed. */
    private static LinkedHashMap<String, String> parseExtend(String extendJson) {
        LinkedHashMap<String, String> extend = new LinkedHashMap<>();
        if (extendJson == null || extendJson.isEmpty()) return extend;
        try {
            JsonObject object = App.gson().fromJson(extendJson, JsonObject.class);
            if (object != null) {
                for (Map.Entry<String, JsonElement> entry : object.entrySet()) {
                    JsonElement element = entry.getValue();
                    if (element != null && element.isJsonPrimitive()) extend.put(entry.getKey(), element.getAsString());
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
        }
        return extend;
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /** Flattens one Vod bean the way VodAdapter binds it. Null-safe: Pigeon fields are non-null. */
    private static B8Messages.B8CategoryItem toItem(Vod item) {
        String name = text(item.getName());
        PicParts pic = resolvePic(name, item.getPic());
        return new B8Messages.B8CategoryItem.Builder()
                .setId(text(item.getId()))
                .setName(name)
                .setYear(text(item.getYear()))
                .setRemarks(text(item.getRemarks()))
                .setSiteName(text(item.getSiteName()))
                .setSiteVisible(item.getSiteVisible() == View.VISIBLE)
                .setNameVisible(item.getNameVisible() == View.VISIBLE)
                .setRemarkVisible(item.getRemarkVisible() == View.VISIBLE)
                .setYearVisible(item.getYearVisible() == View.VISIBLE)
                .setIsFolder(item.isFolder())
                .setIsAction(item.isAction())
                .setAction(text(item.getAction()))
                .setPicUrl(pic.url)
                .setRawPic(text(item.getPic()))
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .build();
    }

    /** Resolved image parts for one card, mirroring ImgUtil.load() semantics. */
    private static final class PicParts {
        String url = "";
        String referer = "";
        String cookie = "";
        String userAgent = "";
        String extraHeadersJson = "";
        String fallbackUrl = "";
        String placeholderText = "！";
        int placeholderColor;
    }

    /**
     * Resolves one vodPic the way native loading does, without touching
     * ImgUtil: {@link ImgUtil#getUrl(String)} already parses the
     * {@code @Headers=} / {@code @Cookie=} / {@code @Referer=} /
     * {@code @User-Agent=} suffixes and the douban referer policy, and
     * its GlideUrl result exposes the clean URL plus the final header
     * map. Delegating to it keeps Dart pixel-for-pixel in sync with
     * native header handling and cannot drift. The fallback URL is the
     * same TmdbProxy auto-fallback the native failure listener tries.
     * Any failure degrades to the text placeholder, exactly like native
     * load()'s catch path; one bad picture never fails the whole screen.
     *
     * <p>Deliberately duplicated from B2HostApiImpl (same for the grid
     * geometry below): each batch must stay independently revertible, so
     * batches share no host helper. If either copy changes, the other
     * must change with it; see docs/b8-b2-keep.md.
     */
    private static PicParts resolvePic(String name, String rawPic) {
        PicParts parts = new PicParts();
        // TextDrawable parity: the first character (or "！"), colored by
        // ColorGenerator.get400() of that same character.
        parts.placeholderText = name.isEmpty() ? "！" : name.substring(0, 1);
        parts.placeholderColor = ColorGenerator.get400(parts.placeholderText);
        try {
            Object model = ImgUtil.getUrl(rawPic);
            if (model instanceof GlideUrl glideUrl) {
                parts.url = text(glideUrl.toStringUrl());
                splitHeaders(glideUrl.getHeaders(), parts);
            } else if (model instanceof String dataUrl) {
                // "data:" URLs pass through getUrl() unchanged. Dart shows
                // the placeholder for them (Image.network cannot load
                // data: URIs); see docs/b8-b2-keep.md.
                parts.url = dataUrl;
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.url = "";
        }
        try {
            String autoFallback = TmdbProxy.nextAutoImageUrl(text(rawPic));
            if (!TextUtils.isEmpty(autoFallback)) {
                Object fallbackModel = ImgUtil.getUrl(autoFallback);
                if (fallbackModel instanceof GlideUrl glideFallback) {
                    parts.fallbackUrl = text(glideFallback.toStringUrl());
                } else if (fallbackModel instanceof String fallbackString) {
                    parts.fallbackUrl = fallbackString;
                }
            }
        } catch (Throwable e) {
            e.printStackTrace();
            parts.fallbackUrl = "";
        }
        return parts;
    }

    /** Splits the final header map into the three named headers plus the rest as JSON. */
    private static void splitHeaders(Map<String, String> headers, PicParts parts) {
        if (headers == null || headers.isEmpty()) return;
        Map<String, String> extra = new LinkedHashMap<>();
        for (Map.Entry<String, String> entry : headers.entrySet()) {
            String key = entry.getKey();
            String value = text(entry.getValue());
            if ("Referer".equalsIgnoreCase(key)) parts.referer = value;
            else if ("Cookie".equalsIgnoreCase(key)) parts.cookie = value;
            else if ("User-Agent".equalsIgnoreCase(key)) parts.userAgent = value;
            else extra.put(text(key), value);
        }
        if (!extra.isEmpty()) parts.extraHeadersJson = App.gson().toJson(extra);
    }

    /**
     * Grid geometry. TypeFragment computes these through the mobile
     * Product/MobileWindow classes, which this main-source-set impl
     * cannot reference (leanback builds would fail: leanback Product has
     * different signatures and MobileWindow does not exist there). The
     * arithmetic below mirrors the mobile originals line by line (same
     * isWide/windowBounds/getCutout copies as C2/B2 — only the column
     * rule differs: TypeFragment uses the full Product.getColumn, not
     * KeepActivity's "3 unless wide"); if they change, all copies must
     * change with them. The clamps only guard degenerate preferences (a
     * zero column would crash both the native grid and the Flutter
     * grid); with shipped defaults they never fire.
     */

    /** Mirrors mobile Product.getColumn(Context, Style). */
    private int categoryColumn(Style style) {
        int count = isWide(activity) ? 7 : 5;
        count = count + (ResUtil.isPad() ? 1 : 0);
        int column = Math.abs(PlayerSetting.getSize() - count);
        if (style.isLand()) column -= 1;
        return Math.max(1, column);
    }

    /** Mirrors mobile Product.getSpec(Context, Style). */
    private int[] categorySpec(int column, Style style) {
        int space = ResUtil.dp2px(32) + ResUtil.dp2px(16 * (column - 1)) + getCutout(activity);
        if (style.isOval()) space += ResUtil.dp2px(column * 16);
        int width = Math.max(1, (windowWidth(activity) - space) / column);
        int height = Math.max(1, (int) (width / style.getRatio()));
        return new int[]{width, height};
    }

    /** Mirrors MobileWindow.isWide(): window width greater than height. */
    private static boolean isWide(Context context) {
        Rect bounds = windowBounds(context);
        return bounds.width() > bounds.height();
    }

    private static int windowWidth(Context context) {
        return windowBounds(context).width();
    }

    /** Mirrors MobileWindow.getBounds(). */
    private static Rect windowBounds(Context context) {
        WindowManager manager = (WindowManager) context.getSystemService(Context.WINDOW_SERVICE);
        if (manager != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            Rect bounds = manager.getCurrentWindowMetrics().getBounds();
            if (bounds.width() > 0 && bounds.height() > 0) return bounds;
        }
        DisplayMetrics metrics = new DisplayMetrics();
        if (manager != null) manager.getDefaultDisplay().getMetrics(metrics);
        if (metrics.widthPixels <= 0 || metrics.heightPixels <= 0) metrics = ResUtil.getDisplayMetrics(context);
        return new Rect(0, 0, metrics.widthPixels, metrics.heightPixels);
    }

    /** Mirrors mobile Product.getCutout(), including its bitwise-or quirk. */
    private static int getCutout(Context context) {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) return 0;
        DisplayCutout cutout = ResUtil.getDisplay(context).getCutout();
        if (cutout == null) return 0;
        int left = cutout.getSafeInsetLeft();
        int right = cutout.getSafeInsetRight();
        return left | right;
    }
}
