    @Override
    public B3Messages.B3DanmakuSettings getDanmakuSettings() {
        // The four-level visibility chain from
        // SettingDanmakuFragment.updateApiVisibility /
        // updateAutoVisibility / updateSpiderVisibility, computed here so
        // Dart only renders the visible flags.
        boolean load = DanmakuSetting.isLoad();
        boolean apiVisible = load;
        boolean autoVisible = load && (DanmakuSetting.hasValidApiUrl() || DanmakuSetting.isBundleSource());
        boolean spiderVisible = load && DanmakuSetting.hasValidApiUrl() && DanmakuSetting.isAuto();
        return new B3Messages.B3DanmakuSettings.Builder()
                .setScreenTitle(activity.getString(R.string.setting_danmaku))
                .setLoadTitle(activity.getString(R.string.danmaku_load))
                .setLoadText(getSwitch(load))
                .setApiTitle(activity.getString(R.string.danmaku_api))
                .setApiText(activity.getString(DanmakuSetting.hasValidApiUrl() ? R.string.yes : R.string.none))
                .setApiVisible(apiVisible)
                .setAutoTitle(activity.getString(R.string.danmaku_auto_load))
                .setAutoText(getSwitch(DanmakuSetting.isAuto()))
                .setAutoVisible(autoVisible)
                .setSpiderTitle(activity.getString(R.string.danmaku_spider_first))
                .setSpiderText(getSwitch(DanmakuSetting.isSpiderFirst()))
                .setSpiderVisible(spiderVisible)
                .build();
    }

