    @Override
    public void openRealtimeModel(B3Messages.VoidResult result) {
        // Mirrors SettingAiFragment.onRealtimeModel: while a model is
        // downloading or being deleted the native row does nothing.
        boolean[] completed = new boolean[1];
        try {
            RealtimeSubtitleController controller = RealtimeSubtitleController.get();
            if (controller.isModelDownloading() || controller.isModelDeleting()) {
                result.success();
                return;
            }
            String[] labels = ResUtil.getStringArray(R.array.select_realtime_subtitle_model);
            SubtitleSettingsDialog.showRealtimeModel(activity, labels, getRealtimeModelIndex(), controller.isModelReady(),
                    index -> selectRealtimeModel(index, result, completed),
                    () -> controller.deleteModel(error -> onRealtimeModelChanged(error, true, result, completed)));
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

    /** Mirrors SettingAiFragment.selectRealtimeModel(). */
    private void selectRealtimeModel(int index, B3Messages.VoidResult result, boolean[] completed) {
        String[] values = ResUtil.getStringArray(R.array.select_realtime_subtitle_model_value);
        if (values == null || index < 0 || index >= values.length) {
            completeOnce(result, completed);
            return;
        }
        Setting.putRealtimeSubtitleModel(values[index]);
        RealtimeSubtitleController controller = RealtimeSubtitleController.get();
        if (controller.isModelReady()) {
            completeOnce(result, completed);
            return;
        }
        // Download starts in the background; Dart polls getAiSettings()
        // while the snapshot says downloading, so progress stays live.
        // The progress listener is a no-op here (no EventChannel).
        controller.downloadModel((percent, fileName) -> {
        }, error -> onRealtimeModelChanged(error, false, result, completed));
    }

    /** Mirrors SettingAiFragment.onRealtimeModelChanged(). */
    private void onRealtimeModelChanged(String error, boolean deleted, B3Messages.VoidResult result, boolean[] completed) {
        if (TextUtils.isEmpty(error)) {
            Notify.show(deleted ? R.string.subtitle_realtime_model_delete_success : R.string.subtitle_realtime_model_download_success);
        } else {
            Notify.show(activity.getString(deleted ? R.string.subtitle_realtime_model_delete_failed : R.string.subtitle_realtime_model_download_failed, error));
        }
        completeOnce(result, completed);
    }

