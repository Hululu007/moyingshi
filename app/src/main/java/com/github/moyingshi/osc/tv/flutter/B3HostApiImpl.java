    private String getSwitch(boolean value) {
        return activity.getString(value ? R.string.setting_on : R.string.setting_off);
    }

    /** Clamps a stored index into an array, mirroring native direct indexing for valid states. */
    private static int clampIndex(int index, int length) {
        if (length <= 0) return 0;
        if (index < 0) return 0;
        if (index >= length) return length - 1;
        return index;
    }

    private static void completeOnce(B3Messages.VoidResult result, boolean[] completed) {
        if (!completed[0]) {
            completed[0] = true;
            result.success();
        }
    }

    /** One row's summary text, mirroring SettingAdFragment.safeRun(): a failure degrades to the host error text. */
    private static final class RowText {
        String text = "";
        boolean error;
    }

    private RowText safeRow(java.util.function.Supplier<String> supplier) {
        RowText row = new RowText();
        try {
            row.text = supplier.get();
            if (row.text == null) row.text = "";
        } catch (Throwable e) {
            e.printStackTrace();
            row.text = activity.getString(R.string.error_config_get);
            row.error = true;
        }
        return row;
    }

    private DanmakuApiHostFragment danmakuHostFragment() {
        FragmentManager fm = activity.getSupportFragmentManager();
        Fragment existing = fm.findFragmentByTag(TAG_DANMAKU_HOST);
        if (existing instanceof DanmakuApiHostFragment host) return host;
        DanmakuApiHostFragment host = new DanmakuApiHostFragment();
        fm.beginTransaction().add(host, TAG_DANMAKU_HOST).commitNow();
        return host;
    }

    /**
     * Headless parent fragment for the reflectively opened
     * DanmakuApiDialog (see {@link #openDanmakuApi}). It carries no UI
     * and lives for the host Activity's lifetime; the dialog calls
     * {@link DanmakuListener#setDanmakuApi(String)} on it, which writes
     * the URL and completes the pending call. Public static with an
     * implicit no-arg constructor so the FragmentManager can restore it
     * after process death (its pending result is null then, and the
     * call is a no-op).
     */
    public static class DanmakuApiHostFragment extends Fragment implements DanmakuListener {
        private B3Messages.VoidResult pendingResult;
        private boolean[] pendingCompleted;

        void setPendingResult(B3Messages.VoidResult result, boolean[] completed) {
            pendingResult = result;
            pendingCompleted = completed;
        }

        @Override
        public void setDanmakuApi(String url) {
            DanmakuSetting.putApiUrl(url);
            if (pendingResult != null && pendingCompleted != null && !pendingCompleted[0]) {
                pendingCompleted[0] = true;
                pendingResult.success();
            }
            pendingResult = null;
            pendingCompleted = null;
        }
    }
