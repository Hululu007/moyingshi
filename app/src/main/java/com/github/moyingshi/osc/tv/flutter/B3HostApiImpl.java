/**
 * B8 B3: native side of the B3 Pigeon contract (mobile TMDB / AI / ad /
 * danmaku settings pages, the "/settings" family).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b3_settings_a_messages.dart}. The
 * generated file {@code B3Messages.java} is not committed; see
 * docs/b8-b3-settings-a.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources and the Setting/DanmakuSetting beans, so Dart never
 * hard-codes locale strings or recomputes visibility rules.
 *
 * <p>Complex sub-flows stay native on purpose: every dialog (TMDB
 * source, detail open/theme pickers, AI config, personal-recommendation
 * confirm, feedback manager, realtime-model picker, number pickers,
 * ad-rule manager, ad-block stats, intro-skip kinds, danmaku API) runs
 * here; Dart only renders snapshots and re-fetches after a dialog
 * reports a change. Dialog methods are {@code @async} on the Dart side
 * and complete exactly when the underlying state may have changed (see
 * the dialog contract in docs/b8-b3-settings-a.md); Dart never awaits
 * them, it attaches a refetch continuation.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. Four dialogs exist only in the mobile
 * source set ({@code DanmakuApiDialog},
 * {@code RecommendationFeedbackDialog}, {@code AdRuleManageDialog},
 * {@code AdBlockStatsDialog}) and are opened reflectively (plan §4.8,
 * move 4; the D5 SyncDialog precedent from C2/B2). R8 keeps every app
 * member name ({@code proguard-rules.pro} keeps
 * {@code com.github.moyingshi.osc.tv.**}), so the reflective lookups
 * survive release builds. On leanback this screen has no entry point,
 * so a reflection failure here is unreachable in practice. Every
 * string and array referenced here was verified to live in the main
 * res/ tree (checked per directory, not with a truncated grep — the
 * B2 dialog_delete_record lesson), so no runtime
 * {@code mobileString()} resolution is needed in this batch.
 */
