    @Override
    public void openAdRuleManage(B3Messages.VoidResult result) {
        // Async: AdRuleManageDialog lives in the mobile source set (and a
        // leanback copy), so this main-source-set impl opens it
        // reflectively. Its nested Callback interface is implemented with
        // a dynamic proxy; onRuleChanged fires when a rule changes.
        // Closing it without a change completes nothing, and Dart does
        // not await these calls.
        boolean[] completed = new boolean[1];
        try {
            Class<?> dialogClass = Class.forName("com.github.moyingshi.osc.tv.ui.dialog.AdRuleManageDialog");
            Class<?> callbackClass = Class.forName("com.github.moyingshi.osc.tv.ui.dialog.AdRuleManageDialog$Callback");
            Object dialog = dialogClass.getMethod("create").invoke(null);
            Object callback = Proxy.newProxyInstance(getClass().getClassLoader(), new Class<?>[]{callbackClass},
                    (proxy, method, args) -> {
                        if ("onRuleChanged".equals(method.getName())) {
                            completeOnce(result, completed);
                            return null;
                        }
                        if ("toString".equals(method.getName())) return "B3AdRuleCallback";
                        if ("hashCode".equals(method.getName())) return System.identityHashCode(proxy);
                        if ("equals".equals(method.getName())) return proxy == args[0];
                        return null;
                    });
            dialogClass.getMethod("show", FragmentActivity.class, callbackClass).invoke(dialog, activity, callback);
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

