    @Override
    public void openDanmakuApi(B3Messages.VoidResult result) {
        // Async: DanmakuApiDialog lives in the mobile source set and its
        // only entry is show(Fragment) — it calls setDanmakuApi() on its
        // parent fragment (DanmakuListener, main-visible). A headless
        // fragment of this class plays that parent role: it is attached
        // to this Activity, the dialog is shown into its child fragment
        // manager reflectively, and the positive button reaches this
        // impl through setDanmakuApi(). Closing the dialog without
        // saving completes nothing, and Dart does not await these calls.
        boolean[] completed = new boolean[1];
        try {
            DanmakuApiHostFragment host = danmakuHostFragment();
            host.setPendingResult(result, completed);
            Class<?> dialogClass = Class.forName("com.github.moyingshi.osc.tv.ui.dialog.DanmakuApiDialog");
            dialogClass.getMethod("show", Fragment.class).invoke(null, host);
        } catch (Throwable e) {
            e.printStackTrace();
            if (!completed[0]) {
                completed[0] = true;
                result.error(e);
            }
        }
    }

