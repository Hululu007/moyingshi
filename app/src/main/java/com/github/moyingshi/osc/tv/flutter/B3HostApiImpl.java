    /** Mirrors SettingAiFragment.setRealtimeModelStatus() + model text helpers. */
    private String getRealtimeModelText() {
        RealtimeSubtitleController controller = RealtimeSubtitleController.get();
        if (controller.isModelDownloading() && controller.getModelDownloadProgress() > 0) {
            return modelProgressStatusText(controller.getModelDownloadProgress());
        }
        int status = controller.isModelDeleting() ? R.string.subtitle_realtime_model_deleting : controller.isModelDownloading() ? R.string.subtitle_realtime_model_downloading : controller.isModelReady() ? R.string.subtitle_realtime_model_ready : R.string.subtitle_realtime_model_missing;
        return modelStatusText(status);
    }

    private String modelProgressStatusText(int progress) {
        int index = getRealtimeModelIndex();
        String label = realtimeModelLabel(index);
        return activity.getString(R.string.subtitle_realtime_model_status, label, activity.getString(R.string.subtitle_realtime_model_downloading_progress, progress));
    }

    private String modelStatusText(int status) {
        int index = getRealtimeModelIndex();
        String label = realtimeModelLabel(index);
        return activity.getString(R.string.subtitle_realtime_model_status, label, activity.getString(status));
    }

    private String realtimeModelLabel(int index) {
        String[] labels = ResUtil.getStringArray(R.array.select_realtime_subtitle_model);
        if (labels != null && index >= 0 && index < labels.length) return labels[index];
        return Setting.getRealtimeSubtitleModel();
    }

    /** Mirrors SettingAiFragment.getRealtimeModelIndex(). */
    private int getRealtimeModelIndex() {
        String[] values = ResUtil.getStringArray(R.array.select_realtime_subtitle_model_value);
        if (values == null) return 0;
        for (int i = 0; i < values.length; i++) if (TextUtils.equals(values[i], Setting.getRealtimeSubtitleModel())) return i;
        return 0;
    }

