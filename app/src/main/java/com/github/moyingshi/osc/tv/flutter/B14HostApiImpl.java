    @Override
    public void fetchServerCandidates(String url, String token,
            B14Messages.Result<B14Messages.B14ImportPreview> result) {
        Completion<B14Messages.B14ImportPreview> completion =
                new Completion<>(result, IMPORT_FETCH_TIMEOUT_MS, preview(false,
                        activity.getString(R.string.error_play_timeout), "", new ArrayList<>(), 0, 0));
        String trimmed = url == null ? "" : url.trim();
        if (!trimmed.startsWith("http://") && !trimmed.startsWith("https://")) {
            completion.complete(preview(false, activity.getString(R.string.following_server_invalid),
                    "", new ArrayList<>(), 0, 0));
            return;
        }
        Task.execute(() -> {
            try {
                FollowingSettings.setServerImportEnabled(true);
                List<AlistSubscriptionImporter.Candidate> candidates =
                        AlistSubscriptionImporter.fetch(trimmed, token == null ? "" : token);
                App.post(() -> {
                    if (completion.isDone()) return;
                    if (candidates == null || candidates.isEmpty()) {
                        completion.complete(preview(false,
                                activity.getString(R.string.following_server_empty),
                                "", new ArrayList<>(), 0, 0));
                        return;
                    }
                    pendingCandidates = candidates;
                    List<String> lines = new ArrayList<>();
                    int limit = Math.min(20, candidates.size());
                    for (int i = 0; i < limit; i++) {
                        AlistSubscriptionImporter.Candidate candidate = candidates.get(i);
                        String line = candidate.title + " · S" + (candidate.season + 1);
                        if (candidate.currentEpisodes > 0) line += " · E" + candidate.currentEpisodes;
                        lines.add(line);
                    }
                    completion.complete(preview(true, "", activity.getString(R.string.following_server_preview_title),
                            lines, candidates.size() - limit, candidates.size()));
                });
            } catch (Throwable error) {
                App.post(() -> {
                    if (completion.isDone()) return;
                    completion.complete(preview(false, text(error.getMessage()), "", new ArrayList<>(), 0, 0));
                });
            }
        });
    }

    @Override
    public void importServerCandidates(B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, IMPORT_TIMEOUT_MS, action(false, "", ""));
        List<AlistSubscriptionImporter.Candidate> candidates = pendingCandidates;
        if (candidates == null || candidates.isEmpty()) {
            completion.complete(action(false, "", ""));
            return;
        }
        pendingCandidates = null;
        Task.execute(() -> {
            AlistSubscriptionImporter.ImportResult imported =
                    AlistSubscriptionImporter.importCandidates(candidates);
            App.post(() -> {
                if (completion.isDone()) return;
                completion.complete(action(true, activity.getString(R.string.following_server_result,
                        imported.created, imported.updated), ""));
            });
        });
    }

