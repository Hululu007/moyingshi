    @Override
    public void getFollowing(Long filterIndex, B14Messages.Result<B14Messages.B14FollowingScreen> result) {
        int filter = filterIndex == null ? FILTER_ALL : filterIndex.intValue();
        if (filter < FILTER_ALL || filter > FILTER_FAILED) filter = FILTER_ALL;
        int filterValue = filter;
        Completion<B14Messages.B14FollowingScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, errorScreen(filterValue));
        Task.execute(() -> {
            FollowingNotifier.createChannel();
            FollowingScheduler.ensurePeriodic(activity);
            FollowingScheduler.enqueueDueNow(activity);
            List<Following> rows = filteredRows(filterValue);
            B14Messages.B14FollowingScreen screen = buildScreen(filterValue, rows);
            App.post(() -> {
                if (completion.isDone()) return;
                lastRows = rows;
                completion.complete(screen);
            });
        });
    }

    @Override
    public void checkAll(B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, CHECK_ALL_TIMEOUT_MS, action(false, "", ""));
        Notify.show(R.string.following_checking);
        Task.execute(() -> {
            List<Following> items = FollowingStore.list();
            boolean success = false;
            FollowingUpdateCoordinator coordinator = new FollowingUpdateCoordinator();
            for (Following item : items) success |= coordinator.checkNow(item.identityKey, true);
            boolean finalSuccess = success;
            App.post(() -> {
                if (completion.isDone()) return;
                Notify.show(finalSuccess ? R.string.following_check_done : R.string.following_check_failed);
                completion.complete(action(finalSuccess, "", ""));
            });
        });
    }

    @Override
    public void checkItem(String identityKey, B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, CHECK_TIMEOUT_MS, action(false, "", ""));
        Task.execute(() -> {
            boolean success = new FollowingUpdateCoordinator().checkNow(identityKey, true);
            App.post(() -> {
                if (completion.isDone()) return;
                Notify.show(success ? R.string.following_check_done : R.string.following_check_failed);
                completion.complete(action(success, "", ""));
            });
        });
    }

    @Override
    public void markRead(String identityKey, B14Messages.Result<B14Messages.B14ActionResult> result) {
        runMarkRead(identityKey,
                new Completion<>(result, ACTION_TIMEOUT_MS, action(false, "", "")));
    }

    private void runMarkRead(String identityKey, Completion<B14Messages.B14ActionResult> completion) {
        FollowingPlaybackBridge.markReadAllAsync(List.of(identityKey), error -> App.post(() -> {
            if (completion.isDone()) return;
            completion.complete(action(error == null, "", ""));
        }));
    }

    @Override
    public void markAllRead(B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, ACTION_TIMEOUT_MS, action(false, "", ""));
        List<String> keys = new ArrayList<>();
        for (Following item : lastRows) {
            if (item.hasUpdate && !TextUtils.isEmpty(item.identityKey)) keys.add(item.identityKey);
        }
        if (keys.isEmpty()) {
            completion.complete(action(true, "", ""));
            return;
        }
        FollowingPlaybackBridge.markReadAllAsync(keys, error -> App.post(() -> {
            if (completion.isDone()) return;
            completion.complete(action(error == null, "", ""));
        }));
    }

    @Override
    public void toggleNotify(String identityKey, B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, NOTIFY_TIMEOUT_MS, action(false, "", ""));
        Task.execute(() -> {
            Following item = FollowingStore.find(identityKey);
            if (item == null) {
                App.post(() -> completion.complete(action(false, "", "")));
                return;
            }
            boolean enabled = !item.notifyEnabled;
            if (!enabled) {
                FollowingPlaybackBridge.setNotifyEnabledAsync(identityKey, false, error -> App.post(() -> {
                    if (completion.isDone()) return;
                    completion.complete(action(error == null, "", ""));
                }));
                return;
            }
            if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU
                    || ContextCompat.checkSelfPermission(activity, Manifest.permission.POST_NOTIFICATIONS)
                            == PackageManager.PERMISSION_GRANTED) {
                enableNotify(identityKey, completion);
                return;
            }
            App.post(() -> PermissionX.init(activity)
                    .permissions(Manifest.permission.POST_NOTIFICATIONS)
                    .request(new PermissionCallback(granted -> {
                        if (Boolean.TRUE.equals(granted)) {
                            enableNotify(identityKey, completion);
                        } else {
                            Notify.show(R.string.following_notification_permission_hint);
                            if (!completion.isDone()) completion.complete(action(true, "", ""));
                        }
                    })));
        });
    }

    @Override
    public void followNextSeason(String identityKey, B14Messages.Result<B14Messages.B14ActionResult> result) {
        Completion<B14Messages.B14ActionResult> completion =
                new Completion<>(result, ACTION_TIMEOUT_MS, action(false, "", ""));
        Task.execute(() -> {
            Following item = FollowingStore.find(identityKey);
            if (item == null || item.latestReleasedSeason <= item.trackedSeason
                    || TextUtils.isEmpty(item.seriesKey)) {
                App.post(() -> completion.complete(action(false, "", "")));
                return;
            }
            String newKey = FollowingIdentity.identityKey(item.seriesKey, item.latestReleasedSeason);
            if (FollowingStore.find(newKey) != null) {
                App.post(() -> completion.complete(action(true, "", newKey)));
                return;
            }
            Following next = copyForNextSeason(item, newKey);
            FollowingSource source = FollowingStore.preferredSource(item.identityKey);
            if (source != null) {
                source = source.copy();
                source.followingKey = newKey;
                source.playableSeason = next.trackedSeason;
                source.playableEpisode = 0;
                source.playableCount = 0;
                source.lastProbeAt = 0;
                source.lastError = "";
            }
            if (source == null) {
                source = new FollowingSource();
                source.followingKey = newKey;
                source.cid = next.cid;
                source.siteKey = next.siteKey;
                source.vodId = next.vodId;
                source.vodName = next.vodName;
                source.vodPic = next.vodPic;
                source.preferred = true;
            }
            FollowingSource finalSource = source;
            try {
                FollowingStore.saveNew(next, finalSource);
                App.post(() -> {
                    if (completion.isDone()) return;
                    FollowingScheduler.enqueueDueNow(activity);
                    Notify.show(R.string.following_added);
                    completion.complete(action(true, "", newKey));
                });
            } catch (Throwable error) {
                App.post(() -> {
                    if (completion.isDone()) return;
                    Notify.show(error.getMessage());
                    completion.complete(action(false, "", ""));
                });
            }
        });
    }

    @Override
    public void continuePlay(String identityKey) {
        Task.execute(() -> {
            Following item = FollowingStore.find(identityKey);
            if (item == null) {
                App.post(() -> Notify.show(R.string.following_check_failed));
                return;
            }
            FollowingSource source = FollowingStore.preferredSource(identityKey);
            FollowingStore.reconcile(item);
            History history = FollowingStore.historyFor(item, source);
            App.post(() -> {
                if (activity.isFinishing() || activity.isDestroyed()) return;
                if (history != null) {
                    VideoActivity.startFromFollowingHistory(activity, history);
                    return;
                }
                FollowingSource target = preferred(item, source);
                if (target == null || TextUtils.isEmpty(target.siteKey) || TextUtils.isEmpty(target.vodId)) {
                    Notify.show(R.string.following_check_failed);
                    return;
                }
                TmdbItem tmdb = item.tmdbId > 0 ? new TmdbItem(item.tmdbId, item.mediaType, item.vodName,
                        "", "", item.vodPic, "", "", 0.0) : null;
                TmdbDetailActivity.start(activity, target.siteKey, target.vodId, item.vodName, item.vodPic,
                        "", tmdb, Setting.getDetailOpenMode());
            });
        });
    }

