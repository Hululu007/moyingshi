    /** One row, mirroring FollowingAdapter.onBindViewHolder line by line. */
    private B14Messages.B14FollowingItem toItem(Following item, FollowingSource source) {
        PicParts pic = resolvePic(item.vodName, item.vodPic);
        int released = FollowingUpdatePolicy.releasedEpisode(item);
        String official = released > 0
                ? activity.getString(R.string.following_official, released)
                : activity.getString(R.string.following_official_unknown);
        List<String> parts = new ArrayList<>();
        if (item.seasonTotalEpisodes > 0) {
            parts.add(activity.getString(R.string.following_season_total, item.seasonTotalEpisodes));
        }
        if (item.seriesTotalEpisodes > 0) {
            parts.add(activity.getString(R.string.following_series_total, item.seriesTotalEpisodes));
        }
        String[] weekdays = activity.getResources().getStringArray(R.array.following_weekdays);
        if (item.nextAirWeekday > 0 && item.nextAirWeekday <= weekdays.length) {
            parts.add(activity.getString(R.string.following_weekday, weekdays[item.nextAirWeekday - 1]));
        }
        String sourceLine;
        if (source != null && source.playableEpisode > 0) {
            sourceLine = activity.getString(R.string.following_source, source.playableEpisode);
        } else {
            sourceLine = activity.getString(FollowingUpdateCoordinator.sourceCheckFailed(item.lastError)
                    ? R.string.following_source_failed : R.string.following_source_unknown);
        }
        StringBuilder progress = new StringBuilder();
        progress.append(item.watchedEpisode > 0
                ? activity.getString(R.string.following_watched, item.watchedEpisode)
                : activity.getString(R.string.following_watched_unknown));
        if (item.unwatchedCount > 0) {
            progress.append('\n').append(activity.getString(R.string.following_unwatched, item.unwatchedCount));
        } else if (released > 0) {
            progress.append('\n').append(activity.getString(R.string.following_unwatched_none));
        }
        boolean badgeVisible = item.hasUpdate && item.unwatchedCount > 0;
        return new B14Messages.B14FollowingItem.Builder()
                .setIdentityKey(text(item.identityKey))
                .setTitle(text(item.vodName))
                .setPicUrl(pic.url)
                .setPicReferer(pic.referer)
                .setPicCookie(pic.cookie)
                .setPicUserAgent(pic.userAgent)
                .setPicExtraHeadersJson(pic.extraHeadersJson)
                .setFallbackPicUrl(pic.fallbackUrl)
                .setPlaceholderText(pic.placeholderText)
                .setPlaceholderColor((long) pic.placeholderColor)
                .setOfficialLine(official)
                .setMetadataLine(TextUtils.join(" · ", parts))
                .setMetadataVisible(!parts.isEmpty())
                .setSourceLine(sourceLine)
                .setProgressLine(progress.toString())
                .setBadgeVisible(badgeVisible)
                .setBadgeText(badgeVisible
                        ? activity.getString(R.string.following_new_count, item.unwatchedCount) : "")
                .setErrorVisible(item.lastError != null && !item.lastError.isBlank())
                .setErrorText(text(item.lastError))
                .setNotifyLabel(activity.getString(item.notifyEnabled
                        ? R.string.following_notify_on : R.string.following_notify_off))
                .setNotifyEnabled(item.notifyEnabled)
                .setNextSeasonVisible(item.latestReleasedSeason > item.trackedSeason)
                .setNextSeasonLabel(item.latestReleasedSeason > item.trackedSeason
                        ? activity.getString(R.string.following_next_season, item.latestReleasedSeason + 1) : "")
                .setReadVisible(item.hasUpdate)
                .build();
    }

