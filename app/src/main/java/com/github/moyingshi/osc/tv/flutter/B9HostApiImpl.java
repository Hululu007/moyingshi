/**
 * B8 B9: native side of the B9 Pigeon contract (mobile search input page).
 *
 * <p>Implements the interface generated by Pigeon in CI from
 * {@code flutter_module/pigeons/b9_search_messages.dart}. The generated file
 * {@code B9Messages.java} is not committed; see docs/b8-b9-search.md.
 *
 * <p>One instance serves one engine. The C0 engine gets an instance bound
 * to C0ShellActivity (only the flag methods are ever called on that
 * engine); the C1 engine gets an instance bound to C1ScreenActivity.
 * All display strings and computed values are resolved here from
 * resources, Setting and VodConfig, so Dart never hard-codes locale
 * strings or composes scope state.
 *
 * <p>Complex sub-flows stay native on purpose: the site dialog, the
 * hot-word / suggest network calls and the results page all run here;
 * Dart only renders the input page and owns the text field.
 *
 * <p>Flavor safety: this class lives in the main source set and must
 * compile for both flavors. The site dialog is mobile-only, so it is
 * opened reflectively (B7 headless-fragment pattern); the headless
 * fragment implements no listener interface, because the native search
 * page passes no SiteListener either (SearchFragment does not implement
 * it), so a site tap only dismisses — exactly like native. Every other
 * reference is main-visible: {@code SearchActivity.direct(Activity,
 * String, String, String, String)} exists in BOTH flavors with the
 * identical signature (the 3-arg direct overload does NOT exist on
 * leanback, so it is never used here), and all B9 strings live in the
 * main res/ tree (verified per directory; the record delete needs no
 * dialog string because native deletes on long-press with no confirm).
 */
public class B9HostApiImpl implements B9Messages.B9HostApi {

    /** Hot/suggest network timeout: every @async method must complete on all paths. */
    private static final long NETWORK_TIMEOUT_MS = 8_000L;

    /** Native hot-word cap per group (SearchFragment.HOT_LIMIT). */
    private static final int HOT_LIMIT = 10;

    private static final String TAG_SEARCH_HOST = "b8_b9_search_host";
    private static final String SITE_DIALOG_CLASS = "com.github.moyingshi.osc.tv.ui.dialog.SiteDialog";
    private static final String RANK_URL = "https://api.web.360kan.com/v1/rank?cat=";
    private static final String RANK_REFERER = "https://www.360kan.com/rank/general";

    private final FragmentActivity activity;

    public B9HostApiImpl(FragmentActivity activity) {
        this.activity = activity;
    }

    @Override
    public B9Messages.B9SearchScreen getSearchScreen(String keyword, String siteKey, String pic, String wallPic) {
        return new B9Messages.B9SearchScreen.Builder()
                .setHintText(activity.getString(R.string.search_keyword))
                .setRecordTitle(activity.getString(R.string.search_record))
                .setHotTitle(activity.getString(R.string.search_hot))
                .setSuggestTitle(activity.getString(R.string.search_suggest))
                .setAllScopeLabel(activity.getString(R.string.search_scope_all))
                .setCurrentScopeLabel(activity.getString(R.string.search_scope_current))
                .setNotSearchableMessage(activity.getString(R.string.detail_site_not_searchable))
                .setHotTvTitle(activity.getString(R.string.search_hot_tv))
                .setHotMovieTitle(activity.getString(R.string.search_hot_movie))
                .setHotVarietyTitle(activity.getString(R.string.search_hot_variety))
                .setInitialCurrentSite(initialCurrentSite(siteKey))
                .setCurrentSiteAvailable(currentSiteAvailable())
                .setRecords(getRecords())
                .setHotTv(hotItems(Setting.getHotTv()))
                .setHotMovie(hotItems(Setting.getHotMovie()))
                .setHotVariety(hotItems(Setting.getHotVariety()))
                .build();
    }

    /** Mirrors SearchFragment.initView: a siteKey entry, or the "current site by default" preference with a searchable home site. */
    private boolean initialCurrentSite(String siteKey) {
        if (!TextUtils.isEmpty(siteKey)) return true;
        return Setting.isSearchCurrentSiteDefault() && currentSiteAvailable();
    }

    /** Mirrors SearchFragment.isDefaultCurrentSite's site check (without the preference gate). */
    private static boolean currentSiteAvailable() {
        try {
            Site home = VodConfig.get().getHome();
            return home != null && !home.isEmpty() && home.isSearchable();
        } catch (Throwable e) {
            e.printStackTrace();
            return false;
        }
    }

    @Override
    public void refreshHotWords(B9Messages.Result<B9Messages.B9HotWords> result) {
        boolean[] completed = new boolean[1];
        Handler handler = new Handler(Looper.getMainLooper());
        // One slot per group, pre-filled with the cached values: a failed
        // group keeps its cached list, exactly like the native page,
        // whose per-group callback simply never fires on failure.
        List<List<String>> slots = new ArrayList<>();
        slots.add(hotItems(Setting.getHotTv()));
        slots.add(hotItems(Setting.getHotMovie()));
        slots.add(hotItems(Setting.getHotVariety()));
        int[] pending = {3};
        Runnable[] timeout = new Runnable[1];
        timeout[0] = () -> completeHot(result, completed, handler, timeout[0], slots);
        handler.postDelayed(timeout[0], NETWORK_TIMEOUT_MS);
        fetchHot(3, Setting::putHotTv, 0, slots, pending, completed, handler, timeout[0], result);
        fetchHot(2, Setting::putHotMovie, 1, slots, pending, completed, handler, timeout[0], result);
        fetchHot(4, Setting::putHotVariety, 2, slots, pending, completed, handler, timeout[0], result);
    }

    /** One 360kan rank call (cat 3 = TV, 2 = movie, 4 = variety), mirroring SearchFragment.getHot(). */
    private void fetchHot(int cat, HotSaver saver, int index, List<List<String>> slots, int[] pending,
            boolean[] completed, Handler handler, Runnable timeout, B9Messages.Result<B9Messages.B9HotWords> result) {
        try {
            OkHttp.newCall(RANK_URL + cat, Map.of(HttpHeaders.REFERER, RANK_REFERER)).enqueue(new Callback() {
                @Override
                public void onResponse(@NonNull Call call, @NonNull Response response) throws IOException {
                    String body = response.body() == null ? "" : response.body().string();
                    if (!TextUtils.isEmpty(body)) {
                        // Native saves the raw JSON and parses it for display.
                        saver.save(body);
                        synchronized (slots) {
                            slots.set(index, hotItems(body));
                        }
                    }
                    onHotGroupDone(pending, completed, handler, timeout, result, slots);
                }

                @Override
                public void onFailure(@NonNull Call call, @NonNull IOException e) {
                    onHotGroupDone(pending, completed, handler, timeout, result, slots);
                }
            });
        } catch (Throwable e) {
            e.printStackTrace();
            onHotGroupDone(pending, completed, handler, timeout, result, slots);
        }
    }

    private void onHotGroupDone(int[] pending, boolean[] completed, Handler handler, Runnable timeout,
            B9Messages.Result<B9Messages.B9HotWords> result, List<List<String>> slots) {
        boolean done;
        synchronized (slots) {
            done = --pending[0] <= 0;
        }
        if (done) completeHot(result, completed, handler, timeout, slots);
    }

    /** Completes on the main thread, exactly once; the timeout is cancelled when the last group arrives first. */
    private void completeHot(B9Messages.Result<B9Messages.B9HotWords> result, boolean[] completed,
            Handler handler, Runnable timeout, List<List<String>> slots) {
        App.post(() -> {
            if (completed[0]) return;
            completed[0] = true;
            handler.removeCallbacks(timeout);
            List<String> tv;
            List<String> movie;
            List<String> variety;
            synchronized (slots) {
                tv = new ArrayList<>(slots.get(0));
                movie = new ArrayList<>(slots.get(1));
                variety = new ArrayList<>(slots.get(2));
            }
            result.success(new B9Messages.B9HotWords.Builder()
                    .setTv(tv)
                    .setMovie(movie)
                    .setVariety(variety)
                    .build());
        });
    }

    @Override
    public void getSuggest(String keyword, B9Messages.Result<B9Messages.B9SuggestResult> result) {
        String query = keyword == null ? "" : keyword.trim();
        if (query.isEmpty()) {
            result.success(new B9Messages.B9SuggestResult.Builder().setWords(new ArrayList<>()).build());
            return;
        }
        boolean[] completed = new boolean[1];
        Handler handler = new Handler(Looper.getMainLooper());
        // One slot per source; the merge runs once, when both arrived or
        // the timeout fired, with whatever arrived (native paints each
        // source as it arrives; this batch returns one merged batch).
        List<List<Word.Data>> slots = new ArrayList<>();
        slots.add(new ArrayList<>());
        slots.add(new ArrayList<>());
        int[] pending = {2};
        Runnable[] timeout = new Runnable[1];
        timeout[0] = () -> completeSuggest(result, completed, handler, timeout[0], slots);
        handler.postDelayed(timeout[0], NETWORK_TIMEOUT_MS);
        fetchSuggest(SearchSuggest.iqiyiUrl(query), false, 0, slots, pending, completed, handler, timeout[0], result);
        fetchSuggest(SearchSuggest.tencentUrl(query), true, 1, slots, pending, completed, handler, timeout[0], result);
    }

    /** One suggest call, mirroring SearchFragment.getSuggest(). */
    private void fetchSuggest(String url, boolean tencent, int index, List<List<Word.Data>> slots, int[] pending,
            boolean[] completed, Handler handler, Runnable timeout, B9Messages.Result<B9Messages.B9SuggestResult> result) {
        try {
            OkHttp.newCall(url).enqueue(new Callback() {
                @Override
                public void onResponse(@NonNull Call call, @NonNull Response response) throws IOException {
                    String body = response.body() == null ? "" : response.body().string();
                    if (!TextUtils.isEmpty(body)) {
                        List<Word.Data> items = tencent ? SearchSuggest.parseTencent(body) : SearchSuggest.parseIqiyi(body);
                        synchronized (slots) {
                            slots.set(index, items);
                        }
                    }
                    onSuggestDone(pending, completed, handler, timeout, result, slots);
                }

                @Override
                public void onFailure(@NonNull Call call, @NonNull IOException e) {
                    onSuggestDone(pending, completed, handler, timeout, result, slots);
                }
            });
        } catch (Throwable e) {
            e.printStackTrace();
            onSuggestDone(pending, completed, handler, timeout, result, slots);
        }
    }

    private void onSuggestDone(int[] pending, boolean[] completed, Handler handler, Runnable timeout,
            B9Messages.Result<B9Messages.B9SuggestResult> result, List<List<Word.Data>> slots) {
        boolean done;
        synchronized (slots) {
            done = --pending[0] <= 0;
        }
        if (done) completeSuggest(result, completed, handler, timeout, slots);
    }

    /** Merges both sources (deduped, LIMIT 20) and completes on the main thread, exactly once. */
    private void completeSuggest(B9Messages.Result<B9Messages.B9SuggestResult> result, boolean[] completed,
            Handler handler, Runnable timeout, List<List<Word.Data>> slots) {
        App.post(() -> {
            if (completed[0]) return;
            completed[0] = true;
            handler.removeCallbacks(timeout);
            List<Word.Data> iqiyi;
            List<Word.Data> tencent;
            synchronized (slots) {
                iqiyi = new ArrayList<>(slots.get(0));
                tencent = new ArrayList<>(slots.get(1));
            }
            List<String> words = new ArrayList<>();
            for (Word.Data item : SearchSuggest.merge(iqiyi, tencent)) {
                words.add(item.getTitle());
            }
            result.success(new B9Messages.B9SuggestResult.Builder().setWords(words).build());
        });
    }

    @Override
    public List<String> getRecords() {
        String json = Setting.getKeyword();
        if (TextUtils.isEmpty(json)) return new ArrayList<>();
        try {
            // Same parse as RecordAdapter.getItems().
            List<String> records = App.gson().fromJson(json, TypeToken.getParameterized(List.class, String.class).getType());
            return records == null ? new ArrayList<>() : new ArrayList<>(records);
        } catch (Throwable e) {
            e.printStackTrace();
            return new ArrayList<>();
        }
    }

    @Override
    public void deleteRecord(String record) {
        if (record == null) return;
        // No confirm dialog: the native long-press deletes directly
        // (RecordAdapter.ViewHolder.onLongClick).
        List<String> records = getRecords();
        if (records.remove(record)) {
            Setting.putKeyword(App.gson().toJson(records));
        }
    }

    @Override
    public void openSiteDialog(B9Messages.Result<Boolean> result) {
        boolean[] completed = new boolean[1];
        FragmentManager.FragmentLifecycleCallbacks callbacks = null;
        try {
            FragmentManager fm = activity.getSupportFragmentManager();
            Fragment host = searchHostFragment();
            // Register the dismiss watcher before showing, so a quick
            // dismiss cannot be missed (B7 watchDialogDismiss pattern).
            callbacks = new FragmentManager.FragmentLifecycleCallbacks() {
                @Override
                public void onFragmentDestroyed(@NonNull FragmentManager manager, @NonNull Fragment fragment) {
                    if (!SITE_DIALOG_CLASS.equals(fragment.getClass().getName())) return;
                    manager.unregisterFragmentLifecycleCallbacks(this);
                    completeSiteDialog(result, completed);
                }
            };
            fm.registerFragmentLifecycleCallbacks(callbacks, false);
            Class<?> dialogClass = Class.forName(SITE_DIALOG_CLASS);
            Object dialog = dialogClass.getMethod("create").invoke(null);
            dialog = dialogClass.getMethod("search").invoke(dialog);
            dialogClass.getMethod("show", Fragment.class).invoke(dialog, host);
        } catch (Throwable e) {
            e.printStackTrace();
            if (callbacks != null) {
                activity.getSupportFragmentManager().unregisterFragmentLifecycleCallbacks(callbacks);
            }
            completeSiteDialog(result, completed);
        }
    }

    /** Completes with the post-dismiss current-site availability, on the main thread, exactly once. */
    private void completeSiteDialog(B9Messages.Result<Boolean> result, boolean[] completed) {
        App.post(() -> {
            if (completed[0]) return;
            completed[0] = true;
            result.success(currentSiteAvailable());
        });
    }

    /** Parses one cached hot-word JSON the way SearchFragment.hotItems() does (cap 10). */
    private static List<String> hotItems(String result) {
        List<String> items = new ArrayList<>();
        if (TextUtils.isEmpty(result)) return items;
        try {
            List<Word.Data> data = Word.objectFrom(result).getData();
            for (int i = 0; i < Math.min(data.size(), HOT_LIMIT); i++) {
                items.add(data.get(i).getTitle());
            }
        } catch (Throwable e) {
            e.printStackTrace();
        }
        return items;
    }

    /** Headless parent fragment for the reflectively opened mobile-only site dialog (B7 pattern). */
    private B9SearchHostFragment searchHostFragment() {
        FragmentManager fm = activity.getSupportFragmentManager();
        Fragment existing = fm.findFragmentByTag(TAG_SEARCH_HOST);
        if (existing instanceof B9SearchHostFragment host) {
            return host;
        }
        B9SearchHostFragment host = new B9SearchHostFragment();
        fm.beginTransaction().add(host, TAG_SEARCH_HOST).commitNow();
        return host;
    }

    /**
     * Headless parent fragment for the site dialog. It carries no UI and
     * lives for the host Activity's lifetime. It deliberately implements
     * NO listener interface: SiteDialog.show() only sets its listener
     * when the parent is a SiteListener, and the native search page
     * (SearchFragment) is not one — so a site tap only dismisses the
     * dialog, exactly like native. Public static with an implicit no-arg
     * constructor so the FragmentManager can restore it after process
     * death.
     */
    public static class B9SearchHostFragment extends Fragment {
    }

    /** One-method saver for the raw hot-word JSON (SearchFragment.HotSaver is mobile-only). */
    private interface HotSaver {
        void save(String result);
    }
}
