    @Override
    public void downloadRemoteBundle(String rawUrl,
            B19Messages.Result<B19Messages.B19RemoteIndex> result) {
        if (busy) {
            result.success(errorIndex(activity.getString(R.string.plugin_manager_remote_busy)));
            return;
        }
        String url = text(rawUrl);
        busy = true;
        Completion<B19Messages.B19RemoteIndex> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, true, errorIndex(loadFailed(
                        activity.getString(R.string.error_play_timeout))));
        executorService().execute(() -> {
            // Native startRemoteImport, verbatim order: drop any stale
            // temp zip, resolve, download (20s), inspect. Every failure
            // deletes the zip and completes with an error index.
            File zip = new File(activity.getCacheDir(), REMOTE_ZIP_NAME);
            delete(zip);
            PluginRemoteSource.Resolution resolution = PluginRemoteSource.resolve(url);
            if (!resolution.isSuccess()) {
                failRemoteImport(zip, resolution.error(), completion);
                return;
            }
            try {
                PluginRemoteSource.download(resolution.urls(), zip, REMOTE_TIMEOUT_SECONDS);
            } catch (IOException | RuntimeException error) {
                failRemoteImport(zip, error.getMessage(), completion);
                return;
            }
            PluginBundleIndex.Result index = PluginBundleIndex.inspect(zip);
            if (index == null || !index.isSuccess()) {
                failRemoteImport(zip, index == null ? null : index.error(), completion);
                return;
            }
            if (index.candidates().isEmpty()) {
                failRemoteImport(zip, activity.getString(R.string.plugin_manager_remote_empty), completion);
                return;
            }
            List<PluginBundleIndex.Candidate> candidates = index.candidates();
            handler.post(() -> {
                busy = false;
                if (completion.isDone()) return;
                remoteZip = zip;
                remoteCandidates = new ArrayList<>(candidates);
                completion.complete(buildIndex(candidates, url, ""));
            });
        });
    }

    private void failRemoteImport(File zip, String error,
            Completion<B19Messages.B19RemoteIndex> completion) {
        delete(zip);
        String message = error == null ? "" : error;
        handler.post(() -> {
            busy = false;
            if (completion.isDone()) return;
            completion.complete(errorIndex(message));
        });
    }

    @Override
    public B19Messages.B19RemoteConfirm getRemoteConfirm(List<String> entryPaths) {
        List<PluginBundleIndex.Candidate> selected = selectedCandidates(entryPaths);
        if (remoteZip == null || remoteCandidates == null || selected.isEmpty()) {
            return new B19Messages.B19RemoteConfirm.Builder()
                    .setValid(false)
                    .setTitle(activity.getString(R.string.plugin_manager_remote_confirm_title))
                    .setMessageText("")
                    .setRiskText("")
                    .setInstallLabel(activity.getString(R.string.plugin_manager_remote_install))
                    .setCancelLabel(activity.getString(R.string.dialog_cancel))
                    .build();
        }
        // Native confirmInstall, verbatim: names joined with the
        // separator, combined permissions, the unconditional
        // not-sandboxed warning, then the plain-language high-risk
        // lines (only for permissions actually requested).
        StringBuilder names = new StringBuilder();
        Set<String> union = new LinkedHashSet<>();
        for (PluginBundleIndex.Candidate candidate : selected) {
            if (names.length() > 0) {
                names.append(activity.getString(R.string.plugin_manager_remote_name_separator));
            }
            String name = candidate.name() == null || candidate.name().isEmpty()
                    ? candidate.id() : candidate.name();
            names.append(name);
            if (candidate.permissions() != null) union.addAll(candidate.permissions());
        }
        StringBuilder message = new StringBuilder(activity.getString(
                R.string.plugin_manager_remote_confirm_message, selected.size(),
                names.toString(), permissionText(union)));
        message.append("\n\n").append(activity.getString(
                R.string.plugin_manager_remote_confirm_not_sandboxed));
        StringBuilder risk = new StringBuilder();
        if (union.contains(PluginCapabilityRegistry.PERMISSION_NET_REQUEST)) {
            risk.append(activity.getString(R.string.plugin_manager_perm_net_request_plain));
        }
        if (union.contains(PluginCapabilityRegistry.PERMISSION_UI_PANEL)) {
            if (risk.length() > 0) risk.append("\n");
            risk.append(activity.getString(R.string.plugin_manager_perm_ui_panel_plain));
        }
        return new B19Messages.B19RemoteConfirm.Builder()
                .setValid(true)
                .setTitle(activity.getString(R.string.plugin_manager_remote_confirm_title))
                .setMessageText(message.toString())
                .setRiskText(risk.toString())
                .setInstallLabel(activity.getString(R.string.plugin_manager_remote_install))
                .setCancelLabel(activity.getString(R.string.dialog_cancel))
                .build();
    }

    @Override
    public void installRemoteCandidates(List<String> entryPaths,
            B19Messages.Result<B19Messages.B19PluginScreen> result) {
        if (busy) {
            result.success(busyScreen());
            return;
        }
        List<PluginBundleIndex.Candidate> selected = selectedCandidates(entryPaths);
        if (remoteZip == null || selected.isEmpty()) {
            result.success(busyScreenWithNotice(
                    activity.getString(R.string.plugin_manager_remote_batch_failed, "")));
            return;
        }
        File zip = remoteZip;
        busy = true;
        Completion<B19Messages.B19PluginScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, true, errorScreen(loadFailed(
                        activity.getString(R.string.error_play_timeout))));
        executorService().execute(() -> {
            // Native runBundleImport: only the checked candidates are
            // passed in; installed entries reload; the zip is cleaned
            // up on every exit of this step.
            PluginPackageImporter.BundleResult bundleResult =
                    PluginPackageImporter.importBundle(zip, selected);
            boolean installed = false;
            if (bundleResult != null && bundleResult.isSuccess()) {
                for (PluginPackageImporter.ItemResult item : bundleResult.items()) {
                    if (item.entry() != null) installed = true;
                }
            }
            if (installed) PluginBootstrap.installAndReloadQuietly();
            Snapshot snapshot = readEntries();
            delete(zip);
            handler.post(() -> {
                busy = false;
                if (completion.isDone()) return;
                remoteZip = null;
                remoteCandidates = null;
                completion.complete(buildRemoteResultScreen(snapshot, bundleResult));
            });
        });
    }

    /** Native showRemoteResult, folded into the refreshed screen. */
    private B19Messages.B19PluginScreen buildRemoteResultScreen(Snapshot snapshot,
            PluginPackageImporter.BundleResult result) {
        if (result == null || !result.isSuccess()) {
            return buildScreen(snapshot, activity.getString(
                    R.string.plugin_manager_remote_batch_failed,
                    result == null ? "" : text(result.error())), "", new ArrayList<>());
        }
        List<String> lines = new ArrayList<>();
        int installed = 0;
        for (PluginPackageImporter.ItemResult item : result.items()) {
            String name = item.candidate() == null ? "" : item.candidate().name();
            if (name == null || name.isEmpty()) {
                name = item.candidate() == null ? "" : item.candidate().id();
            }
            if (item.entry() != null) {
                installed++;
                lines.add(activity.getString(R.string.plugin_manager_remote_item_ok, name));
            } else {
                lines.add(activity.getString(R.string.plugin_manager_remote_item_failed,
                        name, item.error() == null ? "" : item.error()));
            }
        }
        if (lines.isEmpty()) {
            return buildScreen(snapshot, activity.getString(R.string.plugin_manager_remote_empty),
                    "", new ArrayList<>());
        }
        if (installed == lines.size()) {
            return buildScreen(snapshot, activity.getString(
                    R.string.plugin_manager_remote_all_ok, installed), "", new ArrayList<>());
        }
        return buildScreen(snapshot, "", "", lines);
    }

    /** Selected candidates in list order (native checkedCandidates). */
    private List<PluginBundleIndex.Candidate> selectedCandidates(List<String> entryPaths) {
        Set<String> wanted = entryPaths == null ? new HashSet<>() : new HashSet<>(entryPaths);
        List<PluginBundleIndex.Candidate> selected = new ArrayList<>();
        if (remoteCandidates == null) return selected;
        for (PluginBundleIndex.Candidate candidate : remoteCandidates) {
            if (wanted.contains(candidate.entryPath())) selected.add(candidate);
        }
        return selected;
    }

