    private B19Messages.B19RemoteIndex buildIndex(List<PluginBundleIndex.Candidate> candidates,
            String rawUrl, String errorText) {
        List<B19Messages.B19RemoteCandidate> out = new ArrayList<>();
        if (candidates != null) {
            for (PluginBundleIndex.Candidate candidate : candidates) {
                out.add(new B19Messages.B19RemoteCandidate.Builder()
                        .setEntryPath(text(candidate.entryPath()))
                        .setPluginId(text(candidate.id()))
                        .setName(displayName(candidate.id(), candidate.name()))
                        .setVersion(text(candidate.version()))
                        .setRuntimeApi(text(candidate.runtimeApi()))
                        .setMetaText(activity.getString(
                                R.string.plugin_manager_remote_candidate_meta,
                                text(candidate.version()), text(candidate.runtimeApi())))
                        .setPermissionText(permissionText(candidate.permissions()))
                        .setPermissionLabels(permissionLabels(candidate.permissions()))
                        .build());
            }
        }
        return new B19Messages.B19RemoteIndex.Builder()
                .setCandidates(out)
                .setCountText(activity.getString(R.string.plugin_manager_remote_found, out.size()))
                .setSourceText(activity.getString(R.string.plugin_manager_remote_source, hostOf(rawUrl)))
                .setErrorText(text(errorText))
                .build();
    }

    private B19Messages.B19RemoteIndex errorIndex(String errorText) {
        return new B19Messages.B19RemoteIndex.Builder()
                .setCandidates(new ArrayList<>())
                .setCountText("")
                .setSourceText("")
                .setErrorText(text(errorText))
                .build();
    }

    private String loadFailed(String message) {
        return activity.getString(R.string.plugin_manager_load_failed, text(message));
    }

    private static String displayName(PluginSourceConfig.Entry entry) {
        if (entry == null) return "";
        return displayName(entry.id(), entry.name());
    }

    private static String displayName(String id, String name) {
        if (name == null || name.isEmpty()) return id == null ? "" : id;
        return name;
    }

    /** Source host: parse the entered URL, fall back to the raw text (native hostOf). */
    private static String hostOf(String rawUrl) {
        try {
            String host = Uri.parse(rawUrl).getHost();
            if (host != null && !host.isEmpty()) return host;
        } catch (RuntimeException ignored) {
        }
        return rawUrl == null ? "" : rawUrl;
    }

    private static void delete(File file) {
        if (file == null || !file.exists()) return;
        file.delete();
    }

    /**
     * Permission token → human text (native permissionLabel). Unknown
     * tokens show verbatim: hiding one would grant it silently.
     */
    private String permissionLabel(String token) {
        if (PluginCapabilityRegistry.PERMISSION_NET_REQUEST.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_net_request);
        }
        if (PluginCapabilityRegistry.PERMISSION_UI_PANEL.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_ui_panel);
        }
        if (PluginCapabilityRegistry.PERMISSION_UI_FLOATING.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_ui_floating);
        }
        if (PluginCapabilityRegistry.PERMISSION_UI_TOOLBAR.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_ui_toolbar);
        }
        if (PluginCapabilityRegistry.PERMISSION_UI_PAGE.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_ui_page);
        }
        if (PluginCapabilityRegistry.PERMISSION_EVENTS.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_events);
        }
        if (PluginCapabilityRegistry.PERMISSION_EPISODE_DATA.equals(token)) {
            return activity.getString(R.string.plugin_manager_perm_episode_data);
        }
        return token;
    }

    /** High-risk permissions: net access and self-drawn panels (native isHighRisk). */
    private static boolean isHighRisk(String token) {
        return PluginCapabilityRegistry.PERMISSION_NET_REQUEST.equals(token)
                || PluginCapabilityRegistry.PERMISSION_UI_PANEL.equals(token);
    }

    /** Sorted labels joined with the separator (native permissionText). */
    private String permissionText(Set<String> permissions) {
        if (permissions == null || permissions.isEmpty()) {
            return activity.getString(R.string.plugin_manager_perm_none);
        }
        List<String> sorted = new ArrayList<>(permissions);
        Collections.sort(sorted);
        StringBuilder text = new StringBuilder();
        for (String token : sorted) {
            if (text.length() > 0) {
                text.append(activity.getString(R.string.plugin_manager_perm_separator));
            }
            text.append(permissionLabel(token));
        }
        return text.toString();
    }

    private List<B19Messages.B19PermissionLabel> permissionLabels(Set<String> permissions) {
        List<B19Messages.B19PermissionLabel> out = new ArrayList<>();
        if (permissions == null || permissions.isEmpty()) return out;
        List<String> sorted = new ArrayList<>(permissions);
        Collections.sort(sorted);
        for (String token : sorted) {
            out.add(new B19Messages.B19PermissionLabel.Builder()
                    .setLabel(permissionLabel(token))
                    .setHighRisk(isHighRisk(token))
                    .build());
        }
        return out;
    }

    private static boolean isJsonObject(String value) {
        try {
            JsonElement element = JsonParser.parseString(value);
            return element != null && element.isJsonObject();
        } catch (RuntimeException error) {
            return false;
        }
    }

    private boolean canTouchView() {
        return !activity.isFinishing() && !activity.isDestroyed();
    }

    /**
     * Only deletes a directory owned by the plugin root (native
     * removePackageDir): a tampered config entry could otherwise point
     * at any path on the device.
     */
    private static boolean removePackageDir(String directory) {
        if (!PluginPackageImporter.isOwnedDirectory(directory)) return false;
        try {
            File target = new File(directory).getCanonicalFile();
            Path.clear(target);
            return !target.exists();
        } catch (Throwable error) {
            return false;
        }
    }

    /** Background-thread config read; a failure is one line, never a crash (native readEntries). */
    private static Snapshot readEntries() {
        try {
            return new Snapshot(new ArrayList<>(PluginSourceConfig.get().entries()), null);
        } catch (Throwable error) {
            return new Snapshot(Collections.emptyList(), error.toString());
        }
    }

    private static final class Snapshot {
        private final List<PluginSourceConfig.Entry> entries;
        private final String error;

        private Snapshot(List<PluginSourceConfig.Entry> entries, String error) {
            this.entries = entries;
            this.error = error;
        }
    }

    private ExecutorService executorService() {
        if (executor == null || executor.isShutdown()) {
            executor = Executors.newSingleThreadExecutor();
        }
        return executor;
    }

