    /**
     * Main-thread-only one-shot completion for an @async call, with a
     * watchdog. The timeout completes with the given value; a late
     * background completion is a no-op. All callers complete from the
     * main thread (Handler), so no synchronization is needed. Copied
     * from B18HostApiImpl (same shape, B19 result types). Completing
     * also clears the serial busy guard when this call owns it
     * (getPluginScreen never sets busy, so its completion must not
     * clear a task another call started — the poll loop would unlock
     * a running import). The directory-pick import clears the guard
     * in its own post (its completion is the pick poll, not a Pigeon
     * Result).
     */
    private final class Completion<T> {
        private final B19Messages.Result<T> result;
        private final boolean ownsBusy;
        private boolean done;
        private final Runnable timeout;

        Completion(B19Messages.Result<T> result, long timeoutMs, boolean ownsBusy, T timeoutValue) {
            this.result = result;
            this.ownsBusy = ownsBusy;
            this.timeout = () -> complete(timeoutValue);
            handler.postDelayed(this.timeout, timeoutMs);
        }

        void complete(T value) {
            if (done) return;
            done = true;
            handler.removeCallbacks(timeout);
            if (ownsBusy) busy = false;
            result.success(value);
        }

        boolean isDone() {
            return done;
        }
    }
