    @Override
    public void requestPluginDirectory() {
        if (busy || !PICK_IDLE.equals(pickState)) return;
        if (!(activity instanceof C1ScreenActivity)) {
            // C0 engine: the plugin page never opens here, so there is
            // nothing to pick from. Complete silently via the poll state.
            return;
        }
        pickState = PICK_PICKING;
        PermissionUtil.requestFile(activity, granted -> {
            if (!granted) {
                pickMessage = activity.getString(R.string.plugin_manager_permission_required);
                pickState = PICK_IDLE;
                pickEpoch++;
                return;
            }
            // Same FileChooser fallback-branch shape as native
            // chooseDirectory(): the launcher lives in C1ScreenActivity.
            ((C1ScreenActivity) activity).launchPluginDirectoryPicker();
        });
    }

    /** Called by C1ScreenActivity when its directory-picker launcher returns (native onDirectoryPicked). */
    public void onDirectoryPicked(ActivityResult result) {
        if (!PICK_PICKING.equals(pickState)) return;
        if (result.getResultCode() != Activity.RESULT_OK || result.getData() == null) {
            // Native stays silent on cancel; Dart sees the epoch bump
            // with an empty message and shows nothing.
            pickMessage = "";
            pickState = PICK_IDLE;
            pickEpoch++;
            return;
        }
        Uri uri = result.getData().getData();
        // FileActivity returns Uri.fromFile, so getPath() is already
        // the plain absolute path; decoding it again would turn "+"
        // into a space (native comment).
        String path = uri == null ? null : uri.getPath();
        if (path == null || path.isEmpty()) {
            pickMessage = activity.getString(R.string.plugin_manager_invalid_path);
            pickState = PICK_IDLE;
            pickEpoch++;
            return;
        }
        pickState = PICK_IMPORTING;
        busy = true;
        File source = new File(path);
        executorService().execute(() -> {
            PluginPackageImporter.Result importResult = PluginPackageImporter.importFrom(source);
            boolean imported = importResult != null && importResult.entry() != null;
            String name = imported ? importResult.entry().name() : null;
            String error = imported || importResult == null ? null : importResult.error();
            // An imported entry is enabled by default, but only a
            // reload makes it take effect (native importPlugin).
            if (imported) PluginBootstrap.installAndReloadQuietly();
            Snapshot snapshot = readEntries();
            String message = imported
                    ? activity.getString(R.string.plugin_manager_import_ok, name == null ? "" : name)
                    : activity.getString(R.string.plugin_manager_import_failed, error == null ? "" : error);
            handler.post(() -> {
                busy = false;
                if (canTouchView()) {
                    pickMessage = message;
                    pickState = PICK_IDLE;
                    pickEpoch++;
                } else {
                    // The page is gone; the import already landed, so
                    // just reset the pick state for the next open.
                    pickState = PICK_IDLE;
                    pickEpoch++;
                }
            });
        });
    }

