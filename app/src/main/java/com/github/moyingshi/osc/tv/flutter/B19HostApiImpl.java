    @Override
    public void disposePlugins() {
        // Native onDestroy: the temp zip is only deleted when no task
        // is running — a running import owns it until its own exit.
        if (!busy) delete(remoteZip);
        remoteZip = null;
        remoteCandidates = null;
        if (executor != null) {
            executor.shutdownNow();
            executor = null;
        }
    }

