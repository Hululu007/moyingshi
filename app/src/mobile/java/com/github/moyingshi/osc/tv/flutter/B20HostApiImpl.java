    public Boolean isB20Enabled() {
        return Setting.isFlutterB20Enabled();
    }

    @Override
    public void setB20Enabled(Boolean enabled) {
        Setting.putFlutterB20Enabled(Boolean.TRUE.equals(enabled));
    }

