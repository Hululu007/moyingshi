    @Override
    public void deleteMiniapp(String key,
            B20Messages.Result<B20Messages.B20HkScreen> result) {
        if (busy) {
            result.success(busyScreen());
            return;
        }
        String siteKey = text(key);
        busy = true;
        Completion<B20Messages.B20HkScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, true,
                        errorScreen(activity.getString(R.string.error_play_timeout)));
        executorService().execute(() -> {
            // Native onDeleteClick, verbatim order: remove the site
            // entry, then delete the rule file + invalidate its cache.
            String title = "";
            for (Site site : readMiniapps()) {
                if (siteKey.equals(site.getKey())) {
                    title = HkStore.titleOf(site);
                    break;
                }
            }
            List<String> keys = new ArrayList<>();
            keys.add(siteKey);
            LocalSource.removeByKeys(keys);
            if (!title.isEmpty()) {
                HkStore.delete(title);
                HkCache.invalidate(title);
            }
            handler.post(() -> {
                if (disposed || completion.isDone()) return;
                String notice = activity.getString(R.string.lab_local_source_deleted, 1);
                reloadLocalConfig();
                completion.complete(buildScreen(readMiniapps(), notice, ""));
            });
        });
    }

    @Override
    public void openMiniappList(String key) {
        String siteKey = text(key);
        String title = "";
        for (Site site : readMiniapps()) {
            if (siteKey.equals(site.getKey())) {
                title = HkStore.titleOf(site);
                break;
            }
        }
        // Native onItemClick: the miniapp's own list page, still native.
        if (!title.isEmpty() && canTouchView()) {
            HkListActivity.open(activity, title);
        }
    }

    @Override
    public void disposeHk() {
        dispose();
    }

    // ------------------------------------------------------------------
    // Helpers (B19 shape)
    // ------------------------------------------------------------------

    private ExecutorService executorService() {
        if (executor == null || executor.isShutdown()) {
            executor = Executors.newSingleThreadExecutor();
        }
        return executor;
    }

    private boolean canTouchView() {
        AppCompatActivity host = activity;
        return host != null && !host.isFinishing() && !host.isDestroyed();
    }

    private static String text(String value) {
        return value == null ? "" : value;
    }

    /**
     * B19 Completion, verbatim shape: completes the Pigeon Result
     * exactly once, on the watchdog timeout when the worker never
     * answers. When the snapshot is a plain read (getHkScreen) the
     * completion must not clear a task another call started — the
     * poll loop would unlock a running import (B19 §2.2).
     */
    private final class Completion<T> {
        private final B20Messages.Result<T> result;
        private final boolean ownsBusy;
        private boolean done;
        private final Runnable timeout;

        Completion(B20Messages.Result<T> result, long timeoutMs, boolean ownsBusy, T timeoutValue) {
            this.result = result;
            this.ownsBusy = ownsBusy;
            this.timeout = () -> complete(timeoutValue);
            handler.postDelayed(this.timeout, timeoutMs);
        }

        void complete(T value) {
            if (done) return;
            done = true;
            handler.removeCallbacks(timeout);
            if (ownsBusy) busy = false;
            result.success(value);
        }

        boolean isDone() {
            return done;
        }
    }
