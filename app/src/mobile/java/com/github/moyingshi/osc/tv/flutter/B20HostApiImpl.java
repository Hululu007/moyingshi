    @Override
    public void exportMiniapps(List<String> keys,
            B20Messages.Result<B20Messages.B20HkScreen> result) {
        if (busy) {
            result.success(busyScreen());
            return;
        }
        busy = true;
        Completion<B20Messages.B20HkScreen> completion =
                new Completion<>(result, EXPORT_TIMEOUT_MS, true,
                        errorScreen(activity.getString(R.string.error_play_timeout)));
        executorService().execute(() -> {
            List<String> selected = keys == null ? new ArrayList<>() : new ArrayList<>(keys);
            if (selected.isEmpty()) {
                String notice = activity.getString(R.string.hk_miniapp_export_select_first);
                handler.post(() -> {
                    if (disposed || completion.isDone()) return;
                    completion.complete(buildScreen(readMiniapps(), notice, ""));
                });
                return;
            }
            List<Site> sites = readMiniapps();
            LinkedHashSet<String> titles = new LinkedHashSet<>();
            for (Site site : sites) {
                if (!selected.contains(site.getKey())) continue;
                String title = HkStore.titleOf(site);
                if (!title.isEmpty()) titles.add(title);
            }
            if (titles.isEmpty()) {
                String notice = activity.getString(R.string.hk_miniapp_export_not_miniapp);
                handler.post(() -> {
                    if (disposed || completion.isDone()) return;
                    completion.complete(buildScreen(readMiniapps(), notice, ""));
                });
                return;
            }
            // Native runExport, verbatim order: upload one title at a
            // time, keep the first error, keep going after failures.
            Map<String, String> codes = new LinkedHashMap<>();
            String firstError = null;
            int failed = 0;
            for (String title : titles) {
                try {
                    codes.put(title, HkCloudExport.uploadTextDb(title));
                } catch (Exception e) {
                    failed++;
                    if (firstError == null) {
                        firstError = e.getMessage() == null ? e.toString() : e.getMessage();
                    }
                }
            }
            String notice = "";
            if (codes.isEmpty()) {
                notice = activity.getString(R.string.hk_miniapp_export_failed,
                        firstError == null ? "" : firstError);
            } else if (failed > 0) {
                notice = activity.getString(R.string.hk_miniapp_export_partial,
                        codes.size(), failed, firstError == null ? "" : firstError);
            }
            String finalNotice = notice;
            Map<String, String> finalCodes = codes;
            handler.post(() -> {
                if (disposed || completion.isDone()) return;
                if (!finalCodes.isEmpty() && canTouchView()) {
                    // The share sheet is opened host-side (Dart
                    // cannot open it); full success shows no toast,
                    // only the sheet — exactly like native.
                    AppCompatActivity host = activity;
                    Intent share = new Intent(Intent.ACTION_SEND);
                    share.setType("text/plain");
                    share.putExtra(Intent.EXTRA_TEXT, HkCloudExport.shareText(finalCodes,
                            host.getString(R.string.hk_miniapp_export_share_note)));
                    String chooserTitle = finalCodes.size() == 1
                            ? host.getString(R.string.hk_miniapp_export_share_title_one,
                                    finalCodes.keySet().iterator().next())
                            : host.getString(R.string.hk_miniapp_export_share_title_many,
                                    finalCodes.size());
                    host.startActivity(Intent.createChooser(share, chooserTitle));
                }
                completion.complete(buildScreen(readMiniapps(), finalNotice, ""));
            });
        });
    }

