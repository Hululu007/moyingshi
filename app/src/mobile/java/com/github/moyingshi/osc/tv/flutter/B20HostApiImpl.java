    @Override
    public void syncMiniapps(B20Messages.Result<B20Messages.B20HkScreen> result) {
        if (busy) {
            result.success(busyScreen());
            return;
        }
        busy = true;
        Completion<B20Messages.B20HkScreen> completion =
                new Completion<>(result, LOAD_TIMEOUT_MS, true,
                        errorScreen(activity.getString(R.string.error_play_timeout)));
        executorService().execute(() -> {
            int added = HkStore.syncSites();
            handler.post(() -> {
                if (disposed || completion.isDone()) return;
                if (added > 0) reloadLocalConfig();
                String notice = activity.getString(R.string.hk_miniapp_synced, added);
                completion.complete(buildScreen(readMiniapps(), notice, ""));
            });
        });
    }

    // ------------------------------------------------------------------
    // File / directory import: host SAF picker + pick polling
    // ------------------------------------------------------------------

    @Override
    public void requestHkImportPick(String kind) {
        if (busy || !PICK_IDLE.equals(pickState)) return;
        if (!(activity instanceof C1ScreenActivity)) {
            // C0 engine: the Hk page never opens here, so there is
            // nothing to pick from. Complete silently via the poll state.
            return;
        }
        String pickKind = text(kind);
        if (!"file".equals(pickKind) && !"dir".equals(pickKind)) return;
        pickState = PICK_PICKING;
        if ("file".equals(pickKind)) {
            picker.pickFiles();
        } else {
            picker.pickDirectory();
        }
    }

    /**
     * HkImportPicker completion (main thread): the import already ran
     * on the picker's own thread; this is the native onImported
     * callback — notice + reload + warm-up — folded into the pick
     * state the Dart poll reads.
     */
    private void onHkImported(int added) {
        if (!PICK_PICKING.equals(pickState)) return;
        pickMessage = onImportedNotice(added);
        pickState = PICK_IDLE;
        pickEpoch++;
    }

    /** HkImportPicker cancel (main thread): native stays silent, so the pick message stays empty. */
    private void onHkPickCancelled() {
        if (!PICK_PICKING.equals(pickState)) return;
        pickMessage = "";
        pickState = PICK_IDLE;
        pickEpoch++;
    }

